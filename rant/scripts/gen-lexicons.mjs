#!/usr/bin/env node
/**
 * Generate `rant-core`'s lexicon tables from the ones `rite` already fetches.
 *
 * `rite/lexicon/data/*.json` is fetched and committed by
 * `.github/workflows/fetch-lexicons.yml` — AFINN-165, NRC Emotion, and a
 * SUBTLEX-US frequency baseline. This turns them into a Rust source file so the
 * analytic predicates need no I/O, which is the whole contract of `rant-core`.
 *
 *   node rant/scripts/gen-lexicons.mjs [--check]
 *
 * ## Why the encoding is odd
 *
 * The obvious `&[(&str, i8)]` costs ~24 bytes of *relocations* per entry before
 * any characters — 15k entries would add ~600KB to **both** wasm binaries, and
 * the browser one is 229KB gzipped today. So each table is one concatenated
 * blob plus a `&[u32]` offset array: no relocations, no init, binary search
 * straight over the blob. Measured at the bottom of this script; keep it
 * measured, because this file is the only thing standing between a good idea
 * and doubling the composer's download.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '../..');
const OUT = join(ROOT, 'rant/crates/rant-core/src/lexicon_data.rs');
const DATA = join(ROOT, 'rite/lexicon/data');

/** Anything outside this is not a word we can look up from a tokeniser. */
const CLEAN = /^[a-z][a-z'-]*$/;

/** The 10 NRC categories, as bit positions. Order is the wire format. */
const NRC_CATS = [
  'anger', 'anticipation', 'disgust', 'fear', 'joy',
  'negative', 'positive', 'sadness', 'surprise', 'trust',
];

/**
 * How many frequency entries to keep. SUBTLEX has 41,470; past the commonest
 * few thousand the interesting signal is simply "not in the list", so the tail
 * is all cost and no information.
 */
const FREQ_KEEP = 6000;

const read = (name) => {
  const p = join(DATA, `${name}.json`);
  if (!existsSync(p)) {
    console.error(`missing ${p} — run .github/workflows/fetch-lexicons.yml, or check out rite/`);
    process.exit(1);
  }
  return JSON.parse(readFileSync(p, 'utf8'));
};

/** word -> small integer, emitted as `word:value\n` in one sorted blob. */
function table(pairs) {
  const rows = [...pairs].filter(([w]) => CLEAN.test(w)).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  let blob = '';
  const offsets = [];
  for (const [w, v] of rows) {
    offsets.push(blob.length);
    blob += `${w}:${v}\n`;
  }
  offsets.push(blob.length); // sentinel, so entry i is [off[i], off[i+1])
  return { blob, offsets, count: rows.length };
}

const rustBlob = (s) =>
  // Escape only what a Rust string literal cannot hold raw. The data is ASCII
  // after CLEAN, so this stays a byte-for-byte round trip.
  '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"';

const rustOffsets = (o) => {
  const lines = [];
  for (let i = 0; i < o.length; i += 20) lines.push('    ' + o.slice(i, i + 20).join(', ') + ',');
  return lines.join('\n');
};

// ── AFINN: valence, -5..5 ────────────────────────────────────────────────────
const afinn = table(Object.entries(read('afinn')).map(([w, v]) => [w, Math.max(-5, Math.min(5, v | 0))]));

// ── NRC: a 10-bit category mask ──────────────────────────────────────────────
const nrc = table(
  Object.entries(read('nrc')).map(([w, cats]) => {
    let mask = 0;
    for (const c of cats) {
      const i = NRC_CATS.indexOf(c);
      if (i >= 0) mask |= 1 << i;
    }
    return [w, mask];
  }).filter(([, m]) => m !== 0),
);

// ── SUBTLEX: log-bucketed commonness, 0 (rarest kept) .. 255 (commonest) ─────
const freqRaw = Object.entries(read('baseline'))
  .filter(([w]) => CLEAN.test(w))
  .sort(([, a], [, b]) => b - a)
  .slice(0, FREQ_KEEP);
const logs = freqRaw.map(([, v]) => Math.log10(Math.max(v, 0.01)));
const lo = Math.min(...logs);
const hi = Math.max(...logs);
const freq = table(
  freqRaw.map(([w, v], i) => [w, Math.round(((logs[i] - lo) / (hi - lo || 1)) * 255)]),
);

const src = `//! Lexicon tables — GENERATED by \`rant/scripts/gen-lexicons.mjs\`. Do not edit.
//!
//! Source data: \`rite/lexicon/data/*.json\`, fetched and committed by
//! \`.github/workflows/fetch-lexicons.yml\`. Regenerate with:
//!
//! \`\`\`sh
//! node rant/scripts/gen-lexicons.mjs
//! \`\`\`
//!
//! Each table is one sorted \`word:value\\n\` blob plus a \`&[u32]\` offset array,
//! rather than \`&[(&str, i8)]\`: the tuple form costs ~24 bytes of relocations
//! per entry in **both** wasm binaries, and the browser module is small enough
//! that it would notice. Look ups binary-search the offsets directly.
//!
//! | table | entries | licence |
//! |---|---|---|
//! | \`AFINN\` | ${afinn.count} | AFINN-165, ODbL |
//! | \`NRC\` | ${nrc.count} | NRC Emotion Lexicon, free for research/education |
//! | \`FREQ\` | ${freq.count} | SUBTLEX-US, CC BY-NC-ND — commonest ${FREQ_KEEP} only |

/// NRC categories, by bit position. The order is the encoding.
pub const NRC_CATS: [&str; 10] = [
${NRC_CATS.map((c) => `    "${c}",`).join('\n')}
];

pub static AFINN_BLOB: &str = ${rustBlob(afinn.blob)};
pub static AFINN_OFF: &[u32] = &[
${rustOffsets(afinn.offsets)}
];

pub static NRC_BLOB: &str = ${rustBlob(nrc.blob)};
pub static NRC_OFF: &[u32] = &[
${rustOffsets(nrc.offsets)}
];

pub static FREQ_BLOB: &str = ${rustBlob(freq.blob)};
pub static FREQ_OFF: &[u32] = &[
${rustOffsets(freq.offsets)}
];
`;

if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== src) {
    console.error('lexicon_data.rs is stale — run: node rant/scripts/gen-lexicons.mjs');
    process.exit(1);
  }
  console.log('lexicon_data.rs is current');
  process.exit(0);
}

writeFileSync(OUT, src);
const payload = afinn.blob.length + nrc.blob.length + freq.blob.length;
const offsets = (afinn.offsets.length + nrc.offsets.length + freq.offsets.length) * 4;
console.log(`wrote ${OUT}`);
console.log(`  afinn ${afinn.count}  nrc ${nrc.count}  freq ${freq.count}`);
console.log(`  blobs ${(payload / 1024).toFixed(1)} KB + offsets ${(offsets / 1024).toFixed(1)} KB`);
console.log(`  source ${(src.length / 1024).toFixed(1)} KB, gzipped ${(gzipSync(src).length / 1024).toFixed(1)} KB`);
