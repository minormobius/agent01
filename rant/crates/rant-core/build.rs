//! Compile `rant/posts/*.md` into the binary.
//!
//! The house publication's posts are text files in the repo, and the promise is
//! that serving one costs a parse and nothing else — no KV round trip, no
//! bundle fetch, no cold-start read. `include_str!` is how that promise is kept:
//! the bytes are in the wasm module, so a request for a post is a slice of
//! already-resident memory.
//!
//! Adding a post is `git add rant/posts/whatever.md`. The deploy workflow does
//! the rest.

use std::{env, fs, path::PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    // crates/rant-core → rant/
    let posts_dir = manifest.join("../../posts").canonicalize().unwrap_or_else(|_| manifest.join("../../posts"));

    println!("cargo:rerun-if-changed={}", posts_dir.display());

    let mut files: Vec<(String, PathBuf)> = Vec::new();
    if let Ok(entries) = fs::read_dir(&posts_dir) {
        for e in entries.flatten() {
            let path = e.path();
            if path.extension().and_then(|x| x.to_str()) != Some("md") {
                continue;
            }
            let Some(stem) = path.file_stem().and_then(|s| s.to_str()) else { continue };
            println!("cargo:rerun-if-changed={}", path.display());
            files.push((stem.to_string(), path));
        }
    }
    // Deterministic order in, deterministic build out. The runtime sorts by
    // date anyway, but a stable array keeps the wasm hash reproducible.
    files.sort_by(|a, b| a.0.cmp(&b.0));

    let mut out = String::from(
        "/// (slug, source) for every file in `rant/posts/`, generated by build.rs.\n\
         pub const POSTS: &[(&str, &str)] = &[\n",
    );
    for (stem, path) in &files {
        out.push_str(&format!(
            "    ({:?}, include_str!({:?})),\n",
            stem,
            path.to_string_lossy().replace('\\', "/")
        ));
    }
    out.push_str("];\n");

    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("house_posts.rs");
    fs::write(&dest, out).expect("write house_posts.rs");
}
