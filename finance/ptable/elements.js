// finance/ptable/elements.js — the research dataset behind fin.mino.mobi.
//
// One record per element. Hand-assembled; NOT generated. See METHOD.md for the
// attribution rules, the sources, and — importantly — what these numbers are
// not. Short version:
//
//   prod × price = up        upstream, the wellhead/minehead value of a year's
//                            world production at the first marketable form.
//                            Mostly USGS Mineral Commodity Summaries 2026.
//   mid                      the market for the form the element is actually
//                            traded and used in (S is sold as H₂SO₄, N as NH₃,
//                            Ti as TiO₂ pigment, Na as NaOH/Na₂CO₃ …).
//   down                     annual revenue of the FIRST-ORDER product markets
//                            that cannot be made without it. Deliberately one
//                            hop, not a GDP attribution. Estimated.
//   lev = down / up          the leverage ratio. This is the research output.
//
// conf is the honesty field and it is load-bearing:
//   high — up is a sourced USGS/industry figure and down is a measured market
//   med  — up sourced, down is a reasoned estimate over published market sizes
//   low  — both are order-of-magnitude; treat the exponent, not the mantissa
//   nil  — no extraction economy exists (synthetics, research-only nuclides)
//
// gate: true marks a chokepoint — an element whose upstream value is trivial
// next to the output it gates. These are the interesting ones.
//
// basis matters: prod and price are always on the SAME basis, named in `basis`,
// so prod × price is a real number and not a units error. Element content and
// compound content are not interchangeable and mixing them is the single
// easiest way to publish a wrong figure here.

