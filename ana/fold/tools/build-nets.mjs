// Writes js/nets-data.js: the tesseract's 261 nets (from fold.js `nets()`: 82,944 spanning trees unfolded, grouped by
// shape up to congruence). ~30 s. node ana/fold/tools/build-nets.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { nets, canonicalCubes } from '../js/fold.js';
const N = nets();
const rows = N.list.map((n) => ({ parent: n.parent, cubes: n.cubes, run: n.run, trees: n.trees, chiral: canonicalCubes(n.cubes, false) !== canonicalCubes(n.cubes.map((c) => [-c[0], c[1], c[2]]), false) }));
writeFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'js', 'nets-data.js'),
  `// GENERATED by tools/build-nets.mjs: the tesseract's ${rows.length} nets (Turney, 1984), from its ${N.trees} spanning trees.\n` +
  `// parent: the hinge tree (cell → its parent, root 7 = −w); cubes: the flat net's cube centres; run: the longest row;\n// trees: how many spanning trees give this shape; chiral: whether its mirror image is a different net.\n` +
  `export const NETS = ${JSON.stringify(rows)};\n`);
console.log(`${rows.length} nets, ${rows.filter((r) => r.chiral).length} chiral, from ${N.trees} trees`);
