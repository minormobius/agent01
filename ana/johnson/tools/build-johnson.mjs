// Builds js/johnson-data.js: the 92 Johnson solids, unit edge, centred, with their faces.
//
// Source: David McCooey's Visual Polyhedra (dmccooey.com/polyhedra/JohnsonPage1–5.html), whose coordinates for the
// Johnson solids were gathered by Loïs Mignard-Debise. The pages carry each solid's constants, vertices and faces
// inline. Nothing is taken on trust: test/johnson.selftest.mjs re-derives every face from a convex hull of the
// vertices alone and checks unit edges, planar regular faces and convexity.
//
//   node ana/johnson/tools/build-johnson.mjs [--cache DIR]     (fetches the five pages unless DIR holds page1..5.html)
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const ci = process.argv.indexOf('--cache'), cache = ci > 0 ? process.argv[ci + 1] : null;
async function page(i) {
  if (cache && existsSync(path.join(cache, `page${i}.html`))) return readFileSync(path.join(cache, `page${i}.html`), 'utf8');
  const r = await fetch(`https://dmccooey.com/polyhedra/JohnsonPage${i}.html`);
  if (!r.ok) throw new Error(`page ${i}: ${r.status}`);
  return r.text();
}
const solids = [];
for (let i = 1; i <= 5; i++) {
  const html = await page(i);
  // each solid: a miniConvex DIV with Constants, Vertices, Faces, then a link with its name and (Jn)
  const re = /class=Constants value="([^"]*)">[\s\S]*?class=Vertices value="([^"]*)">\s*<INPUT type=hidden class=Faces value="([^"]*)">[\s\S]*?<A href=([A-Za-z0-9]+)\.html>([^<]+)<\/A>[\s\S]*?\(J(\d+)\)/g;
  let m;
  while ((m = re.exec(html))) {
    const C = m[1].split(',').map((s) => s.trim()).filter(Boolean).map(Number);
    const val = (t) => { t = t.trim(); const neg = t.startsWith('-'); if (neg) t = t.slice(1); const v = t.startsWith('C') ? C[+t.slice(1)] : Number(t); if (!Number.isFinite(v)) throw new Error(`J${m[6]}: ${t}`); return neg ? -v : v; };
    const V = m[2].split(',').map((s) => s.trim()).filter(Boolean).map((s) => s.split(/\s+/).map(val));
    const F = m[3].split('#').map((s) => s.replace(/^,/, '').trim()).filter(Boolean).map((s) => s.split(/\s+/).map(Number));
    solids.push({ j: +m[6], name: m[5].trim(), file: m[4], V, F });
  }
}
solids.sort((a, b) => a.j - b.j);
if (solids.length !== 92 || solids.some((s, i) => s.j !== i + 1)) throw new Error(`parsed ${solids.length} solids: ${solids.map((s) => s.j).join(' ')}`);
// unit edge, centred on the vertex centroid
for (const s of solids) {
  let e = Infinity;
  for (const f of s.F) for (let i = 0; i < f.length; i++) { const a = s.V[f[i]], b = s.V[f[(i + 1) % f.length]]; e = Math.min(e, Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2])); }
  const c = [0, 1, 2].map((k) => s.V.reduce((t, v) => t + v[k], 0) / s.V.length);
  s.V = s.V.map((v) => v.map((x, k) => +((x - c[k]) / e).toFixed(12)));
}
// the snub dodecahedron (laevo): the one solid with 92 faces, one seat for each (the "seat" mode). Its own text file.
async function snubText() {
  if (cache && existsSync(path.join(cache, 'LsnubDodecahedron.txt'))) return readFileSync(path.join(cache, 'LsnubDodecahedron.txt'), 'utf8');
  const r = await fetch('https://dmccooey.com/polyhedra/LsnubDodecahedron.txt');
  if (!r.ok) throw new Error(`snub dodecahedron: ${r.status}`);
  return r.text();
}
const txt = await snubText(), C = {};
for (const m of txt.matchAll(/^C(\d+)\s*=\s*([-0-9.]+)\s*$/gm)) C[+m[1]] = Number(m[2]);
const tok = (t) => { t = t.trim(); const neg = t.startsWith('-'); if (neg) t = t.slice(1); const v = t.startsWith('C') ? C[+t.slice(1)] : Number(t); if (!Number.isFinite(v)) throw new Error(`snub: ${t}`); return neg ? -v : v; };
const SV = [...txt.matchAll(/^V\d+\s*=\s*\(([^)]*)\)/gm)].map((m) => m[1].split(',').map(tok));
const SF = [...txt.matchAll(/^\{([^}]*)\}/gm)].map((m) => m[1].split(',').map((x) => +x.trim()));
if (SV.length !== 60 || SF.length !== 92) throw new Error(`snub: ${SV.length} vertices, ${SF.length} faces`);
{ const f = SF[0], a = SV[f[0]], b = SV[f[1]], e = Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2]); for (let i = 0; i < SV.length; i++) SV[i] = SV[i].map((x) => +(x / e).toFixed(12)); }
const out = `// GENERATED by tools/build-johnson.mjs: do not edit. The 92 Johnson solids, unit edge, centred.
// Coordinates: David McCooey's Visual Polyhedra (dmccooey.com/polyhedra), gathered by Loïs Mignard-Debise; checked by
// test/johnson.selftest.mjs (convex hull, unit edges, planar regular faces).
export const JOHNSON = ${JSON.stringify(solids.map(({ j, name, V, F }) => ({ j, name, V, F })))};
// the snub dodecahedron (laevo), unit edge: 92 faces, 12 pentagons and 80 triangles
export const SNUB_DODECAHEDRON = ${JSON.stringify({ V: SV, F: SF })};
`;
writeFileSync(path.join(here, '..', 'js', 'johnson-data.js'), out);
console.log(`wrote ${solids.length} solids, ${solids.reduce((t, s) => t + s.V.length, 0)} vertices, ${(out.length / 1024).toFixed(0)} KB`);
