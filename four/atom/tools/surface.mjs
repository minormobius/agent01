/* The photosphere's atomic data, baked: bound–free cross-sections of every hydrogen level to principal number NMAX and of
   hydrogen-like helium (Z = 2) to 4, in both worlds, from atom/js/photo.js (the book's dipole rate by detailed balance),
   on a log grid in photon energy from each threshold up; and the H⁻ binding from atom/tools/hminus.mjs. Writes
   **generated** atom/js/surfacedata.js, which atom/js/surface.js reads.
     node four/atom/tools/surface.mjs bake        (~2–4 min) */
import { writeFileSync } from "node:fs";
import * as P from "../js/photo.js";
import { hminus, photodetach } from "./hminus.mjs";

const NMAX = 8, NHE = 4, NE = 40, EMAX_EV = 600;
function levels(d, Z, nmax) {
  const out = [];
  for (let N = 1; N <= nmax; N++) for (let l = 0; l < N; l++) { const nr = N - l - 1, E = P.levelE(d, Z, nr, l);
    const grid = Array.from({ length: NE }, (_, i) => -E * (EMAX_EV / (-E * P.HARTREE_EV)) ** (i / (NE - 1)) * (1 + (i === 0 ? 1e-4 : 0)));
    const sig = grid.map((w) => P.sigmaBF(d, Z, nr, l, w)); // a₀^(d−1)
    out.push({ N, l, nr, E_eV: E * P.HARTREE_EV, g: 2 * P.harmDim(d, l), w_eV: grid.map((w) => +(w * P.HARTREE_EV).toPrecision(6)), sigma: sig.map((s) => +s.toPrecision(5)) }); }
  return out;
}
if (process.argv[2] === "bake") {
  const t0 = Date.now(), out = { about: "generated by four/atom/tools/surface.mjs bake: bound–free cross-sections (a0^(d−1)) of hydrogen (Z 1, principal number to 8) and hydrogen-like helium (Z 2, to 4) per level, against photon energy (eV), from atom/js/photo.js; g counts spin.", worlds: {} };
  for (const d of [3, 4]) { out.worlds[d] = { H: levels(d, 1, NMAX), HeII: levels(d, 2, NHE) };
    // H⁻: the s-wave CI state and its photodetachment (ours moved to the measured 0.754 eV threshold; 4D its own)
    const R = hminus(d, { M: 20, lam: 0.25, N: 1600 }), aff = d === 3 ? 0.754 / P.HARTREE_EV : R.EH_exact - R.E;
    const wg = Array.from({ length: 60 }, (_, i) => aff * (1 + 1e-3) * (3000) ** (i / 59)), sg = photodetach(d, R, wg, { affinity: aff, rmax: 850 });
    out.worlds[d].Hminus = { affinity_eV: aff * P.HARTREE_EV, affinityCI_eV: (R.EH_exact - R.E) * P.HARTREE_EV, w_eV: wg.map((w) => +(w * P.HARTREE_EV).toPrecision(6)), sigma: sg.map((s) => +s.toPrecision(5)) }; console.log(`d ${d}: ${out.worlds[d].H.length} H levels, ${out.worlds[d].HeII.length} He⁺ levels (${((Date.now() - t0) / 1000).toFixed(0)} s)`); }
  writeFileSync(new URL("../js/surfacedata.js", import.meta.url), `// generated by four/atom/tools/surface.mjs bake — bound–free cross-sections for the photosphere (atom/js/surface.js)\nexport const SURFACE = ${JSON.stringify(out)};\n`);
  console.log("wrote atom/js/surfacedata.js");
}
