/* The site's term-corrected table: bakes **generated** js/terms.js from the term-corrected search's results (paper 1's
   data/termtable.json, collected from tools/termtable.mjs on the runner). js/tablec.js lays it over js/table.js, and
   the site's pages read the table from there, so they show what paper 1's main table shows: the configurations, total
   energies and first ionizations with Hund's first rule resolved where it fails in four dimensions, and the
   configurations the wider search found (element 82). js/table.js itself stays the bake (paper 1's supplement S1).
     node four/atom/tools/terms.mjs bake [path/to/termtable.json]
   Where a configuration differs from the bake's, the element is solved again here in it, for its orbitals and its
   radial density on RPLOT, exactly as tools/bake.mjs samples them. */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { scf, subshells, R, N, H } from "../js/atom.js";
import { TABLE, RPLOT } from "../js/table.js";
import { SOLVER } from "./bake.mjs";

const here = path.dirname(fileURLToPath(import.meta.url)), [cmd, src = path.join(here, "../../papers/p1/data/termtable.json")] = process.argv.slice(2);
if (cmd !== "bake") { console.log("usage: terms.mjs bake [termtable.json]"); process.exit(0); }
const sh = subshells(4), occOf = (cfg) => { const o = sh.map(() => 0); for (const t of cfg.split(" ")) { const m = t.match(/^(\d+[a-z])(\d+)$/); o[sh.findIndex((x) => x.name === m[1])] = +m[2]; } return o; };
const rows = JSON.parse(readFileSync(src, "utf8")).rows, out = {};
for (const r of rows) {
  const bake = TABLE[4][r.Z - 1], e = { config: r.config, E: r.E_hartree, ion: r.ion_hartree, top: r.outermost, hund: r.hund_correction_eV };
  if (r.config !== bake.config) {
    const occ = occOf(r.config), g = scf(r.Z, occ, 4, { iters: 400, ...SOLVER }); if (!g.converged) throw new Error(`element ${r.Z}: ${r.config} didn't settle`);
    const live = sh.map((s, i) => i).filter((i) => occ[i] > 0);
    e.orb = live.map((i) => { let rm = 0, r2 = 0; for (let j = 0; j < N; j++) { rm += g.qs[i][j] * R[j]; r2 += g.qs[i][j] * R[j] * R[j]; } return { s: sh[i].name, o: occ[i], e: +g.es[i].toFixed(5), r: +rm.toFixed(4), r2: +r2.toFixed(4) }; });
    e.dens = Array.from(RPLOT, (rr) => { const x = Math.log(rr / R[0]) / H, j = Math.min(N - 2, Math.max(0, Math.floor(x))), f = x - j; let s = 0; for (const i of live) s += occ[i] * (g.qs[i][j] * (1 - f) + g.qs[i][j + 1] * f); return +(s / (H * rr)).toPrecision(3); });
  }
  if (e.config === bake.config && Math.abs(e.E - bake.E) < 1e-6 && Math.abs((e.ion ?? 0) - bake.ion) < 1e-6) continue; // nothing to lay over
  out[r.Z] = e;
}
const text = `/* GENERATED by tools/terms.mjs bake from paper 1's data/termtable.json — do not edit. The 4D table's term-corrected
   entries (js/tablec.js lays them over js/table.js): configuration, total energy and first ionization (hartree) with
   Hund's first rule resolved; hund, the ground configuration's correction (eV); orb and dens where the configuration changed. */
export const TERMS = ${JSON.stringify(out)};\n`;
writeFileSync(path.join(here, "../js/terms.js"), text);
console.log(`js/terms.js: ${Object.keys(out).length} elements (${Object.values(out).filter((e) => e.orb).length} with a new configuration)`);
