/* Bakes js/orbitsdata.js for the stars chapter's orbits: a nudged circular orbit under each law, the 4D star's outside
   correction and the precession it causes (measured against the formula), and two planets side by side in one plane
   or in planes turned apart, run for thousands of orbits.
     node four/atom/tools/orbits.mjs        # about half a minute */
import { writeFileSync } from "node:fs";
import * as O from "../js/orbits.js";
import * as S from "../js/stars.js";

const t0 = Date.now();
const nudge = { pinned: O.nudged(1, 4, 12), gauss: O.nudged(2, 4, 12) };
const st = S.polytrope("pinned4", 2, { N: 300 }), dr = 1 / st.r.length, ms = st.rho.map((p, i) => p * 2 * Math.PI ** 2 * st.r[i] ** 3 * dr), star = O.starPotential(st.r, ms);
const precession = [[3, 0.2], [6, 0.3], [12, 0.1]].map(([p, e]) => ({ p, e, measured: +O.measurePrecession(star.slope, p, e).toExponential(4), formula: +O.precessionPerOrbit(star.r2, p).toExponential(4) }));
const planets = [];
for (const a2 of [1.7, 1.3, 1.2, 1.1]) for (const th of [0, 90]) planets.push(O.twoPlanets(a2, th, { orbits: 3000 }));
for (const [a2, th] of [[1.0, 90], [1.05, 60], [1.05, 30]]) planets.push(O.twoPlanets(a2, th, { orbits: 3000 }));
const turning = O.twoPlanets(1.05, 60, { orbits: 3000, sample: 20 });
const moons = Object.fromEntries(Object.entries(O.MOON_PLANES).map(([k, [u, v]]) => [k, O.moonRun(u, v)]));
console.log("moons", JSON.stringify(moons));
const out = { nudge, star: { r2: +star.r2.toFixed(4) }, precession, planets: planets.map(({ series, ...r }) => r), turning: turning.series, moons };
writeFileSync(new URL("../js/orbitsdata.js", import.meta.url), `/* Generated by tools/orbits.mjs from js/orbits.js; do not edit. G = 1, the star's mass 1, planet 1's orbit radius 1.
   nudge: [orbits, r] for a circular orbit given 1% more speed, under pinned 1/r and Gauss's 1/r² (4D). star: the pinned
   4D star's mass-weighted ⟨r²⟩ in its radii. precession: per orbit (rad), measured by integration in that star's own
   potential and by −(3π/4)⟨r²⟩/p². planets: two Jupiter-mass planets, radii 1 and a2, planes thDeg apart (90: completely
   orthogonal), 3000 orbits: largest eccentricity, closest approach, planet 1's largest swing out of its first plane,
   and the orbit it was thrown out on, if it was. turning: [orbit, eccentricity, the planes' angle, planet 1's swing].
   moons: a moon at about a third of its Jupiter-mass planet's reach, in five planes (js/orbits.js MOON_PLANES), for
   150 of the planet's orbits: its largest eccentricity, how far its plane turned, the orbit it was lost on. */
export const ORBITS = ${JSON.stringify(out)};
`);
console.log(`baked in ${((Date.now() - t0) / 1000).toFixed(0)} s`); console.log(JSON.stringify(precession)); console.log(planets.map((p) => `${p.a2}/${p.thDeg}°: emax ${p.emax} dmin ${p.dmin} wander ${p.wander} lost ${p.lost}`).join("\n"));
console.log("gauss nudge end r", nudge.gauss.at(-1), "pinned max r", Math.max(...nudge.pinned.map((q) => q[1])), "turning", JSON.stringify(turning.series.slice(0, 3)), turning.series.length);
