/* The audit's F01, measured: before the fix, js/gauss.js reported an exhausted iteration budget as convergence, so every
   saved Hartree–Fock result's "ok" said nothing. This re-runs saved pair energies with the fixed solver (an explicit
   convergence decision: energy change under 10⁻⁹ and the commutator FPS − SPF under 10⁻⁵, in at most 200 iterations)
   and records, per point, whether it converges, in how many iterations, and how far its energy moves from the saved one.
     node four/atom/tools/reconverge.mjs run <set> [--shard i/m]   one set's points (runner)
     node four/atom/tools/reconverge.mjs bake                      → js/reconverge.js
   sets: ff3, ff4, ff49 (js/ffdata.js: the force fields' pairs), liq3, liq4, liq49 (js/liquidff.js: the liquid probes),
         census (js/census.js: each hydride's hydrogen-bonded pair at its minimum)
   Cache $TMPDIR/atom4-reconverge/<set>_<k>.json */
import { writeFileSync, readFileSync, mkdirSync, existsSync, readdirSync } from "node:fs";
import path from "node:path";
import os from "node:os";
import { pairEnergy, dimerAtoms } from "./census.mjs";

const DIR = path.join(process.env.TMPDIR || os.tmpdir(), "atom4-reconverge"); mkdirSync(DIR, { recursive: true });
const here = path.dirname(new URL(import.meta.url).pathname), [cmd, set] = process.argv.slice(2), KCAL = 627.5095;
const ZOF = { 3: 8, 4: 10, 4.9: 9 };
/* each set's points: { k, d, A, B (atom lists), E (saved, hartree) } */
async function points(set) {
  if (set.startsWith("ff") || set.startsWith("liq")) {
    const key = { 3: "3", 4: "4", 49: "4.9" }[set.replace(/^(ff|liq)/, "")], src = set.startsWith("ff") ? (await import("../js/ffdata.js")).FFDATA : (await import("../js/liquidff.js")).LIQUIDFF;
    const d = key === "3" ? 3 : 4, Z = src[key].Z ?? ZOF[key];
    return src[key].points.map((p) => ({ k: p.k, d, E: p.E, A: p.A.map((at, i) => ({ Z: i ? 1 : Z, at })), B: p.B.map((at, i) => ({ Z: i ? 1 : Z, at })) }));
  }
  if (set === "census") {
    const { CENSUS } = await import("../js/census.js"), out = [];
    for (const d of [3, 4]) for (const m of CENSUS[d]) if (m.dimer?.ok) { const [A, B] = dimerAtoms(m, d, m.dimer.RXX, m.dimer.beta); out.push({ k: d * 100 + m.Z, d, E: m.dimer.E, A, B }); }
    return out;
  }
  throw new Error(`no set ${set}`);
}
if (cmd === "run") {
  const sh = process.argv.find((a) => a.includes("/") && /^\d+\/\d+$/.test(a)), [si, sm] = sh ? sh.split("/").map(Number) : [0, 1];
  const pts = await points(set);
  for (const [n, p] of pts.entries()) {
    if (n % sm !== si) continue; const f = path.join(DIR, `${set}_${p.k}.json`); if (existsSync(f)) continue;
    const t0 = Date.now(), e = pairEnergy(p.A, p.B, p.d);
    writeFileSync(f, JSON.stringify({ set, k: p.k, d: p.d, saved: p.E, E: e.E, ok: e.ok, iterations: e.iterations }));
    console.log(`${set} ${p.k}: ${e.ok ? "converged" : "NOT CONVERGED"} in ${e.iterations}, ${(e.E * KCAL).toFixed(4)} kcal/mol (saved ${(p.E * KCAL).toFixed(4)}, moved ${((e.E - p.E) * KCAL).toExponential(2)}), ${((Date.now() - t0) / 1000).toFixed(0)} s`);
  }
} else if (cmd === "bake") {
  const rows = readdirSync(DIR).filter((f) => f.endsWith(".json")).map((f) => JSON.parse(readFileSync(path.join(DIR, f), "utf8"))), out = {};
  for (const r of rows) { const s = (out[r.set] ??= { n: 0, failed: [], maxIter: 0, maxMove: 0 }); s.n++; s.maxIter = Math.max(s.maxIter, r.iterations); const mv = Math.abs(r.E - r.saved) * KCAL; s.maxMove = Math.max(s.maxMove, mv); if (!r.ok) s.failed.push({ k: r.k, iterations: r.iterations, moved: +mv.toFixed(4) }); }
  for (const [k, s] of Object.entries(out)) { s.maxMove = +s.maxMove.toExponential(2); console.log(`${k}: ${s.n} points, ${s.failed.length} not converged, at most ${s.maxIter} iterations, energies moved at most ${s.maxMove} kcal/mol`); }
  writeFileSync(path.join(here, "../js/reconverge.js"), `/* Generated by tools/reconverge.mjs bake; do not edit. The audit's F01 measured: saved Hartree–Fock pair energies re-run
   with the fixed convergence test. Per set: points re-run, those that didn't converge (k, iterations, kcal/mol moved),
   the most iterations any took, and the largest move from the saved energy (kcal/mol). */
export const RECONVERGE = ${JSON.stringify(out)};
`);
} else console.error("usage: reconverge.mjs run <ff3|ff4|ff49|liq3|liq4|liq49|census> [i/m] | bake");
