/* The compute ledger, for the methods appendix: every run on the compute runner, read from the orphan branch
   atom4-data (each run's run.json and each group's status.json) and from the queue file at the run's own commit (why it
   was run), into js/ledger.js. Run it in a clone that has fetched atom4-data:
     git fetch origin atom4-data && node four/atom/tools/ledger.mjs */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url)), REF = "origin/atom4-data";
const git = (...a) => execFileSync("git", a, { encoding: "utf8", maxBuffer: 1 << 26 });
const ls = (p) => git("ls-tree", "--name-only", `${REF}:${p}`).split("\n").filter(Boolean);
const show = (p) => { try { return git("show", `${REF}:${p}`); } catch { return null; } };

const runs = [];
for (const name of ls("runs")) {
  if (name.startsWith(".")) continue;
  const run = JSON.parse(show(`runs/${name}/run.json`) || "null"); if (!run) continue;
  let queue = null; try { queue = JSON.parse(git("show", `${run.code}:.github/compute/atom4.json`)); } catch {}
  const groups = [];
  for (const g of ls(`runs/${name}`)) {
    const st = show(`runs/${name}/${g}/status.json`); if (!st) continue;
    const s = JSON.parse(st).status || [];
    groups.push({ name: g, cmds: s.length, seconds: s.reduce((t, c) => t + (c.seconds || 0), 0), wall: Math.max(0, ...s.map((c) => c.seconds || 0)), cut: s.filter((c) => c.cut).length, failed: s.filter((c) => !c.cut && c.code !== 0).length });
  }
  const sum = (k) => groups.reduce((t, g) => t + g[k], 0);
  runs.push({ name, at: run.at, result: run.result, code: run.code.slice(0, 9), log: run.log, why: queue && queue.run === name ? queue.why : null,
    groups: groups.length, cmds: sum("cmds"), cpuHours: +(sum("seconds") / 3600).toFixed(2), wallHours: +(Math.max(0, ...groups.map((g) => g.wall)) / 3600).toFixed(2), cut: sum("cut"), failed: sum("failed") });
}
runs.sort((a, b) => a.at.localeCompare(b.at));
const total = { runs: runs.length, cmds: runs.reduce((t, r) => t + r.cmds, 0), cpuHours: +runs.reduce((t, r) => t + r.cpuHours, 0).toFixed(1) };
writeFileSync(path.join(here, "../js/ledger.js"), `/* Generated by tools/ledger.mjs from the atom4-data branch; do not edit. Every run on the compute runner: when it
   finished, its result, the code commit it ran, its Actions log, why it was queued, how many runners (groups) and
   commands, the command-hours it used (one command per core), the longest command's hours, and how many commands were
   cut at the deadline or failed. */
export const LEDGER = ${JSON.stringify({ total, runs })};
`);
console.log(`ledger: ${total.runs} runs, ${total.cmds} commands, ${total.cpuHours} command-hours`); for (const r of runs) console.log(`  ${r.name}: ${r.cmds} cmds, ${r.cpuHours} h, wall ${r.wallHours} h, ${r.result}${r.cut ? `, ${r.cut} cut` : ""}${r.why ? "" : " (no why)"}`);
