/* Every 4D element in profile, for the big table's detail panel (../../table/): each atom re-solved in the site's ground
   configuration (js/tablec.js, paper 1's main table) with each subshell's radial function kept. The bake keeps only the
   total density, which can't say which subshell is which, and the orbital on the 3-sphere needs the radial function.
   Each re-solve must give back the table's energy to 10⁻⁴ hartree (less its Hund correction, which is a term energy,
   not part of the field), or the tool stops: the profile is the table's atom, not a new one.
     node four/atom/tools/profiles.mjs bake    → table/profiles.json (GENERATED, ~3 min; re-run after a bake or terms.mjs)
   Stored per subshell: P(r) = r³R², the radial probability per bohr of one electron, on r from 0.005 to 50 bohr at 20
   points a decade, as integers 0–999 of the subshell's own peak (`k`), so the file stays small. */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { scf, subshells, R, N, H } from "../js/atom.js";
import { TABLE } from "../js/tablec.js";
import { SOLVER } from "./bake.mjs";

const here = path.dirname(fileURLToPath(import.meta.url)), EV = 27.211386245988, SH = subshells(4);
export const RS = Array.from({ length: 81 }, (_, i) => +(0.005 * 10 ** (i / 20)).toPrecision(4));
const occOf = (config) => { const o = SH.map(() => 0); for (const t of config.split(" ")) { const m = t.match(/^(\d+[a-z])(\d+)$/); o[SH.findIndex((s) => s.name === m[1])] = +m[2]; } return o; };
const at = (q, r) => { const x = Math.log(r / R[0]) / H, j = Math.min(N - 2, Math.max(0, Math.floor(x))), u = x - j; return (q[j] * (1 - u) + q[j + 1] * u) / (H * r); };

if (process.argv[1] === fileURLToPath(import.meta.url) && process.argv[2] === "bake") {
  const atoms = [];
  for (const el of TABLE[4]) {
    const occ = occOf(el.config), g = scf(el.Z, occ, 4, { ...SOLVER, iters: 400 }), want = el.E - (el.hund ?? 0) / EV;
    if (!g.converged || Math.abs(g.E - want) > 1e-4) { console.error(`element ${el.Z}: re-solve E ${g.E} against the table's ${want} (converged ${g.converged})`); process.exit(1); }
    const sub = SH.map((s, i) => ({ s, i })).filter(({ i }) => occ[i] > 0).map(({ s, i }) => {
      const P = RS.map((r) => Math.max(0, at(g.qs[i], r))), k = Math.max(...P);
      return { n: s.name, l: s.l, occ: occ[i], e: +g.es[i].toFixed(4), k: +k.toPrecision(4), P: P.map((v) => Math.round((999 * v) / k)) };
    });
    atoms.push({ Z: el.Z, config: el.config, sub });
    if (el.Z % 10 === 0) console.log(`… ${el.Z}`);
  }
  writeFileSync(path.join(here, "../../table/profiles.json"), JSON.stringify({ about: "GENERATED by four/atom/tools/profiles.mjs bake from js/atom.js in js/tablec.js's configurations; do not edit. Per subshell: P(r) = r³R² for one electron per bohr, at r (bohr), as integers of k/999.", r: RS, atoms }) + "\n");
  console.log(`table/profiles.json: ${atoms.length} atoms`);
}
