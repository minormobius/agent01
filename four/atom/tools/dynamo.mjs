/* Kinematic dynamos, ours against 4D's (js/dynamo.js): for each flow, the fastest growth over the field's out-of-plane
   wavenumbers at each resistivity η (the flow's speed and its cells' size 1, so the magnetic Reynolds number Rm = 1/η),
   and the critical Rm where the fastest growth crosses zero.
     node four/atom/tools/dynamo.mjs scan <case>     one case: roberts3, planar3, roberts4, twohelix4, planar4 (cached)
     node four/atom/tools/dynamo.mjs bake            → js/dynamodata.js
   Grids: ours N = 32 (2% from N = 16 at Rm 10); 4D N = 16 (unchanged at N = 32). Cache $TMPDIR/atom4-dynamo */
import { writeFileSync, readFileSync, existsSync, mkdirSync } from "node:fs";
import path from "node:path";
import os from "node:os";
import { growth, FLOWS } from "../js/dynamo.js";

const here = path.dirname(new URL(import.meta.url).pathname), DIR = path.join(process.env.TMPDIR || os.tmpdir(), "atom4-dynamo"); mkdirSync(DIR, { recursive: true });
const ETAS = [1, 0.7, 0.5, 0.4, 0.3, 0.25, 0.2, 0.15, 0.1, 0.07];
const KS = [0.1, 0.2, 0.3, 0.45, 0.6, 0.8, 1, 1.25];
const CASES = {
  roberts3: { d: 3, flow: "roberts", N: 32, ks: KS.map((k) => [k, 0]) },
  planar3: { d: 3, flow: "planar", N: 32, ks: KS.map((k) => [k, 0]) },
  roberts4: { d: 4, flow: "roberts", N: 16, ks: [...KS.map((k) => [k, 0]), ...[0.3, 0.6, 1].flatMap((k) => [[k, 0.3], [k, 0.6], [0, k]])] },
  twohelix4: { d: 4, flow: "twohelix", N: 16, ks: [0, 0.3, 0.6, 0.9, 1.2].flatMap((a) => [0, 0.3, 0.6, 0.9, 1.2].map((b) => [a, b])).filter(([a, b]) => a || b) },
  planar4: { d: 4, flow: "planar", N: 16, ks: [...KS.map((k) => [k, 0]), [0.45, 0.45], [0, 0.45]] },
};
const [cmd, name] = process.argv.slice(2);
if (cmd === "scan") {
  const C = CASES[name], f = path.join(DIR, `${name}.json`), st = existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : { name, ...C, runs: [] }, t0 = Date.now();
  for (const eta of ETAS) for (const [kz, kw] of C.ks) {
    if (st.runs.some((r) => r.eta === eta && r.kz === kz && r.kw === kw)) continue;
    const g = growth({ d: C.d, flow: FLOWS[C.flow], kz, kw, eta, N: C.N, T: 40 });
    st.runs.push({ eta, kz, kw, rate: +g.rate.toFixed(5), settle: +g.settle.toExponential(1), energy: g.energy.map((e) => +e.toExponential(2)), planes: g.planes });
    writeFileSync(f, JSON.stringify(st));
  }
  for (const eta of ETAS) { const rs = st.runs.filter((r) => r.eta === eta), b = rs.reduce((x, y) => (y.rate > x.rate ? y : x)); console.log(`${name} η ${eta} (Rm ${(1 / eta).toFixed(1)}): fastest ${b.rate.toFixed(4)} at kz ${b.kz} kw ${b.kw}`); }
  console.log(`${((Date.now() - t0) / 1000).toFixed(0)} s`);
} else if (cmd === "bake") {
  const out = {};
  for (const n of Object.keys(CASES)) { const f = path.join(DIR, `${n}.json`); if (!existsSync(f)) continue; const st = JSON.parse(readFileSync(f, "utf8"));
    const best = ETAS.map((eta) => { const rs = st.runs.filter((r) => r.eta === eta); if (!rs.length) return null; const b = rs.reduce((x, y) => (y.rate > x.rate ? y : x)); return { eta, Rm: +(1 / eta).toFixed(3), rate: b.rate, kz: b.kz, kw: b.kw, energy: b.energy, planes: b.planes }; }).filter(Boolean);
    // the critical Rm: where the fastest growth crosses zero, linear in 1/η between the two points that straddle it
    let RmC = null; for (let i = 1; i < best.length; i++) { const a = best[i - 1], b = best[i]; if (a.rate < 0 && b.rate >= 0) { RmC = +(a.Rm + ((b.Rm - a.Rm) * -a.rate) / (b.rate - a.rate)).toFixed(2); break; } }
    out[n] = { d: st.d, flow: st.flow, N: st.N, best, RmC, runs: st.runs.map(({ energy, planes, ...r }) => r) };
  }
  writeFileSync(path.join(here, "../js/dynamodata.js"), `/* Generated by tools/dynamo.mjs bake; do not edit. Kinematic dynamos (js/dynamo.js): per case, at each resistivity
   η (Rm = 1/η) the fastest growth rate over the field's out-of-plane wavenumbers (kz, kw), where it occurs and its
   energy by plane; the critical Rm where that growth crosses zero (null if it never does in the range); every run. */
export const DYNAMO = ${JSON.stringify(out)};
`);
  for (const [n, v] of Object.entries(out)) console.log(`${n}: critical Rm ${v.RmC ?? "none in range"}; fastest at Rm ${v.best.at(-1).Rm}: ${v.best.at(-1).rate}`);
} else console.error("usage: dynamo.mjs scan <roberts3|planar3|roberts4|twohelix4|planar4> | bake");
