/* Correlation: what Hartree–Fock leaves out of a pair's binding. Every pair energy in the census and search chapters is
   Hartree–Fock, and on it Xater's and XH₃'s best pairs tie to a fraction of a kcal/mol, far inside what Hartree–Fock
   misses. This adds MP2 (js/gauss.js mp2: second order, cores frozen, counterpoise-corrected like the rest) at each
   best pair as the search left it (js/pairmin.js), so the geometry is Hartree–Fock's and only the energy changes.
     node four/atom/tools/correlation.mjs pair <key> [plus] [shift]   # one pair (keys as in tools/forcefield.mjs: 3, 3.7, 3.9,
                                     # 4, 4.9), in the book's basis or grown by plus (tools/census.mjs basisFor: D, d, p, f;
                                     # "book" for none), the second molecule moved shift bohr along the line between the
                                     # heavy atoms (a scan: does correlation want the pair closer or farther?)
     node four/atom/tools/correlation.mjs bake           # js/correlation.js from the cached results
   Each pair is cached in $TMPDIR/atom4-correlation/pair_<key>_<plus>[_s<shift>].json. For our pairs,
   tools/correlation-ref.py computes the same energies at the same geometry with PySCF in standard large bases
   (aug-cc-pVTZ, aug-cc-pVQZ) into tools/correlation-ref.json, committed: how much of the correlation's binding the
   book's basis catches. The bake carries both. */
import { writeFileSync, readFileSync, mkdirSync, existsSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { tmpdir } from "node:os";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url)), OUT = path.join(tmpdir(), "atom4-correlation"), KCAL = 627.509;
mkdirSync(OUT, { recursive: true });
const argv = process.argv.slice(2), mode = argv[0];

if (mode === "pair") {
  const key = argv[1], plus = argv[2] && argv[2] !== "book" ? argv[2] : "", shift = +(argv[3] ?? 0), file = path.join(OUT, `pair_${key}_${plus || "book"}${shift ? "_s" + shift : ""}.json`);
  if (existsSync(file)) { console.log("already done:", readFileSync(file, "utf8")); process.exit(0); }
  const { WORLDS } = await import("./forcefield.mjs"), { pairEnergy } = await import("./census.mjs"), { PAIRMIN } = await import("../js/pairmin.js");
  const w = WORLDS[key], pm = PAIRMIN[key].best, at = (M) => M.map((p, i) => ({ Z: i ? 1 : w.Z, at: p })), t0 = Date.now();
  const u = pm.B[0].map((v, i) => v - pm.A[0][i]), un = Math.hypot(...u), B = pm.B.map((p) => p.map((v, i) => v + (shift * u[i]) / un));
  const e = pairEnergy(at(pm.A), at(B), w.d, { mp2: true, plus }), s = (Date.now() - t0) / 1000;
  const r = { key, plus: plus || "book", shift, d: w.d, Z: w.Z, n: e.n, hf: e.E, E2: e.E2, os: e.os, ss: e.ss, pairmin: pm.E, ok: e.ok, seconds: s };
  writeFileSync(file, JSON.stringify(r));
  console.log(`${key} ${plus || "book"}${shift ? ` moved ${shift}` : ""}: Hartree–Fock ${(e.E * KCAL).toFixed(3)}, correlation (MP2) ${(e.E2 * KCAL).toFixed(3)}, so MP2 ${((e.E + e.E2) * KCAL).toFixed(3)} kcal/mol (${e.n} functions, ${s.toFixed(0)} s)`);
} else if (mode === "bake") {
  const out = {}, refs = JSON.parse(readFileSync(path.join(here, "correlation-ref.json"), "utf8"));
  for (const f of readdirSync(OUT).filter((f) => /^pair_.*\.json$/.test(f)).sort()) {
    const r = JSON.parse(readFileSync(path.join(OUT, f), "utf8"));
    const o = (out[r.key] ??= { d: r.d, Z: r.Z, bases: {}, ...(refs[r.key] ? { ref: refs[r.key] } : {}) });
    const row = { n: r.n, hf: +r.hf.toFixed(7), E2: +r.E2.toFixed(7), os: +r.os.toFixed(7), ss: +r.ss.toFixed(7), ok: r.ok };
    if (r.shift) ((o.scan ??= {})[r.plus] ??= {})[r.shift] = row; else o.bases[r.plus] = row;
  }
  writeFileSync(path.join(here, "../js/correlation.js"), `/* Generated by tools/correlation.mjs bake; do not edit. Per molecule key: its best pair (js/pairmin.js) re-scored with
   the correlation Hartree–Fock leaves out, MP2 with the cores frozen, counterpoise-corrected (hartree). Per basis (the
   book's, and grown: tools/census.mjs basisFor): n functions, the Hartree–Fock interaction hf, the correlation's share
   E2 and its opposite- and same-spin parts; scan: the same with the second molecule moved along the line between the
   heavy atoms, by basis and distance (bohr). For our pairs, ref: the same at the same geometry by PySCF in standard
   bases (tools/correlation-ref.py). */
export const CORRELATION = ${JSON.stringify(out)};
`);
  console.log("wrote js/correlation.js", JSON.stringify(out));
} else {
  console.error("modes: pair <key> | bake"); process.exit(1);
}
