/* Nebulae settling round a young star (js/nebula.js), for the runner: does a rotating cloud flatten into a disk?
     node four/atom/tools/nebula.mjs run <d> <a1> <a2> <N> <T> <seed> [eta] [sigma]
       one cloud: d dimensions, turning at rates a1 (xy) and a2 (zw), N particles, run to time T (the star's mass and
       the cloud's radius 1, so a circular orbit at the edge takes 2π). Saves its state every couple of minutes to
       $TMPDIR/atom4-nebula/<name>.json and resumes from it; the shape is sampled 80 times.
     node four/atom/tools/nebula.mjs bake
       every run in $TMPDIR/atom4-nebula into js/nebuladata.js: the shape over time, and a few hundred particles of the
       final state for drawing. */
import { writeFileSync, readFileSync, mkdirSync, existsSync, readdirSync, renameSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as NB from "../js/nebula.js";

const DIR = path.join(tmpdir(), "atom4-nebula"), here = path.dirname(fileURLToPath(import.meta.url));
const pack = (a) => Buffer.from(a.buffer, a.byteOffset, a.byteLength).toString("base64");
const unpack = (s, T) => { const b = Buffer.from(s, "base64"); return new T(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)); };
const save = (file, o) => { writeFileSync(file + ".part", JSON.stringify(o)); renameSync(file + ".part", file); };
const [mode, ...args] = process.argv.slice(2);

if (mode === "run") {
  const [d, a1, a2, N, T, seed] = args.slice(0, 6).map(Number), eta = +(args[6] ?? 0.5), sigma = +(args[7] ?? 0.1);
  const name = `d${d}_a${a1}_${a2}_n${N}_T${T}_s${seed}` + (args[6] ? `_e${eta}` : "") + (args[7] ? `_g${sigma}` : ""), file = path.join(DIR, name + ".json");
  mkdirSync(DIR, { recursive: true });
  const h = (24 / N) ** (1 / d), dt = 0.002, samples = 80, steps = Math.round(T / dt), each = Math.round(steps / samples), saveEvery = 120e3;
  let S, rec;
  if (existsSync(file)) { rec = JSON.parse(readFileSync(file, "utf8")); if (rec.done) { console.log(name, "already done"); process.exit(0); }
    S = { d, N, x: unpack(rec.x, Float64Array), v: unpack(rec.v, Float64Array), alive: unpack(rec.alive, Uint8Array), t: rec.t, accreted: rec.accreted, escaped: rec.escaped }; console.log(name, "resumes at t =", S.t); }
  else { S = NB.cloud({ d, N, a1, a2, f: 0.7, sigma, seed }); rec = { d, a1, a2, N, T, seed, eta, sigma, h, dt, series: [NB.shape(S)] }; }
  const record = (done) => save(file, { ...rec, t: S.t, accreted: S.accreted, escaped: S.escaped, x: pack(S.x), v: pack(S.v), alive: pack(S.alive), done });
  let last = Date.now(); const t0 = Date.now(), s0 = Math.round(S.t / dt);
  for (let s = s0; s < steps; s++) {
    NB.step(S, { dt, h, eta });
    if ((s + 1) % each === 0) { const sh = NB.shape(S); rec.series.push(sh); console.log(`t ${sh.t} alive ${sh.alive} axes ${sh.axes.join(" ")} align ${sh.plus} ${sh.minus ?? ""} ecc ${sh.ecc} (${((Date.now() - t0) / 1000).toFixed(0)} s)`); }
    if (Date.now() - last > saveEvery) { record(false); last = Date.now(); }
  }
  record(true); console.log(name, "done");
} else if (mode === "bake") {
  const runs = [];
  for (const f of readdirSync(DIR).filter((f) => f.endsWith(".json")).sort()) {
    const r = JSON.parse(readFileSync(path.join(DIR, f), "utf8")), x = unpack(r.x, Float64Array), v = unpack(r.v, Float64Array), alive = unpack(r.alive, Uint8Array), snap = [];
    for (let i = 0, k = 0; i < r.N; i++) if (alive[i] && k++ % Math.max(1, Math.floor(r.N / 600)) === 0) snap.push([...x.slice(i * r.d, i * r.d + r.d), ...v.slice(i * r.d, i * r.d + r.d)].map((u) => +u.toFixed(4)));
    runs.push({ name: f.replace(".json", ""), d: r.d, a1: r.a1, a2: r.a2, N: r.N, T: r.T, seed: r.seed, eta: r.eta, sigma: r.sigma, done: !!r.done, t: r.t, series: r.series, snap });
  }
  writeFileSync(path.join(here, "../js/nebuladata.js"), `/* Generated by tools/nebula.mjs bake from the runner's nebula runs; do not edit. Per run: its dimension, rates a1
   (xy) and a2 (zw), particles, end time; series: the shape sampled over time (axes: the root-mean-square extent along
   the gas's principal directions, largest first; plus/minus: how both halves of each orbit's turning line up with
   the cloud's; ecc: the mean orbital eccentricity, 0 when settled onto circles); snap: some particles at the end, x then v. */
export const NEBULA = ${JSON.stringify(runs)};
`);
  console.log(`baked ${runs.length} runs`);
} else { console.log("usage: nebula.mjs run <d> <a1> <a2> <N> <T> <seed> [eta] [sigma] | bake"); process.exit(1); }
