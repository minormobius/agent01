/* Bakes js/starsdata.js for the stars chapter: the three laws' polytropes (profiles, central concentration, the virial
   check, E/W), how much of the pull comes from outside each radius, and the tunnelling rates that light a core.
     node four/atom/tools/stars.mjs        # about half a minute */
import { writeFileSync } from "node:fs";
import * as S from "../js/stars.js";

const t0 = Date.now(), models = {};
for (const [key, law, n] of [["ours", "newton", 1.5], ["pinned", "pinned4", 2], ["gauss", "gauss4", 2], ["oursRad", "newton", 3], ["pinnedRad", "pinned4", 4]]) {
  const p = S.polytrope(law, n), every = Math.max(1, Math.floor(p.r.length / 100));
  models[key] = { law, d: p.d, n, centralOverMean: +p.centralOverMean.toFixed(4), virial: +p.virial.toExponential(2), bound: +p.bound.toFixed(4), converged: p.converged,
    profile: p.r.filter((_, i) => i % every === 0).map((x, i) => [+x.toFixed(4), +p.rho[i * every].toFixed(5)]),
    outer: key === "ours" || key === "pinned" ? S.outerPull(p).filter((_, i) => i % 8 === 0).map(([x, f]) => [+x.toFixed(3), +f.toFixed(4)]) : null };
}
// lighting: tunnelling rate against temperature for p + p and D + D, and the temperature a 4D core needs to match ours
const pp = { mu: 469.459, rn: 2 }, dd = { mu: 937.8, rn: 4 }, Ts = Array.from({ length: 25 }, (_, i) => 5e6 * 1.12 ** i);
const lighting = {
  Ts: Ts.map((T) => +T.toPrecision(4)),
  pp3: Ts.map((T) => +S.logRate(T, { ...pp, d: 3 }).toFixed(3)), pp4: Ts.map((T) => +S.logRate(T, { ...pp, d: 4 }).toFixed(3)),
  // at 1.5e7 K: how many times less often 4D nuclei tunnel (the barrier alone), and the temperature that would make it up
  match: { pp: [1, 2, 4].map((rn) => ({ rn, deficit: +Math.exp(S.logRate(1.5e7, { ...pp, rn, d: 3 }) - S.logRate(1.5e7, { ...pp, rn, d: 4 })).toFixed(2), ratio: +(S.matchingTemperature(1.5e7, { ...pp, rn }) / 1.5e7).toFixed(3) })),
    dd: +(S.matchingTemperature(1.5e7, dd) / 1.5e7).toFixed(3), ddDeficit: +Math.exp(S.logRate(1.5e7, { ...dd, d: 3 }) - S.logRate(1.5e7, { ...dd, d: 4 })).toFixed(2) },
};
writeFileSync(new URL("../js/starsdata.js", import.meta.url), `/* Generated by tools/stars.mjs from js/stars.js; do not edit. Polytropes in units G = 1, radius 1, central density 1
   (profile: [r, ρ]; outer: [r, the share of the inward pull from mass outside r]), and log tunnelling rates (up to
   the nuclear factor) against temperature in kelvin; at 1.5e7 K, how many times less often 4D nuclei get through the
   barrier, and the temperature ratio that would make it up if temperature alone did. */
export const STARS = ${JSON.stringify({ models, lighting })};
`);
console.log(`baked in ${((Date.now() - t0) / 1000).toFixed(0)} s`, JSON.stringify(Object.fromEntries(Object.entries(models).map(([k, m]) => [k, [m.centralOverMean, m.bound, m.virial]]))), JSON.stringify(lighting.match), models.pinned.outer.slice(0, 6));
