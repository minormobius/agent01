/* The Bluminium viewer's data: bakes **generated** js/bluminiumdata.js for bluminium.html.
     node four/atom/tools/bluminium.mjs bake      (about three minutes in the sandbox)
   What it holds, all from the tools that compute it:
     - Bl₂Px₃'s two candidate cells (crystalref-Bl2Px3.json z2-0, z2-1): the primitive cell, its atoms, each distinct
       cation site with its ligands (crystalfield.mjs's ligands());
     - the dopants: 3dⁿ 3+ ions in 4D (n = 1–4, 14–17; element 25 + n), each with its repulsion's F⁰, F², F⁴
       (multiplets.mjs's slater()) and, on every site, its ligand-field matrix with and without the clouds' leak
       (crystalfield.mjs's dBlock(): point charges −2, leak S/8|x − X|³);
     - ours for the check: Cr³⁺, Ti³⁺, V³⁺ and Mn³⁺ on corundum's Al site;
     - the angular tensors A_n (n = 0, 2, 4) for ours and 4D, so the page builds ⟨ab|cd⟩ without quadrature;
     - ruby's calibration (s, β: the ⁴T₂ band at 2.23 eV, the ²E line at 1.786 eV), found here as multiplets.mjs finds it;
     - tools/bluminium-results.json, hand-kept: the cells' energies and gaps as the runner's runs report them.
   The page itself diagonalizes (js/multiplet.js), so the sliders on s and β are live. */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { dopant, dBlock, host } from "./crystalfield.mjs";
import { slater, angular } from "./multiplets.mjs";
import { levels, firsts } from "../js/multiplet.js";
import { invM } from "./pwcheck.mjs";

const here = path.dirname(fileURLToPath(import.meta.url)), HA = 27.211386, r6 = (x) => (Math.abs(x) < 1e-12 ? 0 : +x.toPrecision(7));
const ionOf = (D, Z, n) => dopant(Z, D, `${D === 3 ? "1s2 2s2 2p6 3s2 3p6" : "1s2 2s2 2p8 3s2 3p8"} 3d${n}`);
const mat = (H) => H.map((r) => Array.from(r, r6));

if (process.argv[2] !== "bake") { console.log("usage: bluminium.mjs bake"); process.exit(0); }
const t0 = Date.now(), log = (s) => process.stderr.write(`${((Date.now() - t0) / 1000).toFixed(0)}s ${s}\n`);
const ang3 = angular(3), ang4 = angular(4), A = (ang) => ang.A.map((M) => M.map((r) => Array.from(r, r6)));

/* ours: corundum's site, and the ruby fit */
const ruby = host("ruby"), ours = [];
for (const [Z, n, name] of [[22, 1, "Ti³⁺"], [23, 2, "V³⁺"], [24, 3, "Cr³⁺"], [25, 4, "Mn³⁺"]]) { const io = ionOf(3, Z, n), F = slater(3, io.q);
  ours.push({ Z, n, name, converged: io.converged, F: F.map(r6), H: mat(dBlock(3, ruby.sites[0].L, ruby.q, ruby.c, io.q).H) }); log(`ours ${name}`); }
const cr = ours.find((o) => o.Z === 24), H3 = cr.H, at3 = (s, b) => firsts(levels(5, 3, H3, s, ang3, cr.F, b), [3, 2]);
let s = 1, b = 1; for (let it = 0; it < 40; it++) { const f = at3(s, b); s *= 2.23 / f.allowed_eV; const g = at3(s, b), g2 = at3(s, b * 1.01); b += (1.786 - g.flip_eV) / ((g2.flip_eV - g.flip_eV) / (0.01 * b)); if (Math.abs(g.allowed_eV - 2.23) < 1e-5 && Math.abs(g.flip_eV - 1.786) < 1e-5) break; }
log(`ruby fit s ${s.toFixed(4)} β ${b.toFixed(4)}`);

/* the cells */
const file = JSON.parse(readFileSync(path.join(here, "crystalref-Bl2Px3.json"), "utf8")), cells = {};
for (const name of ["z2-0", "z2-1"]) {
  const st = file[name], H0 = st.H, P = st.P ?? H0.map((_, i) => H0.map((_, j) => +(i === j))), Hp = P.map((row) => H0[0].map((_, c) => row.reduce((t, v, k) => t + v * H0[k][c], 0))), Hpi = invM(Hp), atoms = [];
  st.s.forEach((f, i) => { const x = H0[0].map((_, c) => f.reduce((t, v, k) => t + v * H0[k][c], 0)), g = x.map((_, j) => x.reduce((t, v, c) => t + v * Hpi[c][j], 0)).map((v) => v - Math.floor(v + 1e-9));
    if (!atoms.some((q) => q.k === st.kinds[i] && q.g.every((v, j) => Math.abs(((v - g[j] + 0.5) % 1 + 1) % 1 - 0.5) < 1e-4))) atoms.push({ k: st.kinds[i], g: g.map(r6) }); });
  const hs = host("bl", name);
  cells[name] = { H: Hp.map((r) => r.map(r6)), atoms, sites: hs.sites.map(({ site, L }) => ({ site, ligands: L.map((l) => ({ v: l.v.map(r6), r: r6(l.r) })) })), leakS: r6(hs.S) };
}
const dopants = [];
for (const n of [1, 2, 3, 4, 14, 15, 16, 17]) { const Z = 25 + n, io = ionOf(4, Z, n), F = slater(4, io.q), on = {};
  for (const [name, c] of Object.entries(cells)) { const hs = host("bl", name); on[name] = hs.sites.map(({ L }) => ({ leak: mat(dBlock(4, L, hs.q, hs.c, io.q).H), bare: mat(dBlock(4, L, hs.q, 0, io.q).H) })); }
  dopants.push({ Z, n, converged: io.converged, eps3d_eV: +(io.eps3d * HA).toFixed(2), r3d: +io.r.toFixed(4), F: F.map(r6), on }); log(`4D 3d${n}`); }

const results = JSON.parse(readFileSync(path.join(here, "bluminium-results.json"), "utf8"));
const out = { ruby: { s: r6(s), beta: r6(b), allowed_eV: 2.23, flip_eV: 1.786 }, A3: A(ang3), A4: A(ang4), ours, cells, dopants, results };
const text = `/* GENERATED by tools/bluminium.mjs bake — do not edit. The Bluminium viewer's data (bluminium.html). */\nexport const BLUMINIUM = ${JSON.stringify(out)};\n`;
writeFileSync(path.join(here, "../js/bluminiumdata.js"), text); log(`wrote js/bluminiumdata.js (${(text.length / 1024).toFixed(0)} kB)`);
