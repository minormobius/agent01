/* The planets' stability map, for the runner: two planets round a star (js/orbits.js twoPlanets, the pinned 1/r pull),
   over the ratio of their orbits' sizes, the angle between their planes, and their mass, each run for 10⁵ orbits of the
   inner one. Two ways for planes to differ: "iso", both principal angles equal (90°: completely orthogonal, the 4D
   tilt), and "line", sharing a line and tilted in one angle (the only tilt our planets have). This is what an orrery
   generator needs to know before it places planets.
     node four/atom/tools/stability.mjs run <mass> <kind> [orbits]   # one mass and kind, every ratio and angle; cached
     node four/atom/tools/stability.mjs bake                          # into js/stabilitydata.js */
import { writeFileSync, readFileSync, mkdirSync, existsSync, readdirSync, renameSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { twoPlanets } from "../js/orbits.js";

const DIR = path.join(tmpdir(), "atom4-stability"), here = path.dirname(fileURLToPath(import.meta.url));
export const RATIOS = [1.0, 1.05, 1.1, 1.15, 1.2, 1.3, 1.45, 1.6], ANGLES = [0, 15, 30, 45, 60, 75, 90];
const [mode, ...args] = process.argv.slice(2);

if (mode === "run") {
  const mp = +args[0], kind = args[1], orbits = +(args[2] ?? 100000), file = path.join(DIR, `${mp}_${kind}_${orbits}.json`);
  mkdirSync(DIR, { recursive: true });
  const st = existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : { mp, kind, orbits, runs: [] }, t0 = Date.now();
  for (const a2 of RATIOS) for (const th of ANGLES) {
    if (st.runs.some((r) => r.a2 === a2 && r.th === th)) continue;
    const t = Date.now(), r = twoPlanets(a2, th, { mp, orbits, kind });
    st.runs.push({ a2, th, emax: r.emax, dmin: r.dmin, wander: r.wander, lost: r.lost, s: +((Date.now() - t) / 1000).toFixed(1) });
    writeFileSync(file + ".part", JSON.stringify(st)); renameSync(file + ".part", file);
    console.log(`${((Date.now() - t0) / 1000).toFixed(0)}s mass ${mp} ${kind} radii 1 : ${a2} at ${th}°: ${r.lost !== null ? `thrown out at orbit ${r.lost}` : `kept, eccentricity up to ${r.emax}`}, closest ${r.dmin}`);
  }
  console.log("done");
} else if (mode === "bake") {
  const sets = existsSync(DIR) ? readdirSync(DIR).filter((f) => f.endsWith(".json")).map((f) => JSON.parse(readFileSync(path.join(DIR, f), "utf8"))) : [];
  writeFileSync(path.join(here, "../js/stabilitydata.js"), `/* Generated by tools/stability.mjs bake from the runner's runs; do not edit. Per planet mass (in star masses) and
   kind of tilt ("iso": both of the planes' angles th; "line": sharing a line, one angle th), two planets on circular
   orbits of radii 1 and a2, run for the given number of orbits of the inner one: the largest eccentricity either
   reached, their closest approach, how far the inner one's orbit swung out of its first plane, and the orbit a planet
   was thrown out on (null: kept). */
export const RATIOS = ${JSON.stringify(RATIOS)}, ANGLES = ${JSON.stringify(ANGLES)};
export const STABILITY = ${JSON.stringify(sets.map((s) => ({ mp: s.mp, kind: s.kind, orbits: s.orbits, runs: s.runs.map(({ s: _, ...r }) => r) })))};
`);
  console.log(`baked ${sets.length} sets`);
} else { console.log("usage: stability.mjs run <mass> <kind> [orbits] | bake"); process.exit(1); }
