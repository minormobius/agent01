/* Paper 1's d² in a ligand field: does the four-dimensional singlet that breaks Hund's rule survive a crystal field, and
   when does a triplet take over? The free ion is element 26's 2+ (3d² over the closed shells), on its own orbital; the
   field is point charges q at ±R along each axis (the 16-cell, four dimensions' octahedron: eight ligands), projected
   exactly onto the degrees 0, 2, 4 a d × d product holds (crystalfield.mjs dBlock); the levels are every determinant of
   two electrons in the shell's 18 spin orbitals (js/multiplet.js levels). The field is scaled by s from zero, and Δ is
   the one-electron splitting it gives. Three shapes in 4D (axes, tesseract corners, 24-cell) and two in ours. Ours' Ti²⁺
   (3d²) is the check: its ³F → ³T₁ stays the ground
   at every field, as Tanabe and Sugano have it for d².
     node four/atom/tools/ligandd2.mjs      → papers/p1/data/ligandd2.json (a minute) */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { HA, dopant, dBlock, groups } from "./crystalfield.mjs";
import { slater, angular, levels } from "./multiplets.mjs";

const R = 4, Q = -1, S = [0, 0.5, 1, 1.5, 2, 3, 4, 5, 6, 6.25, 6.5, 6.75, 7, 7.25, 7.5, 7.75, 8, 10, 12, 16, 20];
/* ligand sets at distance R: along the axes (the cross-polytope: ours' octahedron, 4D's 16-cell), at the corners of the
   cube (ours' cube, 4D's tesseract), and 4D's 24-cell (the permutations of (±1, ±1, 0, 0)) */
function shape(D, kind) {
  const pts = [];
  if (kind === "axes") for (let i = 0; i < D; i++) for (const sg of [1, -1]) { const v = Array(D).fill(0); v[i] = sg; pts.push(v); }
  if (kind === "corners") for (let b = 0; b < 1 << D; b++) pts.push(Array.from({ length: D }, (_, i) => ((b >> i) & 1 ? 1 : -1)));
  if (kind === "24-cell") for (let i = 0; i < D; i++) for (let j = i + 1; j < D; j++) for (const a of [1, -1]) for (const b of [1, -1]) { const v = Array(D).fill(0); v[i] = a; v[j] = b; pts.push(v); }
  return pts.map((v) => { const n = Math.hypot(...v); return { v: v.map((x) => (R * x) / n), r: R }; });
}
function run(D, Z, kind) {
  const core = D === 3 ? "1s2 2s2 2p6 3s2 3p6" : "1s2 2s2 2p8 3s2 3p8", ion = dopant(Z, D, `${core} 3d2`), F = slater(D, ion.q), ang = angular(D);
  const ligs = shape(D, kind);
  const blk = dBlock(D, ligs, Q, 0, ion.q), m = ang.m, one = groups(blk.levels_eV, 0.002), delta1 = blk.spread_eV;
  const scan = S.map((s) => { const L = levels(m, 2, blk.H, s, ang, F, 1).multiplets.slice(0, 8);
    return { s, delta_eV: +(s * delta1).toFixed(4), ground: { mult: L[0].mult, g: L[0].g }, low: L.map(({ Eabs, ...x }) => x) }; });
  const flip = scan.find((x, k) => k > 0 && x.ground.mult !== scan[0].ground.mult);
  return { D, Z, ion: `${Z}²⁺ 3d²`, ligands: kind, n: ligs.length, converged: ion.converged, F_eV: F.map((x) => +(x * HA).toFixed(4)), R, q: Q, oneElectron: one, oneElectronSpread_eV: delta1,
    freeIon: scan[0].low, groundChangesAt: flip ? { s: flip.s, delta_eV: flip.delta_eV, to: flip.ground } : null, scan };
}
const out = { about: "Generated by atom/tools/ligandd2.mjs; do not edit. A d² ion in point charges q at distance R in five shapes (4D: along the axes, the 16-cell; at the tesseract's corners; the 24-cell. Ours: the octahedron, the cube), field scaled by s; delta_eV the one-electron spread; low: the lowest multiplets (eV above the lowest, 2S+1, degeneracy).", rows: [run(4, 26, "axes"), run(4, 26, "corners"), run(4, 26, "24-cell"), run(3, 22, "axes"), run(3, 22, "corners")] };
writeFileSync(new URL("../../papers/p1/data/ligandd2.json", import.meta.url), JSON.stringify(out, null, 1) + "\n");
for (const r of out.rows) {
  console.log(`${r.D}D ${r.ion}, ${r.n} ligands (${r.ligands}): one-electron groups at s = 1 ${JSON.stringify(r.oneElectron)}; free ion ${r.freeIon.slice(0, 3).map((x) => `${x.mult}×${x.g}@${x.eV}`).join(", ")}`);
  for (const x of r.scan) console.log(`   s ${x.s}  Δ ${x.delta_eV}  ground ${x.ground.mult} (${x.ground.g})  next ${x.low.slice(1, 4).map((y) => `${y.mult}×${y.g}@${y.eV}`).join(", ")}`);
  console.log("   ground changes:", JSON.stringify(r.groundChangesAt));
}
