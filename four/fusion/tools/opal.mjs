/* OPAL's opacities for our world, as measured input: the Rosseland means of Iglesias & Rogers 1996 (OPAL) above
   log T 3.75 and Ferguson et al. 2005 below, both at Asplund et al. 2009's solar mixture, as MESA distributes them
   (github.com/MESAHub/mesa, kap/kap_data.tar.xz: a09_z*_x*.data and lowT_fa05_a09p_z*_x*.data; MIST v1.2's opacities).
   Usage: node four/fusion/tools/opal.mjs <dir of kap_data> → four/atom/js/opaldata.js (generated; read by atom/js/opal.js).
   Kept: Z 0, 0.001, 0.004, 0.01, 0.02, 0.03 at X 0–0.95, the low-T tables from log T 3.2 to 3.95 only (blended into OPAL's over 3.80–3.88, as MESA does), log κ (cm²/g) on (log T, log R),
   R = ρ/T6³ (g/cm³), as integers in thousandths (the tables' own precision), base64 Int16. */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url)), OUT = join(HERE, "../../atom/js/opaldata.js");
const dir = process.argv[2];
if (!dir) { console.error("usage: opal.mjs <dir of kap_data>"); process.exit(1); }
const ZS = [0, 0.001, 0.004, 0.01, 0.02, 0.03], XS = [0, 0.1, 0.2, 0.35, 0.5, 0.7, 0.8, 0.9, 0.95];
const zname = (z) => (z === 0 ? "0.0" : String(z)), xname = (x) => (x === 0 ? "0.0" : String(x));

function read(file) {
  const L = readFileSync(file, "utf8").split("\n"), h = L[2].trim().split(/\s+/).map(Number);
  const [, , X, Z, nR, R0, R1, nT, T0, T1] = h, logR = L[5].trim().split(/\s+/).map(Number), logT = [], v = [];
  if (logR.length !== nR) throw new Error(`${file}: ${logR.length} log R, header says ${nR}`);
  for (const line of L.slice(7)) { const w = line.trim().split(/\s+/); if (w.length < 2) continue; logT.push(+w[0]);
    if (w.length !== nR + 1) throw new Error(`${file}: row ${w[0]} has ${w.length - 1} values`);
    for (const s of w.slice(1)) { const n = +s; if (!Number.isFinite(n)) throw new Error(`${file}: ${s}`); v.push(Math.round(n * 1000)); } }
  if (logT.length !== nT || logT[0] !== T0 || logT[nT - 1] !== T1 || logR[0] !== R0 || logR[nR - 1] !== R1) throw new Error(`${file}: axes`);
  return { X, Z, logT, logR, v };
}
function cut(t, a, b) { const n = t.logR.length, keep = t.logT.map((T, i) => [T, i]).filter(([T]) => T >= a - 1e-9 && T <= b + 1e-9);
  return { ...t, logT: keep.map(([T]) => T), v: keep.flatMap(([, i]) => t.v.slice(i * n, (i + 1) * n)) }; }
function family(prefix, Tmin = -1, Tmax = 99) {
  let axes = null; const tabs = [];
  for (const z of ZS) for (const x of XS) {
    const f = join(dir, `${prefix}_z${zname(z)}_x${xname(x)}.data`); if (!existsSync(f)) throw new Error(`missing ${f}`);
    const t = cut(read(f), Tmin, Tmax); if (Math.abs(t.X - x) > 1e-9 || Math.abs(t.Z - z) > 1e-9) throw new Error(`${f}: X ${t.X} Z ${t.Z}`);
    if (!axes) axes = { logT: t.logT, logR: t.logR };
    else if (t.logT.join() !== axes.logT.join() || t.logR.join() !== axes.logR.join()) throw new Error(`${f}: axes differ`);
    tabs.push(Buffer.from(Int16Array.from(t.v).buffer).toString("base64")); }
  return { ...axes, tabs };
}
const hi = family("a09"), lo = family("lowT_fa05_a09p", 3.2, 3.95);
const data = { source: "OPAL (Iglesias & Rogers 1996) above log T 3.75, Ferguson et al. 2005 below, Asplund et al. 2009 mixture; MESA kap_data a09 / lowT_fa05_a09p", Z: ZS, X: XS, hi, lo };
writeFileSync(OUT, `/* generated by four/fusion/tools/opal.mjs — do not edit. ${data.source}. log κ (cm²/g) × 1000 as base64 Int16, one table per (Z, X), Z outer. */\nexport const OPAL = ${JSON.stringify(data)};\n`);
console.log(`${OUT}: ${ZS.length * XS.length} × 2 tables, ${(readFileSync(OUT).length / 1024).toFixed(0)} kB`);
