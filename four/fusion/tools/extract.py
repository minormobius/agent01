"""Extract the REACLIB rates the fusion widget needs (four/fusion/reaclib.js).

Source: the REACLIB snapshot pynucastro ships, pynucastro/data/reaclib_default2_20250330 (downloaded by pynucastro from
reaclib.jinaweb.org; Cyburt et al. 2010, ApJS 189, 240). Keeps every reaction whose reactants and products all lie in
SPECIES (neutrons and other side channels are dropped, and said so on the page). Each reaction keeps all of its fitted
sets: lambda = sum over sets of exp(a0 + a1/T9 + a2 T9^(-1/3) + a3 T9^(1/3) + a4 T9 + a5 T9^(5/3) + a6 ln T9).
    python3 four/fusion/tools/extract.py <path to reaclib_default2_20250330>
"""
import json, sys, re, collections, os

SPECIES = ["p", "d", "he3", "he4", "li7", "be7", "b8", "c12", "c13", "n13", "n14", "n15", "o15", "o16", "o17", "f17",
           "f18", "o18", "ne20", "ne22", "na23", "mg24", "al27", "si28", "p31", "s32", "cl35", "ar36", "k39", "ca40", "sc43", "ti44", "v47",
           "cr48", "mn51", "fe52", "co55", "ni56"]
# chapter -> (number of reactants, number of products)
CH = {1: (1, 1), 2: (1, 2), 3: (1, 3), 4: (2, 1), 5: (2, 2), 6: (2, 3), 7: (2, 4), 8: (3, 1), 9: (3, 2), 10: (4, 2), 11: (1, 4)}

def parse(path):
    lines = open(path).read().split("\n"); i = 0; out = []
    while i < len(lines):
        if not lines[i].strip(): i += 1; continue
        ch = int(lines[i].strip()); h = lines[i + 1]; c1 = lines[i + 2]; c2 = lines[i + 3]; i += 4
        nuc = [h[5 + 5 * k: 10 + 5 * k].strip() for k in range(6)]; nuc = [x for x in nuc if x]
        label = h[43:47].strip(); flag = h[47:48]; rev = h[48:49] == "v"; Q = float(h[52:64])
        a = [float(c1[13 * k: 13 * k + 13]) for k in range(4)] + [float(c2[13 * k: 13 * k + 13]) for k in range(3)]
        nr, npd = CH[ch]; out.append(dict(ch=ch, r=nuc[:nr], p=nuc[nr:nr + npd], label=label, flag=flag, rev=rev, Q=Q, a=a))
    return out

rows = parse(sys.argv[1]); S = set(SPECIES); keep = collections.OrderedDict()
for e in rows:
    if not all(x in S for x in e["r"] + e["p"]): continue
    ec = "ec" in e["label"]  # an electron capture (pep is p + p's ec set): its own reaction, the rate × ρY_e
    key = (tuple(e["r"]), tuple(e["p"]), ec)
    k = keep.setdefault(key, dict(r=e["r"], p=e["p"], Q=e["Q"], labels=[], sets=[], weak=False, ec=ec, rev=False))
    k["sets"].append(e["a"]); k["labels"].append(e["label"] + e["flag"] + ("v" if e["rev"] else ""))
    k["weak"] |= e["flag"] == "w"; k["rev"] |= e["rev"]
out = list(keep.values())
src = os.path.basename(sys.argv[1])
js = f"""/* Generated by four/fusion/tools/extract.py; do not edit. Every reaction among the widget's {len(SPECIES)} nuclei in the
   REACLIB snapshot {src} (reaclib.jinaweb.org via pynucastro; Cyburt et al. 2010, ApJS 189, 240), all fitted sets kept:
   rate = Σ exp(a0 + a1/T9 + a2 T9^(-1/3) + a3 T9^(1/3) + a4 T9 + a5 T9^(5/3) + a6 ln T9), in s⁻¹ for one reactant, N_A⟨σv⟩
   (cm³ mol⁻¹ s⁻¹) for two, N_A²⟨σv⟩ for three. ec: an electron capture, × ρY_e. rev: a reverse rate from detailed
   balance (partition functions taken as 1). labels: REACLIB's source label per set, flag (n, r, w) and v for reverse. */
export const SOURCE = {json.dumps(src)};
export const SPECIES = {json.dumps(SPECIES)};
export const REACTIONS = {json.dumps(out, separators=(",", ":"))};
"""
open(os.path.join(os.path.dirname(__file__), "..", "reaclib.js"), "w").write(js)
print(len(out), "reactions;", sum(len(x["sets"]) for x in out), "sets;", len(js) // 1024, "kB")
for x in out[:0]: print(x)
