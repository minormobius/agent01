/* The 4D stages' temperatures, for the widget (fusion/stages4.js): at each strength in data4.js,
     hydrogen   the Sun's pace: half the hydrogen gone in 4.6 Gyr from 75% hydrogen, 25% helium (net4's sunPace)
     helium     the helium-4 capture's rate-matched ignition (nuclei.mjs capture: ⁴He + ⁴He at our ¹²C(α,γ)'s pace)
     ceryllium  0.27 GK (nuclei.mjs heburn's ceryllium + itself, barrier-only at our O + O pace)
   Run after rates4.mjs (it runs this itself).   node four/fusion/tools/stages4.mjs */
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { model, STRENGTHS } from "../js/net4.js";

const DIR = `${process.env.TMPDIR ?? "/tmp"}/atom4-nuclei`, load = (f) => (existsSync(`${DIR}/${f}`) ? JSON.parse(readFileSync(`${DIR}/${f}`, "utf8")) : null);
const caps = [...(load("MN-capture.json")?.rows ?? []), ...(load("MN-capture-scan.json")?.rows ?? [])], out = {};
for (const s of STRENGTHS) { const m = model(s), cap = caps.find((r) => Math.abs(r.s - s) < 1e-4);
  if (!cap) throw new Error(`no helium-4 capture at s = ${s}: run nuclei.mjs capture`);
  out[s] = { h: +m.sunPace({ "1-1": 0.75, "2-4": 0.25 }).toPrecision(4), he: +cap.T[0].toPrecision(4), ce: 2.71e8 };
  console.log(`s ${s}: hydrogen ${(out[s].h / 1e6).toFixed(1)} MK, helium ${(out[s].he / 1e6).toFixed(1)} MK, ceryllium 271 MK`); }
writeFileSync(new URL("../stages4.js", import.meta.url), `/* Generated by four/fusion/tools/stages4.mjs; do not edit. Each 4D stage's temperature (K) at each strength: hydrogen at
   the Sun's pace, helium at its capture's rate-matched ignition, ceryllium at 0.27 GK. */
export const STAGE_T = ${JSON.stringify(out)};\n`);
