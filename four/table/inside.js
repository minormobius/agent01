/* Inside the atom: paper 1's figures 4 and 5 for any 4D element. The pinned element's subshells in profile (each
   subshell's electrons per unit ln r, the outermost drawn thick) and one of its orbitals cut through the nucleus by a
   plane of 4D space. Data: profiles.json (GENERATED by ../atom/tools/profiles.mjs bake: every element re-solved in the
   table's configuration with each subshell's radial function kept), fetched the first time it's needed.
   The radial function is stored as P(r) = r³R², which loses R's sign; R's n − l − 1 nodes are put back at the deepest
   minima of P (a node is where P touches zero). The angular parts are harmonic polynomials of degree l in x, y, z, w. */

const $ = (id) => document.getElementById(id);
let data = null, loading = null, state = { Z: 0, sub: null, plane: "xw", harm: 0 };
const COL = { 0: "#9fb3ff", 1: "#6fe0ff", 2: "#7be0a0", 3: "#ffd166" }; // s p d f
const PLANES = { xy: [0, 1], xz: [0, 2], xw: [0, 3], yz: [1, 2], yw: [1, 3], zw: [2, 3] };
const AX = ["x", "y", "z", "w"];
// harmonic polynomials on the unit vector u = (x, y, z, w): each satisfies ∇²f = 0 in four dimensions
const HARM = {
  0: [["s (round)", () => 1]],
  1: [["w", (u) => u[3]], ["x", (u) => u[0]]],
  2: [["x² + y² − z² − w²", (u) => u[0] ** 2 + u[1] ** 2 - u[2] ** 2 - u[3] ** 2], ["xw", (u) => u[0] * u[3]], ["x² − w²", (u) => u[0] ** 2 - u[3] ** 2]],
  3: [["x³ − 3xw²", (u) => u[0] ** 3 - 3 * u[0] * u[3] ** 2], ["xyw", (u) => u[0] * u[1] * u[3]], ["xyz", (u) => u[0] * u[1] * u[2]]],
};

function load() {
  if (!loading) loading = fetch("profiles.json").then((r) => { if (!r.ok) throw new Error(`profiles.json: HTTP ${r.status}`); return r.json(); }).then((d) => (data = d));
  return loading;
}

/* the pinned element changed (or the page opened on one): draw it once the data is in */
export function inside(Z, label) {
  const box = $("inside"); if (!box) return;
  if (!(Z > 0)) { box.innerHTML = `<p class="kv">Pick a 4D element in the table above to see inside it.</p>`; return; }
  if (state.Z !== Z) state = { ...state, Z, sub: null, harm: 0 };
  state.label = label;
  if (!data) { box.innerHTML = `<p class="kv">Loading the solved atoms…</p>`; load().then(() => inside(state.Z, state.label)).catch((e) => { box.innerHTML = `<p class="kv">Couldn't load the profiles (${e.message}).</p>`; }); return; }
  const at = data.atoms.find((a) => a.Z === Z); if (!at) { box.innerHTML = `<p class="kv">Element ${Z} isn't in the profiles.</p>`; return; }
  const outer = at.sub.reduce((a, b) => (b.e > a.e ? b : a));
  if (!state.sub || !at.sub.some((q) => q.n === state.sub)) state.sub = outer.n;
  const q = at.sub.find((x) => x.n === state.sub), H = HARM[q.l];
  if (state.harm >= H.length) state.harm = 0;
  box.innerHTML = `
    <div class="in-grid">
      <figure class="in-fig"><figcaption><b>${label}</b> in profile: each subshell's electrons per unit of ln r. The outermost, <b>${outer.n}</b>, is drawn thick; the area under a curve is its electron count.</figcaption>
        <canvas id="in-prof" class="in-prof"></canvas>
        <div class="in-keys">${at.sub.map((x) => `<button type="button" class="in-chip${x.n === state.sub ? " on" : ""}" data-sub="${x.n}" style="--c:${COL[x.l]}">${x.n}<sup>${x.occ}</sup> <span>${x.e.toFixed(3)} Ha</span></button>`).join("")}</div>
      </figure>
      <figure class="in-fig"><figcaption>A <b>${q.n}</b> orbital, cut through the nucleus by the <b>${state.plane[0]}–${state.plane[1]}</b> plane: cyan where it's positive, rose where it's negative, brighter where it's larger (scaled to the outer lobe, so the innermost lobes may saturate). Pick the subshell above, the orbital's shape and the plane below.</figcaption>
        <canvas id="in-slice" class="in-slice" width="320" height="320"></canvas>
        <div class="in-keys">${H.map(([t], i) => `<button type="button" class="in-chip${i === state.harm ? " on" : ""}" data-harm="${i}">${t}</button>`).join("")}</div>
        <div class="in-keys">${Object.keys(PLANES).map((p) => `<button type="button" class="in-chip${p === state.plane ? " on" : ""}" data-plane="${p}">${p[0]}–${p[1]}</button>`).join("")}</div>
      </figure>
    </div>`;
  box.querySelectorAll("[data-sub]").forEach((b) => (b.onclick = () => { state.sub = b.dataset.sub; state.harm = 0; inside(state.Z, state.label); }));
  box.querySelectorAll("[data-harm]").forEach((b) => (b.onclick = () => { state.harm = +b.dataset.harm; inside(state.Z, state.label); }));
  box.querySelectorAll("[data-plane]").forEach((b) => (b.onclick = () => { state.plane = b.dataset.plane; inside(state.Z, state.label); }));
  profile($("in-prof"), at, outer);
  slice($("in-slice"), q, H[state.harm][1], PLANES[state.plane]);
}

const P = (q, i) => (q.k * q.P[i]) / 999;
function profile(cv, at, outer) {
  const dpr = Math.min(2, devicePixelRatio || 1), w = cv.clientWidth, h = cv.clientHeight; cv.width = w * dpr; cv.height = h * dpr;
  const g = cv.getContext("2d"); g.setTransform(dpr, 0, 0, dpr, 0, 0); g.clearRect(0, 0, w, h);
  const r = data.r, lx = (x) => 30 + ((w - 40) * Math.log10(x / r[0])) / Math.log10(r.at(-1) / r[0]);
  const y = (q, i) => q.occ * P(q, i) * r[i], ymax = Math.max(...at.sub.flatMap((q) => r.map((_, i) => y(q, i)))) * 1.1, ly = (v) => h - 18 - ((h - 28) * v) / ymax;
  g.strokeStyle = "rgba(255,255,255,0.15)"; g.beginPath(); g.moveTo(30, h - 18); g.lineTo(w - 10, h - 18); g.stroke();
  g.font = "10px ui-monospace, monospace"; g.fillStyle = "#9a958c";
  for (const t of [0.01, 0.1, 1, 10]) { g.fillText(String(t), lx(t) - 8, h - 5); g.fillRect(lx(t), h - 20, 1, 4); }
  g.fillText("r (bohr), log scale", w - 128, 12);
  for (const q of at.sub) {
    g.strokeStyle = COL[q.l]; g.globalAlpha = q.n === state.sub || q === outer ? 1 : 0.7; g.lineWidth = q === outer ? 2.6 : q.n === state.sub ? 1.8 : 1.1;
    g.beginPath(); r.forEach((_, i) => (i ? g.lineTo(lx(r[i]), ly(y(q, i))) : g.moveTo(lx(r[i]), ly(y(q, i))))); g.stroke();
  }
  g.globalAlpha = 1;
}

/* R(r) with its sign: |R| = √(P/r³), and a sign change at each of the n − l − 1 deepest interior minima of P */
function radial(q) {
  const r = data.r, n = +q.n.match(/^\d+/)[0], nodes = n - q.l - 1, p = r.map((_, i) => P(q, i));
  const mins = []; for (let i = 1; i < p.length - 1; i++) if (p[i] <= p[i - 1] && p[i] < p[i + 1]) mins.push(i);
  const flips = mins.sort((a, b) => p[a] - p[b]).slice(0, nodes).sort((a, b) => a - b);
  const R = p.map((v, i) => Math.sqrt(v / r[i] ** 3) * (flips.filter((f) => f < i).length % 2 ? -1 : 1));
  const peak = r[p.indexOf(Math.max(...p))];
  return { at: (x) => { if (x <= r[0]) return R[0]; if (x >= r.at(-1)) return 0; const k = Math.min(r.length - 2, Math.floor((20 * Math.log10(x / r[0])))), u = Math.log(x / r[k]) / Math.log(r[k + 1] / r[k]); return R[k] * (1 - u) + R[k + 1] * u; }, peak };
}
function slice(cv, q, ang, [a, b]) {
  const n = 160, g = cv.getContext("2d"), img = g.createImageData(n, n), R = radial(q), L = Math.max(0.5, 2.4 * R.peak), vals = new Float64Array(n * n);
  let mx = 0;
  for (let j = 0; j < n; j++) for (let i = 0; i < n; i++) {
    const p = [0, 0, 0, 0]; p[a] = -L + (2 * L * (i + 0.5)) / n; p[b] = L - (2 * L * (j + 0.5)) / n;
    const rr = Math.hypot(...p), v = rr === 0 ? 0 : R.at(rr) * ang(p.map((c) => c / rr)); vals[j * n + i] = v; if (rr > 0.4 * R.peak) mx = Math.max(mx, Math.abs(v)); // brightness set by the outer lobe; the core may saturate
  }
  const bg = [11, 13, 19], pos = [111, 224, 255], neg = [255, 107, 154];
  for (let k = 0; k < n * n; k++) { const t = mx ? Math.min(1, Math.sqrt(Math.abs(vals[k]) / mx)) : 0, c = vals[k] >= 0 ? pos : neg; for (let m = 0; m < 3; m++) img.data[4 * k + m] = Math.round(bg[m] + t * (c[m] - bg[m])); img.data[4 * k + 3] = 255; }
  const off = new OffscreenCanvas(n, n); off.getContext("2d").putImageData(img, 0, 0);
  g.imageSmoothingEnabled = true; g.drawImage(off, 0, 0, cv.width, cv.height);
  g.font = "italic 13px ui-monospace, monospace"; g.fillStyle = "#c9c3b8"; g.fillText(AX[a], cv.width - 16, cv.height / 2 - 6); g.fillText(AX[b], cv.width / 2 + 6, 16);
  const bar = cv.width / (2 * L); g.fillStyle = "#e8e4dc"; g.fillRect(12, cv.height - 14, Math.min(bar, cv.width - 24), 2);
  g.font = "11px ui-monospace, monospace"; g.fillText(bar < cv.width - 24 ? "1 bohr" : `${(2 * L).toFixed(1)} bohr across`, 12, cv.height - 20);
}
