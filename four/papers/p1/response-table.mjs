/* Paper 1's table of atomic response (section 11): for closed-shell atoms and the one-s-electron alkalis of both worlds,
   the static dipole polarizability α(0), α(iω) on the Casimir–Polder nodes, the homonuclear dispersion coefficient C₆,
   Q = Σ⟨r²⟩ over the electrons, and in four dimensions the permanent C₅ = 3Q²/64 (forces.js permanentB) and the
   distance R* = C₆/C₅ inside which dispersion leads. All by atom/tools/response.mjs's coupled response (Hartree + local
   exchange, each electron's own share removed; exact for hydrogen), whose angular shares are exact for full subshells
   and for a single s electron, which is why the set is what it is.
   Convergence: the frequency quadrature (40 nodes against 80), and the radial grid (N, r₀ and r_max one at a time, each
   in its own process with ATOM4_GRID="N,r0,rmax", as convergence.mjs does); the sum rule ω²α(iω) → the electron count
   at ω = 300.
     node four/papers/p1/response-table.mjs      → data/response.json (a few minutes, 4 processes) */
import { writeFileSync, readFileSync } from "node:fs";
import { execFile } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const SET = { 3: [1, 2, 3, 4, 10, 11, 12, 18, 19, 20, 30, 36], 4: [1, 2, 3, 4, 12, 13, 14, 22, 23, 24, 42, 50, 51, 52, 78] };
export const GRIDS = [
  { label: "default", N: 700, r0: 1e-5, rmax: 150 }, { label: "N 1000", N: 1000, r0: 1e-5, rmax: 150 },
  { label: "r₀ 10⁻⁶", N: 700, r0: 1e-6, rmax: 150 }, { label: "r_max 250", N: 700, r0: 1e-5, rmax: 250 },
];
const me = fileURLToPath(import.meta.url), here = path.dirname(me);

/* Gauss–Legendre on ω = a tan θ, as response.mjs's OMEGA, with n nodes */
function nodes(n, a = 0.6) {
  const x = [], w = [];
  for (let i = 1; i <= n; i++) { let z = Math.cos((Math.PI * (i - 0.25)) / (n + 0.5)), pp = 0; for (let it = 0; it < 100; it++) { let p1 = 1, p2 = 0; for (let j = 1; j <= n; j++) { const p3 = p2; p2 = p1; p1 = ((2 * j - 1) * z * p2 - (j - 1) * p3) / j; } pp = (n * (z * p1 - p2)) / (z * z - 1); const z1 = z; z = z1 - p1 / pp; if (Math.abs(z - z1) < 1e-15) break; } x.push(z); w.push(2 / ((1 - z * z) * pp * pp)); }
  return { om: x.map((t) => a * Math.tan((Math.PI / 4) * (t + 1))), wt: x.map((t, k) => (w[k] * (Math.PI / 4) * a) / Math.cos((Math.PI / 4) * (t + 1)) ** 2) };
}
const c6 = (al, wt, d) => ((d + 3) / (2 * Math.PI)) * al.reduce((s, a, k) => s + wt[k] * a * a, 0);

if (process.argv[2] === "--child") {
  const fine = process.argv[3] === "fine", { coupledAlpha } = await import("../../atom/tools/response.mjs");
  const Q40 = nodes(40), Q80 = nodes(80), out = [];
  for (const d of [3, 4]) for (const Z of SET[d]) {
    const a = coupledAlpha(Z, d, { omegas: [0, 300, ...Q40.om] }), row = { d, Z, a0: a[0], fsum: 300 * 300 * a[1], c6: c6(a.slice(2), Q40.wt, d) };
    if (fine) { row.aw = a.slice(2); const b = coupledAlpha(Z, d, { omegas: Q80.om }); row.c6fine = c6(b, Q80.wt, d); }
    out.push(row);
  }
  process.stdout.write(JSON.stringify(out));
} else {
  const run = (g, fine) => new Promise((ok, no) => execFile(process.execPath, [me, "--child", fine ? "fine" : ""], { env: { ...process.env, ATOM4_GRID: `${g.N},${g.r0},${g.rmax}` }, maxBuffer: 1 << 26 }, (e, so) => (e ? no(e) : ok(JSON.parse(so)))));
  const t0 = Date.now(), res = await Promise.all(GRIDS.map((g, i) => run(g, i === 0)));
  const { TABLE } = await import("../../atom/js/tablec.js"), { sumR2, permanentB } = await import("../../atom/js/forces.js"), Q40 = nodes(40);
  const rows = res[0].map((r) => {
    const Q = sumR2(TABLE[r.d][r.Z - 1]), C5 = permanentB(Q, Q, r.d), alt = res.slice(1).map((x) => x.find((y) => y.d === r.d && y.Z === r.Z));
    const spread = (k) => Math.max(...alt.map((x) => Math.abs(x[k] / r[k] - 1)));
    return { D: r.d, Z: r.Z, config: TABLE[r.d][r.Z - 1].config, alpha0: +r.a0.toPrecision(6), C6: +r.c6.toPrecision(6), Q: +Q.toPrecision(6), C5: r.d === 4 ? +C5.toPrecision(6) : 0,
      Rstar: r.d === 4 ? +(r.c6 / C5).toPrecision(4) : null, sumRule: +(r.fsum / r.Z).toPrecision(4), quadrature: +Math.abs(r.c6fine / r.c6 - 1).toExponential(2),
      grid: { alpha0: +spread("a0").toExponential(2), C6: +spread("c6").toExponential(2), worst: GRIDS.slice(1).map((g, i) => ({ grid: g.label, alpha0: +(alt[i].a0 / r.a0 - 1).toExponential(2), C6: +(alt[i].c6 / r.c6 - 1).toExponential(2) })) },
      alphaIw: r.aw.map((v) => +v.toPrecision(5)) };
  });
  writeFileSync(path.join(here, "data/response.json"), JSON.stringify({ about: "Generated by papers/p1/response-table.mjs from atom/tools/response.mjs (coupled response, Hartree + local exchange); do not edit. alpha0 and C6 in atomic units; Q = Σ⟨r²⟩ (bohr²); C5 = 3Q²/64 (4D only: 1/r isn't harmonic there); Rstar = C6/C5 (bohr), inside which dispersion leads; sumRule = ω²α(iω = 300)/Z; quadrature: |C6(80 nodes)/C6(40) − 1|; grid: the largest relative change over the other grids. alphaIw on omega.", omega: Q40.om.map((w) => +w.toPrecision(6)), grids: GRIDS, rows }, null, 1) + "\n");
  for (const r of rows) console.log(r.D, String(r.Z).padStart(3), "α", r.alpha0, "C6", r.C6, "Q", r.Q, "R*", r.Rstar, "sum", r.sumRule, "quad", r.quadrature, "grid α", r.grid.alpha0, "C6", r.grid.C6);
  console.log(`${((Date.now() - t0) / 1000).toFixed(0)} s`);
}
