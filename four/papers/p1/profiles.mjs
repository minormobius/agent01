/* Paper 1's element profiles: a few 4D atoms re-solved in their baked ground configuration, with each subshell's radial
   function kept (the bake keeps only ⟨r⟩ and ⟨r²⟩ per subshell, and the total density). Each re-solve must give back
   the bake's total energy to 10⁻⁴ hartree, or the tool stops: the profile is the bake's atom, not a new one.
     node four/papers/p1/profiles.mjs      writes papers/p1/data/profiles.json (seconds to a minute)
   build.mjs draws the profile and orbital figures from that file. Re-run after a bake. */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { scf, subshells, R, N, H } from "../../atom/js/atom.js";
import { TABLE } from "../../atom/js/table.js";
import { SOLVER } from "../../atom/tools/bake.mjs";

export const PROFILED = [7, 8, 12, 26, 101, 128];
const here = path.dirname(fileURLToPath(import.meta.url)), SH = subshells(4);
const occOf = (config) => { const o = SH.map(() => 0); for (const t of config.split(" ")) { const m = t.match(/^(\d+[a-z])(\d+)$/); o[SH.findIndex((s) => s.name === m[1])] = +m[2]; } return o; };
const RS = Array.from({ length: 161 }, (_, i) => +(0.005 * 10 ** (i / 40)).toPrecision(4)); // 0.005 to 50 bohr, 40 a decade
const at = (q, r) => { const x = Math.log(r / R[0]) / H, j = Math.min(N - 2, Math.max(0, Math.floor(x))), u = x - j; return (q[j] * (1 - u) + q[j + 1] * u) / (H * r); }; // radial probability per bohr

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = { about: "Generated by papers/p1/profiles.mjs: 4D atoms re-solved in their baked configurations; each subshell's radial probability per bohr, P(r) = q/(h r), for one electron, at r (bohr). Do not edit.", r: RS, atoms: [] };
  for (const Z of PROFILED) {
    const el = TABLE[4][Z - 1], occ = occOf(el.config), t0 = Date.now();
    const g = scf(Z, occ, 4, { ...SOLVER, iters: 400 });
    if (!g.converged || Math.abs(g.E - el.E) > 1e-4) { console.error(`element ${Z}: re-solve E ${g.E} against the bake's ${el.E} (converged ${g.converged})`); process.exit(1); }
    const sub = SH.map((s, i) => ({ s, i })).filter(({ i }) => occ[i] > 0).map(({ s, i }) => ({ name: s.name, l: s.l, occ: occ[i], e: +g.es[i].toFixed(5), P: RS.map((r) => +at(g.qs[i], r).toPrecision(4)) }));
    out.atoms.push({ Z, config: el.config, E: +g.E.toFixed(5), ion: el.ion, sub });
    console.log(`element ${Z}: E ${g.E.toFixed(5)} (bake ${el.E}), ${((Date.now() - t0) / 1000).toFixed(1)} s`);
  }
  writeFileSync(path.join(here, "data/profiles.json"), JSON.stringify(out) + "\n");
}
