/* Paper 1's grid convergence (appendix C): sampled atoms re-solved in their baked configurations on other radial grids
   (one of the number of points N, the inner end r₀ and the outer end r_max changed at a time), each total energy and first
   ionization (ΔSCF from the baked outermost subshell) set against the default grid's.
     node four/papers/p1/convergence.mjs      writes papers/p1/data/convergence.json (a few minutes, 4 processes)
   Each grid runs in its own process with ATOM4_GRID="N,r0,rmax" (atom.js reads it at import; nothing else does). */
import { writeFileSync } from "node:fs";
import { execFile } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const SAMPLE = { 4: [2, 12, 13, 22, 50, 78, 128, 138], 3: [10, 18, 36] };
export const GRIDS = [
  { label: "default", N: 700, r0: 1e-5, rmax: 150 },
  { label: "N 500", N: 500, r0: 1e-5, rmax: 150 }, { label: "N 1000", N: 1000, r0: 1e-5, rmax: 150 },
  { label: "r₀ 10⁻⁴", N: 700, r0: 1e-4, rmax: 150 }, { label: "r₀ 10⁻⁶", N: 700, r0: 1e-6, rmax: 150 },
  { label: "r_max 100", N: 700, r0: 1e-5, rmax: 100 }, { label: "r_max 250", N: 700, r0: 1e-5, rmax: 250 },
];
const me = fileURLToPath(import.meta.url), here = path.dirname(me);

if (process.argv[2] === "--child") {
  const { scf, subshells } = await import("../../atom/js/atom.js"), { TABLE } = await import("../../atom/js/table.js"), { SOLVER } = await import("../../atom/tools/bake.mjs");
  const out = [];
  for (const d of [4, 3]) for (const Z of SAMPLE[d]) {
    const sh = subshells(d), el = TABLE[d][Z - 1], occ = sh.map(() => 0);
    for (const t of el.config.split(" ")) { const m = t.match(/^(\d+[a-z])(\d+)$/); occ[sh.findIndex((s) => s.name === m[1])] = +m[2]; }
    const top = sh.findIndex((s) => s.name === el.top), g = scf(Z, occ, d, { ...SOLVER, iters: 400 });
    let ion = -g.E; if (Z > 1) { const o = occ.slice(); o[top]--; ion = scf(Z, o, d, { ...SOLVER, iters: 400, start: g.qs }).E - g.E; }
    out.push({ d, Z, E: g.E, ion, converged: g.converged });
  }
  process.stdout.write(JSON.stringify(out));
} else if (process.argv[1] === me) {
  const run = (g) => new Promise((res, rej) => execFile(process.execPath, [me, "--child"], { env: { ...process.env, ATOM4_GRID: `${g.N},${g.r0},${g.rmax}` }, maxBuffer: 1 << 24 }, (e, so) => (e ? rej(e) : res({ ...g, atoms: JSON.parse(so) }))));
  const results = [], queue = GRIDS.slice(), t0 = Date.now();
  await Promise.all(Array.from({ length: 4 }, async () => { while (queue.length) { const g = queue.shift(); results.push(await run(g)); console.error(`${g.label} done`); } }));
  results.sort((a, b) => GRIDS.findIndex((g) => g.label === a.label) - GRIDS.findIndex((g) => g.label === b.label));
  const base = results[0], rows = results.slice(1).map((g) => ({ label: g.label, N: g.N, r0: g.r0, rmax: g.rmax,
    atoms: g.atoms.map((a, i) => ({ d: a.d, Z: a.Z, dE: a.E - base.atoms[i].E, dIon: a.ion - base.atoms[i].ion, converged: a.converged })) }));
  const worst = (k) => Math.max(...rows.flatMap((g) => g.atoms.map((a) => Math.abs(a[k]))));
  const summary = { maxAbs_dE: worst("dE"), maxAbs_dIon: worst("dIon"), allConverged: results.every((g) => g.atoms.every((a) => a.converged)),
    byGrid: rows.map((g) => ({ label: g.label, maxAbs_dE: Math.max(...g.atoms.map((a) => Math.abs(a.dE))), maxAbs_dIon: Math.max(...g.atoms.map((a) => Math.abs(a.dIon))) })) };
  writeFileSync(path.join(here, "data/convergence.json"), JSON.stringify({ about: "Generated by papers/p1/convergence.mjs: sampled atoms on other radial grids, each against the default (N 700, r0 1e-5, rmax 150 bohr). Hartree. Do not edit.", sample: SAMPLE, base: { N: 700, r0: 1e-5, rmax: 150, atoms: base.atoms }, summary, rows }, null, 1) + "\n");
  console.log(JSON.stringify(summary, null, 1), `${((Date.now() - t0) / 1000).toFixed(0)} s`);
}
