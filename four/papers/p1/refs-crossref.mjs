/* Paper 1's reference metadata from Crossref: for every entry of refs.json with a DOI, the publisher's record as CSL
   JSON (api.crossref.org's transform), trimmed to the fields a reference list prints. Network, so run by hand when
   refs.json gains a DOI; build.mjs reads the cache offline and fails if a DOI isn't in it.
     node four/papers/p1/refs-crossref.mjs   → data/crossref.json */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url)), OUT = join(HERE, "data/crossref.json");
const KEEP = ["type", "title", "author", "editor", "container-title", "collection-title", "volume", "issue", "page", "issued", "publisher", "publisher-place", "DOI", "edition"];
const refs = JSON.parse(readFileSync(join(HERE, "refs.json"), "utf8")).refs.filter((r) => r.doi);
const cache = existsSync(OUT) ? JSON.parse(readFileSync(OUT, "utf8")).records : {};
for (const r of refs) {
  const doi = r.doi.toLowerCase();
  if (cache[doi]) continue;
  await new Promise((ok) => setTimeout(ok, 1500)); // Crossref's public pool rate-limits bursts
  const res = await fetch(`https://api.crossref.org/works/${encodeURIComponent(r.doi)}/transform/application/vnd.citationstyles.csl+json`, { headers: { "User-Agent": "four-papers-p1-refs/1.0" } });
  if (!res.ok) { console.error(`${r.key}: ${r.doi}: HTTP ${res.status}`); process.exitCode = 1; continue; }
  const m = await res.json(), rec = {};
  for (const k of KEEP) if (m[k] != null && m[k] !== "") rec[k] = m[k];
  for (const k of ["author", "editor"]) if (rec[k]) rec[k] = rec[k].map((a) => (a.literal ? { literal: a.literal } : { family: a.family, given: a.given }));
  if (Array.isArray(rec.title)) rec.title = rec.title[0];
  if (Array.isArray(rec["container-title"])) rec["container-title"] = rec["container-title"][0];
  cache[doi] = rec; console.log(`${r.key}: ${rec.title}`);
}
writeFileSync(OUT, JSON.stringify({ about: "Generated by papers/p1/refs-crossref.mjs from api.crossref.org (CSL JSON, trimmed); do not edit. Keyed by lower-case DOI.", records: Object.fromEntries(Object.entries(cache).sort()) }, null, 1) + "\n");
console.log(`data/crossref.json: ${Object.keys(cache).length} records`);
