/* Paper 1 appendix E.2's outside check on the Hartree–Fock atom: four-dimensional helium-like ions Z = 2–10 by js/hf.js
   (Richardson from h = 0.02 and 0.01), against the two-parameter correlated (Hylleraas-type) variational energies of
   Escobar-Ruiz, Olivares-Pilón, Aquino and Cruz, J. Phys. B 54, 235002 (2021), Table I (refs.json escobar2021, read by
   the literature audit). Those include correlation, so a Hartree–Fock limit must lie above them; the gap is a lower
   bound on the size of the correlation energy, not a benchmark. No D = 4 Hartree–Fock-limit table has been obtained
   (refs loeser1986hf, its tables unread).
     node four/papers/p1/he4-check.mjs     → data/he4check.json */
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { hfAtom } from "../../atom/js/hf.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const ESCOBAR = { 2: -1.26809, 3: -3.20486, 4: -6.03008, 5: -9.744, 6: -14.3467, 7: -19.8382, 8: -26.2187, 9: -33.4879, 10: -41.6461 };
const rows = Object.entries(ESCOBAR).map(([z, ref]) => {
  const Z = +z, a = hfAtom(4, Z, [{ n: 1, l: 0, q: 2 }], { grid: { h: 0.02 } }), b = hfAtom(4, Z, [{ n: 1, l: 0, q: 2 }], { grid: { h: 0.01 } }), E = (4 * b.E - a.E) / 3;
  return { Z, hf: +E.toFixed(6), escobar2021: ref, gap: +(E - ref).toFixed(5), converged: a.converged && b.converged };
});
writeFileSync(join(HERE, "data/he4check.json"), JSON.stringify({ about: "Generated by papers/p1/he4-check.mjs; do not edit. 4D helium-like ions: Hartree–Fock (js/hf.js) against the two-parameter correlated variational energies of Escobar-Ruiz et al. 2021, Table I (hartree).", rows }, null, 1) + "\n");
for (const r of rows) console.log(JSON.stringify(r));
