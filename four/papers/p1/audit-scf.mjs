/* Paper 1's solver audit (methods, appendix C). atom.js's self-consistent field stops when the total energy changes by
   less than its tol between iterations. The plane-wave work met a stop like that leaving the far density unconverged.
   Here: each sampled atom solved in its baked configuration as the bake solved it, then driven on to a far tighter stop
   from there, and the two compared: total energy, first ionization (ΔSCF from the baked outermost subshell, both
   ways), the outermost orbital energy, and the density at 5, 10 and 20 bohr.
     node four/papers/p1/audit-scf.mjs        writes papers/p1/data/audit-scf.json (about a minute) */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { scf, subshells, R, N, H } from "../../atom/js/atom.js";
import { TABLE } from "../../atom/js/table.js";
import { SOLVER } from "../../atom/tools/bake.mjs";

export const SAMPLE = { 4: [2, 7, 12, 13, 22, 26, 50, 51, 68, 78, 101, 128, 138], 3: [2, 10, 11, 18, 26, 36] };
export const TIGHT = { tol: 1e-12, iters: 3000 };
const here = path.dirname(fileURLToPath(import.meta.url));
const occOf = (sh, config) => { const o = sh.map(() => 0); for (const t of config.split(" ")) { const m = t.match(/^(\d+[a-z])(\d+)$/); o[sh.findIndex((s) => s.name === m[1])] = +m[2]; } return o; };
const densAt = (g, occ, r) => { const x = Math.log(r / R[0]) / H, j = Math.min(N - 2, Math.floor(x)), u = x - j; let s = 0; occ.forEach((o, i) => { if (o > 0) s += o * (g.qs[i][j] * (1 - u) + g.qs[i][j + 1] * u); }); return s / (H * r); };

function audit(d, Z) {
  const sh = subshells(d), el = TABLE[d][Z - 1], occ = occOf(sh, el.config), top = sh.findIndex((s) => s.name === el.top);
  const loose = scf(Z, occ, d, { ...SOLVER, iters: 160 }), tight = scf(Z, occ, d, { ...SOLVER, ...TIGHT, start: loose.qs });
  const ion = (g, opts) => { if (Z === 1) return -g.E; const o = occ.slice(); o[top]--; return scf(Z, o, d, { ...SOLVER, ...opts, start: g.qs }).E - g.E; };
  const ionL = ion(loose, { iters: 160 }), ionT = ion(tight, TIGHT);
  const rel = (a, b) => (b === 0 ? 0 : Math.abs(a - b) / Math.abs(b));
  const S = (g) => { let t = 0; occ.forEach((o, i) => { if (o > 0) for (let j = 0; j < N; j++) t += o * g.qs[i][j] * R[j] * R[j]; }); return t; }; // Σ⟨r²⟩, the far pull's S
  return {
    d, Z, config: el.config, converged: { loose: loose.converged, tight: tight.converged },
    dE: tight.E - loose.E, dIon: ionT - ionL, dEps: tight.es[top] - loose.es[top],
    bakeE: el.E, bakeIon: el.ion, looseE: loose.E, tightE: tight.E, looseIon: ionL, tightIon: ionT,
    densRel: Object.fromEntries([5, 10, 20].map((r) => [r, rel(densAt(loose, occ, r), densAt(tight, occ, r))])),
    densTight: Object.fromEntries([5, 10, 20].map((r) => [r, densAt(tight, occ, r)])),
    S: { loose: S(loose), tight: S(tight), rel: rel(S(loose), S(tight)) }, bakeS: el.orb.reduce((t, o) => t + o.o * o.r2, 0),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rows = [];
  for (const d of [4, 3]) for (const Z of SAMPLE[d]) { const t0 = Date.now(), a = audit(d, Z); rows.push(a); console.log(`${d}D ${String(Z).padStart(3)}: ΔE ${a.dE.toExponential(1)}  Δion ${a.dIon.toExponential(1)}  Δε ${a.dEps.toExponential(1)}  ρ(10), ρ(20) ${a.densTight[10].toExponential(0)} ${a.densTight[20].toExponential(0)} off ${a.densRel[10].toExponential(0)} ${a.densRel[20].toExponential(0)}  S ${a.S.tight.toFixed(4)} off ${a.S.rel.toExponential(0)} (bake ${a.bakeS.toFixed(4)})  ${a.converged.tight ? "" : "(tight stop not reached)"} ${((Date.now() - t0) / 1000).toFixed(1)} s`); }
  const mx = (k) => Math.max(...rows.map((r) => Math.abs(r[k])));
  const summary = { maxAbs_dE: mx("dE"), maxAbs_dIon: mx("dIon"), maxAbs_dEps: mx("dEps"), maxDensRel20: Math.max(...rows.map((r) => r.densRel[20])), maxSRel: Math.max(...rows.map((r) => r.S.rel)), maxBakeSRel: Math.max(...rows.map((r) => Math.abs(r.bakeS - r.S.tight) / r.S.tight)), allTight: rows.every((r) => r.converged.tight) };
  writeFileSync(path.join(here, "data/audit-scf.json"), JSON.stringify({ about: "Generated by papers/p1/audit-scf.mjs: the bake's stop (energy change < 1e-7 Ha) against a far tighter one (1e-12, from the same field), per sampled atom. Do not edit.", tight: TIGHT, summary, rows }, null, 1) + "\n");
  console.log(JSON.stringify(summary));
}
