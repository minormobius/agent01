"""Measured ground configurations and lowest levels of Cs–Hf (Z = 55–72), from NIST's Handbook of Basic Atomic
Spectroscopic Data (Sansonetti & Martin 2005, refs.json nist-handbook), its neutral-atom level tables (<element>table5.htm).
For paper 1's lanthanide calibration of Hartree–Fock against the local exchange (atom/tools/hftable.mjs rank, D = 3).
  python3 four/papers/p1/nist-levels.py [set] [dir]   fetch the set's tables (lanthanides, light, third) → data/nist-<set>.json;
                                                      with dir, parse <dir>/<element>table5.htm instead of fetching
Each configuration's lowest listed level is kept (cm⁻¹, and eV at 8065.543937 cm⁻¹ per eV), so the measured ground and its
nearest competitors are both on file. Parent terms in parentheses and jj labels (5d3/2) are dropped from the configuration;
NIST omits the closed core, which is put back ([Kr] 4d10 5s2 5p6, and 4f14 for Lu and Hf, where NIST counts it as core)."""
import re, html, json, sys, os, urllib.request
SETS = {  # name: (first Z, element names as the Handbook spells them in its URLs) → data/nist-<name>.json
    "lanthanides": (55, "cesium barium lanthanum cerium praseodymium neodymium promethium samarium europium gadolinium terbium dysprosium holmium erbium thulium ytterbium lutetium hafnium".split()),
    "light": (4, "beryllium boron carbon nitrogen oxygen fluorine".split()),
    "third": (12, "magnesium aluminum silicon phosphorus sulfur chlorine".split()),
}
NOBLE = [(54, "1s2 2s2 2p6 3s2 3p6 3d10 4s2 4p6 4d10 5s2 5p6"), (36, "1s2 2s2 2p6 3s2 3p6 3d10 4s2 4p6"), (18, "1s2 2s2 2p6 3s2 3p6"), (10, "1s2 2s2 2p6"), (2, "1s2")]
URL = "https://physics.nist.gov/PhysRefData/Handbook/Tables/{}table5.htm"
EV = 8065.543937
def cell(c):
    c = re.sub(r"(?i)</sup>\s*<sup>", "", c); c = re.sub(r"(?i)<sup>([^<]*)</sup>", r"^\1 ", c)
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", c))).strip()
def norm(c):
    c = re.sub(r"\([^)]*\)", "", c); c = re.sub(r"(?<=[spdfg])\d+/2", "", c)
    return {f"{n}{l}": int(k or 1) for n, l, k in re.findall(r"(\d+)([spdfg])(?:\^(\d+))?", c)}
def full(Z, occ):
    o = {}  # NIST leaves out the noble-gas core below the element (and 4f14 for Lu and Hf)
    core = next(c for z, c in NOBLE if z < Z)
    for t in core.split(): o[re.match(r"\d+[a-z]", t).group()] = int(re.match(r"\d+[a-z](\d+)", t).group(1))
    if Z >= 71: o["4f"] = 14
    o.update(occ)
    key = lambda s: (int(s[:-1]), "spdfg".index(s[-1]))
    return " ".join(f"{s}{o[s]}" for s in sorted(o, key=key) if o[s])
def table(e, src):
    if src: return open(os.path.join(src, e + "table5.htm"), encoding="latin-1").read()
    return urllib.request.urlopen(urllib.request.Request(URL.format(e), headers={"User-Agent": "four-paper1-levels/1.0"})).read().decode("latin-1")
name = sys.argv[1] if len(sys.argv) > 1 else "lanthanides"; src = sys.argv[2] if len(sys.argv) > 2 else None; out = []
Z0, ELS = SETS[name]
for Z, e in zip(range(Z0, Z0 + len(ELS)), ELS):
    cfg, lev = None, {}
    for r in re.findall(r"<tr[^>]*>(.*?)</tr>", table(e, src), re.S | re.I):
        cs = [cell(c) for c in re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", r, re.S | re.I)]
        if len(cs) != 5: continue
        if cs[0]: cfg = cs[0]
        try: E = float(re.sub(r"[^\d.]", "", cs[3]))
        except ValueError: continue
        occ = norm(cfg)
        if not occ: continue
        k = full(Z, occ)
        if k not in lev or E < lev[k]["cm1"]: lev[k] = {"config": k, "cm1": E, "eV": round(E / EV, 4), "nist": cfg, "term": cs[1], "J": cs[2]}
    low = sorted(lev.values(), key=lambda x: x["cm1"])
    out.append({"Z": Z, "element": e, "config": low[0]["config"], "term": low[0]["term"], "J": low[0]["J"], "source": URL.format(e), "levels": low[:12]})
here = os.path.dirname(os.path.abspath(__file__))
json.dump({"about": f"Generated by papers/p1/nist-levels.py {name} from NIST's Handbook of Basic Atomic Spectroscopic Data (neutral-atom level tables, retrieved 2026-11-08); do not edit. config: the measured ground configuration, closed core included; levels: each configuration's lowest listed level, the twelve lowest configurations.", "rows": out},
          open(os.path.join(here, f"data/nist-{name}.json"), "w"), indent=1, ensure_ascii=False)
for r in out: print(r["Z"], r["config"], r["term"], r["J"], "| next:", "; ".join(f'{x["config"]} {x["eV"]}' for x in r["levels"][1:3]))
