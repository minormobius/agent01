#!/usr/bin/env node
// lecture-narration.mjs — what "The Minormobius Lectures" needs to speak (lecture/narration.js, GENERATED):
// the pronunciations of every word the lecturer says (the CMU dictionary, voice/lexicon.json on top, and
// EXTRA below for the names it lacks), and how long the formant voice (lib/chipvoice.js) takes to say
// each line, which is what score.js times the whole film by.
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fullLexicon } from './voice-lex.mjs';
import { speak } from '../lib/chipvoice.js';
import { OPENING, LECTURES } from '../lecture/script.js';

const EXTRA = {
  egregores: 'EH1 G R IH0 G AO2 R Z', teixcalaan: 'T EY1 SH K AH0 L AA2 N', piranesi: 'P IH2 R AH0 N EY1 Z IY0',
  severian: 'S EH0 V IH1 R IY0 AH0 N', thecla: 'TH EH1 K L AH0', autarch: 'AO1 T AA2 R K', neuromancer: 'N UH1 R OW0 M AE2 N S ER0',
  earthsea: 'ER1 TH S IY2', mobius: 'M OW1 B IY0 AH0 S', hoopy: 'HH UW1 P IY0', kakeya: 'K AA0 K EY1 AH0', erdos: 'EH1 R D AH0 SH',
  druids: 'D R UW1 IH0 D Z', dorcas: 'D AO1 R K AH0 S', gene: 'JH IY1 N', wolfe: 'W UH1 L F',
};
const here = dirname(fileURLToPath(import.meta.url)), full = { ...fullLexicon(), ...EXTRA }, LEX = {};
const all = [OPENING, ...LECTURES].flatMap((l) => l.lines);
for (const l of all) for (const w of l.say.toLowerCase().match(/[a-z]+(?:'[a-z]+)?/g)) {
  if (!full[w]) throw new Error(`not in the dictionary: ${w} (add it to EXTRA)`);
  LEX[w] = full[w];
}
const DUR = all.map((l) => { const r = speak(l.say, LEX, { rate: 8000 }); return +(r.audio.length / r.rate).toFixed(3); });
const js = `// GENERATED by studio/tools/lecture-narration.mjs: the words the lecturer says, and how long each line takes.
// Pronunciations from the CMU Pronouncing Dictionary, Copyright (C) 1993-2015 Carnegie Mellon University. BSD-2-Clause.
export const DUR = ${JSON.stringify(DUR)};
export const LEXICON = ${JSON.stringify(Object.fromEntries(Object.entries(LEX).sort()), null, 0).replace(/","/g, '",\n  "')};
`;
writeFileSync(join(here, '..', 'lecture', 'narration.js'), js);
console.log(`${all.length} lines, ${Object.keys(LEX).length} words, ${DUR.reduce((a, b) => a + b, 0).toFixed(0)} s spoken`);
