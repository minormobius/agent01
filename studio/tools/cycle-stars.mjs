#!/usr/bin/env node
// cycle-stars.mjs — writes studio/cycle/stars.js from d3-celestial's star and constellation data.
//
// Source: https://github.com/ofrohn/d3-celestial (data/stars.6.json, data/constellations.lines.json),
// Copyright (c) 2015 Olaf Frohn, BSD 3-clause; the notice is carried into the output. Stars to
// magnitude 5.5 (a dark-sky naked-eye limit, 2851 stars): RA, Dec (degrees, J2000), V magnitude, B−V.
//
//   node studio/tools/cycle-stars.mjs <dir with the two json files>
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) { console.error('usage: cycle-stars.mjs <dir>'); process.exit(1); }
const stars = JSON.parse(readFileSync(join(dir, 'stars.6.json'), 'utf8')).features
  .filter((f) => f.properties.mag <= 5.5)
  .sort((a, b) => a.properties.mag - b.properties.mag);
const ra = (x) => ((x % 360) + 360) % 360;
const S = stars.map((f) => {
  const [r, d] = f.geometry.coordinates, bv = parseFloat(f.properties.bv);
  return `${ra(r).toFixed(3)},${d.toFixed(3)},${f.properties.mag.toFixed(2)},${Number.isFinite(bv) ? bv.toFixed(2) : '0.6'}`;
});
const lines = JSON.parse(readFileSync(join(dir, 'constellations.lines.json'), 'utf8')).features.flatMap((f) =>
  f.geometry.coordinates.map((poly) => `[${poly.map(([r, d]) => `${ra(r).toFixed(2)},${d.toFixed(2)}`).join(',')}]`));
const out = `// stars.js — GENERATED by studio/tools/cycle-stars.mjs; do not edit.
//
// Stars to magnitude 5.5 and the constellation figures, from d3-celestial
// (https://github.com/ofrohn/d3-celestial), under this licence:
//
${readFileSync(join(dir, 'LICENSE'), 'utf8').trim().split('\n').map((l) => `//   ${l}`).join('\n')}

/** [ra°, dec°, V mag, B−V] × ${S.length}, J2000, brightest first. */
export const STARS = [${S.join(',')}];
export const N = ${S.length};
/** Constellation figures: polylines of [ra°, dec°, ra°, dec°, …]. */
export const LINES = [${lines.join(',')}];
`;
writeFileSync(new URL('../cycle/stars.js', import.meta.url), out);
console.log(`stars.js: ${S.length} stars, ${lines.length} figure lines, ${(out.length / 1024).toFixed(0)} KB`);
