// nobody-history.mjs — the history behind "Nobody Drew It" (studio/nobody): one evolved world, recorded.
//
//   node studio/tools/nobody-history.mjs                               (~17 min) → studio/nobody/history.js
//   node studio/tools/nobody-history.mjs grew 0,150000,300000,950000   → studio/grew/history.js
// (both GENERATED; the second is "And Still It Grew"'s, with a fourth snapshot)
//
// Grown's world (packages/attractor/lib/organism.js), seed 1, the three founders ×3, mutation 0.3,
// predation and drifting veins on: the run in which Quul (a gut body trailing four mouths) came to
// fill the world. It keeps three snapshots the film replays from (the founders; step 300,000, the
// predators' world; step 950,000, Quul's), and a census every 2000 steps: every species' count, for
// the time-lapse between them (the most successful 18 by name, the rest together).
import { writeFileSync } from 'node:fs';
import { World, GENOMES, signature, WX, WY, WZ } from '../../packages/attractor/lib/organism.js';

const DIR = process.argv[2] || 'nobody', SNAPS = (process.argv[3] || '0,300000,950000').split(',').map(Number), END = Math.max(...SNAPS), EVERY = 2000;
const W = new World(1, { cap: 60, mutate: 0.3 });
['grazer', 'reef', 'swimmer'].forEach((n, i) => { for (let k = 0; k < 3; k++) { const a = (i * 3 + k) / 9 * 6.283; W.add(GENOMES[n], [WX / 2 + Math.cos(a) * 45, WY / 2, WZ / 2 + Math.sin(a) * 45], a, 4); } });
const snaps = [], census = [], t0 = Date.now();
for (let s = 0; s <= END; s++) {
  if (s) W.step();
  if (SNAPS.includes(s)) { W.census(); snaps.push(W.snapshot()); console.log(`snapshot at ${s}: ${W.bodies.length} bodies`); }
  if (s % EVERY === 0) { const c = W.census(), row = {}; for (const [sig, x] of Object.entries(c)) row[sig] = x.count; census.push(row); }
  if (s % 100000 === 0 && s) console.log(`${s} · ${((Date.now() - t0) / 1000).toFixed(0)} s`);
}
// the species of the time-lapse: the 18 that filled the most of it, in order of first appearance
const lives = {}; for (const row of census) for (const [sig, n] of Object.entries(row)) lives[sig] = (lives[sig] || 0) + n;
const top = Object.keys(lives).sort((a, b) => lives[b] - lives[a]).slice(0, 18);
const first = (sig) => census.findIndex((r) => r[sig]);
top.sort((a, b) => first(a) - first(b));
const species = top.map((sig) => ({ sig, name: W.book[sig].name, first: first(sig) * EVERY, lives: lives[sig] }));
const rows = census.map((r) => [...top.map((sig) => r[sig] || 0), Object.entries(r).filter(([sig]) => !top.includes(sig)).reduce((a, [, n]) => a + n, 0)]);
const out = `// GENERATED by studio/tools/nobody-history.mjs ${DIR}: one evolved world (Grown's, seed 1), recorded. Do not edit.\nexport const HISTORY = ${JSON.stringify({ every: EVERY, species, rows, snaps: SNAPS })};\nexport const SNAPSHOTS = ${JSON.stringify(snaps)};\n`;
writeFileSync(new URL(`../${DIR}/history.js`, import.meta.url), out);
console.log(`wrote studio/${DIR}/history.js (${(out.length / 1024).toFixed(0)} KB): ${species.map((x) => x.name).join(', ')}`);
