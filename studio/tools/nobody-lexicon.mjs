#!/usr/bin/env node
// nobody-lexicon.mjs [dir] — the pronunciations a piece sings (nobody/: "Nobody Drew It"; grew/: "And Still It Grew"), cut from the CMU dictionary
// (voice/cmudict.txt, with voice/lexicon.json's hand readings on top) into nobody/lexicon.js,
// so the page need not fetch 3.6 MB to sing forty words.
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fullLexicon } from './voice-lex.mjs';
const DIR = process.argv[2] || 'nobody';
const S = await import(`../${DIR}/score.js`);
const songs = [S.song, ...(S.harmonySong ? [S.harmonySong] : [])];

const here = dirname(fileURLToPath(import.meta.url)), full = fullLexicon(), out = {};
for (const l of songs.flatMap((x) => x.lines)) for (const w of l.lyric.toLowerCase().replace(/-/g, '').match(/[a-z']+/g)) {
  if (!full[w]) throw new Error(`not in the dictionary: ${w}`);
  out[w] = full[w];
}
const sorted = Object.fromEntries(Object.entries(out).sort());
writeFileSync(join(here, '..', DIR, 'lexicon.js'), `// GENERATED by studio/tools/nobody-lexicon.mjs ${DIR}: the words "${S.title}" sings.\n// Pronunciations from the CMU Pronouncing Dictionary, Copyright (C) 1993-2015 Carnegie Mellon University. BSD-2-Clause.\nexport const LEXICON = ${JSON.stringify(sorted, null, 0).replace(/","/g, '",\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, ',\n}')};\n`);
console.log(`${Object.keys(sorted).length} words`);
