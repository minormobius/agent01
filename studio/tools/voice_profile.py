#!/usr/bin/env python3
"""voice_profile.py - distil the reference voice into a profile the formant voice can use.

    python3 studio/tools/voice_profile.py <reference dir> <measured.json> studio/lib/chipvoice-profile.js

Vowel formants come from the phonetics kit's h_d words ("Say heed again"), measured with Praat's
Burg tracker (parselmouth) in the middle of the vowel, between the h's and the d's character
timings. A value that fails a sanity check (an F1 under 250 Hz is the fundamental, not F1) is
left out, and the textbook value stays. Durations per phoneme and the voice's pitch come from
voice_measure.py's alignment of every recording (measured.json).
"""
import json, sys
import numpy as np
import parselmouth

ref, measured, out = sys.argv[1:4]
KIT = ['IY heed', 'IH hid', 'EY hayed', 'EH head', 'AE had', 'AA hod', 'AO hawed', 'OW hoed', 'UH hood', "UW who'd", 'AH hud', 'ER heard', 'AY hide', "AW how'd", 'OY hoyed']
vowels = {}
for i, nm in enumerate(KIT):
    p, w = nm.split()
    a = json.load(open(f'{ref}/x{i + 1}.json'))['alignment']; t = ''.join(a['characters'])
    s0 = t.index(w); s1 = s0 + len(w) - 1
    t0, t1 = a['character_end_times_seconds'][s0], a['character_start_times_seconds'][s1]
    F = parselmouth.Sound(f'{ref}/x{i + 1}.wav').to_formant_burg(time_step=0.005, max_number_of_formants=5, maximum_formant=5000)
    def at(u): return [F.get_value_at_time(q, t0 + u * (t1 - t0)) for q in (1, 2, 3)]
    def med(us):
        v = np.array([at(u) for u in us]); m = np.nanmedian(v, axis=0)
        return [round(float(x)) for x in m]
    mid, start, end = med(np.linspace(0.35, 0.65, 7)), med([0.15, 0.2, 0.25]), med([0.75, 0.8, 0.85])
    ok = lambda f: f[0] >= 250 and f[0] < 1100 and f[1] > f[0] + 200 and f[2] > f[1] + 150
    entry = {}
    if ok(mid): entry['F'] = mid
    if p in ('EY', 'AY', 'AW', 'OY', 'OW') and ok(start) and ok(end): entry['F'], entry['F2'] = start, end
    if entry: vowels[p] = entry
m = json.load(open(measured))
dur = {p: {k: round(v[k]) for k in ('dur', 'dur_stressed', 'dur_unstressed') if v.get(k)} for p, v in m['phones'].items()}
v = m['voice']
profile = {'source': 'ElevenLabs voice NkiasLzNGB7MWA6gNgU4 (candidate 2c, picked by the owner), measured 2026-09-25',
           'f0': v['f0_median'], 'range': round(float(np.log(v['f0_p90'] / v['f0_p10'])), 2), 'phones_per_sec': v['phones_per_sec'],
           'vowels': vowels, 'durations': dur}
open(out, 'w').write('// chipvoice-profile.js — GENERATED by studio/tools/voice_profile.py from the reference voice.\n'
                     '// What lib/chipvoice.js uses in place of its textbook tables when VOICE.profile is 1.\n'
                     f'export const PROFILE = {json.dumps(profile, indent=1)};\n')
print(json.dumps({k: profile[k] for k in ('f0', 'range', 'phones_per_sec')}), '\nvowels measured:', {k: v for k, v in vowels.items()})
