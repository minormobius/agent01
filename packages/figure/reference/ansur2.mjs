#!/usr/bin/env node
// ansur2.mjs — derive the body-proportion reference (lib/ansur2.js) from ANSUR II.
//
// ANSUR II (US Army Natick, 2012; public release) measured 93 dimensions on
// 4,082 men and 1,986 women. The raw CSVs are public domain; one mirror that
// carries both sexes in one file, with a gender column, is
// https://calmcode.io/static/data/ergonomics.csv (the official files are listed
// at https://www.openlab.psu.edu/ansur2/).
//
//   node reference/ansur2.mjs ergonomics.csv > lib/ansur2.js
// (a JS module, not JSON, so the browser copy imports it without import attributes)
//
// Every ratio is [5th percentile, median, 95th percentile], per sex. Heights are
// in HEAD UNITS below the chin, like the rig. ANSUR does not measure head height
// (vertex to menton), so it is estimated as 1.92 × the menton–sellion length
// (chin to the bridge of the nose), the ratio of the two in the NASA
// anthropometry tables (≈ 232 / 121 mm for men). That estimate is the weakest
// link here: it shifts every head-unit number together, not their ratios.
import fs from 'node:fs';

const [header, ...lines] = fs.readFileSync(process.argv[2], 'utf8').trim().split('\n');
const cols = header.split(',');
const rows = lines.map((l) => Object.fromEntries(l.split(',').map((v, i) => [cols[i], v])));
const q = (vals) => { const v = [...vals].sort((a, b) => a - b), n = v.length; return [v[Math.floor(n * 0.05)], v[n >> 1], v[Math.floor(n * 0.95)]].map((x) => +x.toFixed(3)); };
const corr = (a, b) => { const n = a.length, ma = a.reduce((s, x) => s + x) / n, mb = b.reduce((s, x) => s + x) / n; let c = 0, va = 0, vb = 0; for (let i = 0; i < n; i++) { c += (a[i] - ma) * (b[i] - mb); va += (a[i] - ma) ** 2; vb += (b[i] - mb) ** 2; } return +(c / Math.sqrt(va * vb)).toFixed(3); };
const out = {};
for (const sex of ['Male', 'Female']) {
  const R = rows.filter((r) => r.gender === sex), f = (r, k) => Number(r[k]);
  const H = R.map((r) => f(r, 'mentonsellionlength') * 1.92);
  const m = { heads_tall: q(R.map((r, i) => f(r, 'stature') / H[i])) };
  for (const [name, key] of [['suprasternale', 'suprasternaleheight'], ['cervicale', 'cervicaleheight'], ['acromion', 'acromialheight'], ['chest', 'chestheight'], ['waist', 'waistheightomphalion'], ['trochanter', 'trochanterionheight'], ['crotch', 'crotchheight'], ['buttock', 'buttockheight'], ['knee', 'kneeheightmidpatella']])
    m[`${name}_below_chin`] = q(R.map((r, i) => (f(r, 'stature') - f(r, key)) / H[i] - 1));
  const ratio = (a, b) => q(R.map((r) => f(r, a) / f(r, b)));
  Object.assign(m, {
    waist_to_hip_breadth: ratio('waistbreadth', 'hipbreadth'), bideltoid_to_hip_breadth: ratio('bideltoidbreadth', 'hipbreadth'),
    chest_to_hip_breadth: ratio('chestbreadth', 'hipbreadth'), buttock_to_waist_depth: ratio('buttockdepth', 'waistdepth'),
    chest_to_waist_depth: ratio('chestdepth', 'waistdepth'), neck_circ_to_head: q(R.map((r, i) => f(r, 'neckcircumference') / H[i])),
    hip_breadth_heads: q(R.map((r, i) => f(r, 'hipbreadth') / H[i])), bideltoid_heads: q(R.map((r, i) => f(r, 'bideltoidbreadth') / H[i])),
    thigh_circ_to_hip_breadth: ratio('thighcircumference', 'hipbreadth'),
  });
  const cd = R.map((r) => f(r, 'chestdepth') / f(r, 'stature')), cb = R.map((r) => f(r, 'chestbreadth') / f(r, 'stature')), wd = R.map((r) => f(r, 'waistdepth') / f(r, 'stature'));
  m.r_chestdepth_chestbreadth = corr(cd, cb);
  // the chest's projection past the waist (a bust proxy) against the ribcage's breadth:
  // for women, r ≈ 0 — how much bust is independent of how broad the frame is
  m.r_projection_vs_chestbreadth = corr(cd.map((x, i) => x - wd[i]), cb);
  m.n = R.length;
  out[sex.toLowerCase()] = m;
}
console.log('// ansur2.js — GENERATED by reference/ansur2.mjs from ANSUR II; do not edit.\n// Body proportions of 6,068 US Army personnel, in heads (see that script).\nexport default ' + JSON.stringify(out, null, 1) + ';');
