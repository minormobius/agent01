// evolve.mjs — run Grown's world with mutation on, for a long time, headless; keep the bestiary.
//
//   node packages/attractor/tools/evolve.mjs [steps=1000000] [seed=1] [--json out.json] [--write]
//   node packages/attractor/tools/evolve.mjs --merge a.json b.json …      (→ lib/evolved.js)
//
// The world starts with three of each hand-written body, with predation and drifting veins. Every
// child has a chance (`MUTATE`) of a mutated program; a mutation that changes the organ tree is a new
// species. There is no fitness function: what feeds buds, what doesn't starves or is eaten. If
// everything dies, the founders are put back (and that is counted). Every 2000 steps a census is
// taken; a species' "lives" is the sum of its counts over censuses (how much of the world's history
// it filled). --json keeps a run's summary; --merge (or --write, for this one run) writes the top
// evolved plans across runs to lib/evolved.js, which the page seeds worlds from.
import { writeFileSync, readFileSync } from 'node:fs';
import { World, GENOMES, WX, WY, WZ } from '../lib/organism.js';

const argv = process.argv.slice(2), flag = (k) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : null; };
const MUTATE = 0.3;

function merge(runs) {
  // the best plans across runs: by lives, a plan (signature) once, the founders left out
  const seen = new Set(), keep = [];
  for (const r of runs.flatMap((run) => run.book.map((b) => ({ ...b, seed: run.seed }))).sort((a, b) => b.lives - a.lives)) {
    if (GENOMES[r.name] || seen.has(r.sig)) continue; seen.add(r.sig); keep.push(r);
    if (keep.length >= 24) break;
  }
  const out = `// GENERATED by packages/attractor/tools/evolve.mjs (${runs.length} run${runs.length > 1 ? 's' : ''}, mutation ${MUTATE}). Do not edit.\n// The body plans that evolved and filled the most of their worlds' histories (the founders left out).\nexport const EVOLVED = ${JSON.stringify(keep)};\nexport const RUNS = ${JSON.stringify(runs.map(({ book, ...r }) => r))};\n`;
  writeFileSync(new URL('../lib/evolved.js', import.meta.url), out);
  console.log(`wrote lib/evolved.js: ${keep.length} plans from ${runs.length} runs`);
}

if (argv.includes('--merge')) {
  merge(argv.filter((a) => a.endsWith('.json')).map((f) => JSON.parse(readFileSync(f, 'utf8'))));
} else {
  const pos = argv.filter((a, i) => !a.startsWith('--') && !(argv[i - 1] || '').startsWith('--json'));
  const steps = +(pos[0] || 1000000), seed = +(pos[1] || 1);
  const W = new World(seed, { cap: 60, mutate: MUTATE });
  const found = () => ['grazer', 'reef', 'swimmer'].forEach((n, i) => { for (let k = 0; k < 3; k++) { const a = (i * 3 + k) / 9 * 6.283; W.add(GENOMES[n], [WX / 2 + Math.cos(a) * 45, WY / 2, WZ / 2 + Math.sin(a) * 45], a, 4); } });
  found();
  let reseeds = 0; const t0 = Date.now(), timeline = [], causes = {};
  for (let k = 1; k <= steps; k++) {
    W.step();
    if (W.bodies.length === 0) { reseeds++; found(); }
    if (k % 2000 === 0) {
      const c = W.census(), top = Object.entries(c).sort((a, b) => b[1].count - a[1].count);
      for (const d of W.dead) causes[d.cause] = (causes[d.cause] || 0) + 1; W.dead.length = 0;
      if (k % 10000 === 0) timeline.push({ s: k, alive: W.bodies.length, plans: top.length, top: top.slice(0, 3).map(([sig, x]) => [x.name, x.count, sig]) });
      if (k % 50000 === 0) console.log(`${k} · ${W.bodies.length} alive in ${top.length} plans · ${top.slice(0, 4).map(([sig, x]) => `${x.name} ${x.count} ${sig}`).join(' · ')} · mutants ${W.mutants} · deaths ${JSON.stringify(causes)} · ${((Date.now() - t0) / 1000).toFixed(0)} s`);
    }
  }
  const book = Object.values(W.book).sort((a, b) => b.lives - a.lives);
  console.log(`\nseed ${seed}: ${book.length} body plans ever lived; the most successful:`);
  for (const r of book.slice(0, 15)) console.log(`${r.name.padEnd(12)} lives ${String(r.lives).padStart(6)}  peak ${String(r.peak).padStart(3)}  first ${r.first}  last ${r.last}  hunt ${(r.genome.beat.hunt || 0).toFixed(2)}  ${r.sig}`);
  const run = { seed, steps, mutate: MUTATE, reseeds, mutants: W.mutants, plans: book.length, causes, timeline, book: book.slice(0, 60).map((r) => ({ name: r.name, sig: r.sig, lives: r.lives, peak: r.peak, first: r.first, last: r.last, from: r.genome.from || null, genome: r.genome })) };
  if (flag('--json')) writeFileSync(flag('--json'), JSON.stringify(run));
  if (argv.includes('--write')) merge([run]);
}
