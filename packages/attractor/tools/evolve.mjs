// evolve.mjs — run Grown's world with mutation on, for a long time, headless; keep the bestiary.
//
//   node packages/attractor/tools/evolve.mjs [steps=400000] [seed=1] [--write]
//
// The world starts with three of each hand-written body. Every child has a chance (`mutate`) of a
// mutated program; a mutation that changes the organ tree is a new species. There is no fitness
// function: what feeds buds, what doesn't starves. If everything dies, the founders are put back
// (and that is counted). Every 2000 steps a census is taken; a species' "lives" is the sum of its
// counts over censuses (how much of the world's history it filled). --write keeps the top body
// plans, with their programs, in lib/evolved.js, which the page can seed a world from.
import { writeFileSync } from 'node:fs';
import { World, GENOMES, signature, WX, WY, WZ } from '../lib/organism.js';

const args = process.argv.slice(2).filter((a) => !a.startsWith('--')), write = process.argv.includes('--write');
const steps = +(args[0] || 400000), seed = +(args[1] || 1), MUTATE = 0.3;
const W = new World(seed, { cap: 60, mutate: MUTATE });
const found = () => ['grazer', 'reef', 'swimmer'].forEach((n, i) => { for (let k = 0; k < 3; k++) { const a = (i * 3 + k) / 9 * 6.283; W.add(GENOMES[n], [WX / 2 + Math.cos(a) * 45, WY / 2, WZ / 2 + Math.sin(a) * 45], a, 4); } });
found();
let reseeds = 0; const t0 = Date.now(), timeline = [];
for (let k = 1; k <= steps; k++) {
  W.step();
  if (W.bodies.length === 0) { reseeds++; found(); }
  if (k % 2000 === 0) {
    const c = W.census(), top = Object.entries(c).sort((a, b) => b[1].count - a[1].count);
    timeline.push({ s: k, alive: W.bodies.length, plans: top.length, top: top.slice(0, 3).map(([sig, x]) => [x.name, x.count]) });
    if (k % 20000 === 0) console.log(`${k} · ${W.bodies.length} alive in ${top.length} plans · ${top.slice(0, 4).map(([sig, x]) => `${x.name} ${x.count} ${sig}`).join(' · ')} · mutants ${W.mutants} · reseeds ${reseeds} · ${((Date.now() - t0) / 1000).toFixed(0)} s`);
  }
}
const book = Object.values(W.book).sort((a, b) => b.lives - a.lives);
console.log(`\n${book.length} body plans ever lived; the most successful:`);
for (const r of book.slice(0, 15)) console.log(`${r.name.padEnd(12)} lives ${String(r.lives).padStart(6)}  peak ${String(r.peak).padStart(3)}  first ${r.first}  last ${r.last}  ${r.sig}`);
if (write) {
  const keep = book.filter((r) => !GENOMES[r.name]).slice(0, 16).map((r) => ({ name: r.name, sig: r.sig, lives: r.lives, peak: r.peak, first: r.first, last: r.last, from: r.genome.from || null, genome: r.genome }));
  const out = `// GENERATED by packages/attractor/tools/evolve.mjs (${steps} steps, seed ${seed}, mutation ${MUTATE}). Do not edit.\n// The body plans that evolved and filled the most of the world's history (the founders left out).\nexport const EVOLVED = ${JSON.stringify(keep)};\nexport const RUN = ${JSON.stringify({ steps, seed, mutate: MUTATE, reseeds, mutants: W.mutants, plans: book.length, timeline: timeline.filter((_, i) => i % 5 === 0) })};\n`;
  writeFileSync(new URL('../lib/evolved.js', import.meta.url), out);
  console.log('wrote lib/evolved.js');
}
