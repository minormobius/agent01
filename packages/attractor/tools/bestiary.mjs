#!/usr/bin/env node
// bestiary.mjs — search the quadratic flows and keep what is strange: lib/bestiary.js, a catalogue of
// codes with their shape (extents, correlation dimension, Lyapunov exponent, fill). The avatar picks its
// parts from here by fit; the page can still search for new ones live.
//
//   node packages/attractor/tools/bestiary.mjs [count=240] [firstSeed=1]
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { discover, NAMED, realise, dimension, lyapunov } from '../lib/space.js';

const here = dirname(fileURLToPath(import.meta.url));
const count = Number(process.argv[2] || 240), first = Number(process.argv[3] || 1);
const out = [], seen = new Set(), t0 = Date.now();
const r3 = (v) => Math.round(v * 1000) / 1000;
for (const k of Object.keys(NAMED)) {
  const r = realise(k, 12000), A = NAMED[k];
  out.push({ key: k, ext: r.ext.map(r3), dim: r3(dimension(r)), lyap: r3(lyapunov(A.f, A.x0, A.dt, 4000)), fill: r3(r.fill) });
}
for (let s = first; out.length < count + Object.keys(NAMED).length; s++) {
  const r = discover(s, { n: 12000 });
  if (!r || seen.has(r.code)) continue;
  seen.add(r.code);
  out.push({ key: r.code, ext: r.ext.map(r3), dim: r3(r.dim), lyap: r3(r.lyap), fill: r3(r.fill), seed: s });
  if (out.length % 20 === 0) console.log(`${out.length} (${((Date.now() - t0) / 1000).toFixed(0)} s)`);
}
writeFileSync(join(here, '..', 'lib', 'bestiary.js'), `// GENERATED by tools/bestiary.mjs: strange attractors found in the quadratic flows (and the named ones).
// key: a NAMED flow or a 30-letter coefficient code (space.js); ext: principal extents (longest 1);
// dim: correlation dimension; lyap: largest Lyapunov exponent; fill: share of its box it occupies.
export const BESTIARY = [\n${out.map((b) => '  ' + JSON.stringify(b)).join(',\n')},\n];\n`);
console.log(`${out.length} in ${((Date.now() - t0) / 1000).toFixed(0)} s`);
