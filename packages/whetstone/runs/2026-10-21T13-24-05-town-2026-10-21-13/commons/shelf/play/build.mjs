// node shelf/play/build.mjs : copies core.mjs to www/jams/core.js and builds house/api/play.mjs
// from route-head.mjs + wander-twin.mjs + core.mjs + route-body.mjs. Edit those, not the outputs.
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('.', import.meta.url).pathname, root = here + '../../';
const r = f => readFileSync(here + f, 'utf8');
writeFileSync(root + 'www/jams/core.js', '// COPY of shelf/play/core.mjs (shelf/play/build.mjs). Edit there.\n' + r('core.mjs'));
writeFileSync(root + 'house/api/play.mjs', '// GENERATED by shelf/play/build.mjs from shelf/play/. Edit the parts there, not this file.\n'
  + r('route-head.mjs') + '\n// ---- wander twin (shelf/play/wander-twin.mjs) ----\n' + r('wander-twin.mjs')
  + '\n// ---- core (shelf/play/core.mjs) ----\n' + r('core.mjs') + '\n// ---- route (shelf/play/route-body.mjs) ----\n' + r('route-body.mjs'));
console.log('built www/jams/core.js and house/api/play.mjs');
