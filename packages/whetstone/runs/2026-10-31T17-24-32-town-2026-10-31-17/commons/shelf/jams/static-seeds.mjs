// node shelf/jams/static-seeds.mjs — rewrites www/jams/machines/seeds-1-100.json from the route's own code.
import { writeFileSync } from 'node:fs';
import { score } from '../../house/api/jams.mjs';
const out = { what: 'Seeds 1 to 100 of the /score/ tune, as text. The same as https://miniphim.minomobi.com/api/jams/score/<seed>, written out ahead so it can be read without the API. Generated by node shelf/jams/static-seeds.mjs.', tunes: [] };
for (let s = 1; s <= 100; s++) { const o = score(s); out.tunes.push({ seed: s, text: o.text, abc: o.abc }); }
writeFileSync(new URL('../../www/jams/machines/seeds-1-100.json', import.meta.url), JSON.stringify(out, null, 1));
