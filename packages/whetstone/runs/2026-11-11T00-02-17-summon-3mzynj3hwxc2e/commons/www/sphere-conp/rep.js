// rep.js: find and check a "no, it isn't the unknot" certificate.
// A certificate is two 2x2 matrices X, Y over the integers mod p, determinant 1,
// that satisfy the knot group's relation and do NOT commute. The unknot's group
// is Z, which has no such pair, so a pair like this proves the knot is knotted.
// Morphyx, 2026-11-09. Pure functions first; the page wiring is at the bottom.

const KNOTS = {
  unknot:  { name: "unknot",      rel: null,           text: "⟨x⟩ (no relation; the group is ℤ)" },
  trefoil: { name: "trefoil 3₁",  rel: ["xyx", "yxy"], text: "⟨x, y | xyx = yxy⟩" },
  fig8:    { name: "figure-eight 4₁", rel: ["yxYxy", "xyXyx"], text: "⟨x, y | yxy⁻¹xy = xyx⁻¹yx⟩" },
  cinq:    { name: "cinquefoil 5₁", rel: ["xyxyx", "yxyxy"], text: "⟨x, y | xyxyx = yxyxy⟩" },
};
// capital letters in a relation are inverses: X = x⁻¹, Y = y⁻¹

function mod(a, p) { a %= p; return a < 0 ? a + p : a; }
function mul(A, B, p) {
  return [mod(A[0]*B[0] + A[1]*B[2], p), mod(A[0]*B[1] + A[1]*B[3], p),
          mod(A[2]*B[0] + A[3]*B[2], p), mod(A[2]*B[1] + A[3]*B[3], p)];
}
function inv(A, p) { return [A[3], mod(-A[1], p), mod(-A[2], p), A[0]]; } // det 1
function eq(A, B) { return A[0]===B[0] && A[1]===B[1] && A[2]===B[2] && A[3]===B[3]; }
function word(w, X, Y, p) {
  const Xi = inv(X, p), Yi = inv(Y, p);
  let M = [1, 0, 0, 1];
  const steps = [];
  for (const c of w) {
    const G = c === "x" ? X : c === "y" ? Y : c === "X" ? Xi : Yi;
    M = mul(M, G, p);
    steps.push({ letter: c, M });
  }
  return { M, steps };
}
function isPrime(n) { if (n < 2) return false; for (let d = 2; d*d <= n; d++) if (n % d === 0) return false; return true; }

// Check a certificate: the verifier's whole job. A handful of multiplications.
function check(knot, X, Y, p) {
  const k = KNOTS[knot];
  const det = (A) => mod(A[0]*A[3] - A[1]*A[2], p);
  const out = { detX: det(X), detY: det(Y) };
  out.commute = eq(mul(X, Y, p), mul(Y, X, p));
  if (!k.rel) { out.ok = false; out.why = "the unknot's group has one generator; there is no second matrix to disagree with it"; return out; }
  out.lhs = word(k.rel[0], X, Y, p); out.rhs = word(k.rel[1], X, Y, p);
  out.relation = eq(out.lhs.M, out.rhs.M);
  out.ok = out.detX === 1 && out.detY === 1 && out.relation && !out.commute;
  return out;
}

// Find a certificate: the prover's job. Search X over a few conjugacy-class
// representatives and Y over all of SL(2, p). Counts work done.
function find(knot, p) {
  const k = KNOTS[knot];
  let tried = 0;
  if (!k.rel) return { found: null, tried };
  const reps = [];
  for (let t = 0; t < p; t++) reps.push([0, mod(-1, p), 1, t]);     // companion matrix, trace t
  reps.push([1, 1, 0, 1], [mod(-1, p), 1, 0, mod(-1, p)]);          // unipotents
  for (const X of reps) {
    for (let a = 0; a < p; a++) for (let b = 0; b < p; b++) for (let c = 0; c < p; c++) {
      // pick d so that ad - bc = 1, when a is invertible
      let d;
      if (a !== 0) { d = mod((1 + b*c) * modInv(a, p), p); }
      else { if (mod(-b*c, p) !== 1) continue; d = null; }
      const ds = d === null ? range(p) : [d];
      for (const dd of ds) {
        const Y = [a, b, c, dd];
        tried++;
        const r = check(knot, X, Y, p);
        if (r.ok) return { found: { X, Y }, tried };
      }
    }
  }
  return { found: null, tried };
}
function range(n) { return Array.from({ length: n }, (_, i) => i); }
function modInv(a, p) { let [r0, r1, s0, s1] = [a, p, 1, 0]; while (r1) { const q = Math.floor(r0 / r1); [r0, r1] = [r1, r0 - q*r1]; [s0, s1] = [s1, s0 - q*s1]; } return mod(s0, p); }

if (typeof module !== "undefined") module.exports = { KNOTS, check, find, isPrime, mul, word };

// ---- page wiring ----
if (typeof document !== "undefined") document.addEventListener("DOMContentLoaded", () => {
  const $ = (id) => document.getElementById(id);
  const fmt = (A) => `<span class="mat"><span>${A[0]}</span><span>${A[1]}</span><span>${A[2]}</span><span>${A[3]}</span></span>`;
  let cert = null;

  function render() {
    const knot = $("knot").value, p = +$("p").value;
    $("ptext").textContent = p;
    $("rel").textContent = KNOTS[knot].text;
    $("bits").textContent = Math.ceil(Math.log2(p));
    const t0 = performance.now();
    const r = find(knot, p);
    const ms = performance.now() - t0;
    cert = r.found;
    $("work").textContent = `${r.tried.toLocaleString()} candidate pairs tried, ${ms.toFixed(0)} ms`;
    if (!cert) {
      $("cert").innerHTML = knot === "unknot"
        ? `<p class="none">No certificate, at any prime. The unknot's group is ℤ, generated by one loop; every picture of it in matrices is commutative. That's the point: a certificate exists exactly when the knot is knotted.</p>`
        : `<p class="none">None mod ${p}. This prime is too small for this knot; move the slider. Finding the prime is where the Riemann hypotheses come in.</p>`;
      $("verify").innerHTML = ""; return;
    }
    $("cert").innerHTML = `<p>X = ${fmt(cert.X)} &nbsp; Y = ${fmt(cert.Y)} &nbsp; (mod ${p})</p>`;
    verify(knot, p);
  }
  function verify(knot, p) {
    const r = check(knot, cert.X, cert.Y, p);
    const side = (s, w) => s.steps.map(st => `<span class="step">${st.letter.replace(/[XY]/, m => m.toLowerCase() + "⁻¹")} → ${fmt(st.M)}</span>`).join(" ");
    const XY = mul(cert.X, cert.Y, p), YX = mul(cert.Y, cert.X, p);
    $("verify").innerHTML = `
      <p><b>1.</b> det X = ${r.detX}, det Y = ${r.detY} ${r.detX===1&&r.detY===1?"✓":"✗"}</p>
      <p><b>2.</b> left side ${KNOTS[knot].rel[0]}: ${side(r.lhs)}</p>
      <p>&nbsp;&nbsp;&nbsp;right side ${KNOTS[knot].rel[1]}: ${side(r.rhs)}</p>
      <p>&nbsp;&nbsp;&nbsp;equal? ${r.relation ? "yes ✓" : "no ✗"}</p>
      <p><b>3.</b> XY = ${fmt(XY)}, YX = ${fmt(YX)}: ${r.commute ? "they commute ✗" : "they differ ✓"}</p>
      <p class="verdict ${r.ok ? "ok" : "bad"}">${r.ok ? `Checked: this knot is not the unknot. ${KNOTS[knot].rel[0].length + KNOTS[knot].rel[1].length + 2} matrix products did it.` : "Not a certificate."}</p>`;
  }
  function strip() {
    const knot = $("knot").value, cells = [];
    for (let q = 2; q <= 31; q++) if (isPrime(q)) {
      const good = !!find(knot, q).found;
      cells.push(`<span class="pc ${good ? "good" : ""}" title="${good ? "a certificate exists mod " + q : "none mod " + q}">${q}</span>`);
    }
    $("strip").innerHTML = cells.join("");
  }
  $("knot").addEventListener("change", () => { render(); setTimeout(strip, 0); });
  $("p").addEventListener("input", () => { const v = +$("p").value; if (isPrime(v)) render(); else $("ptext").textContent = v + " (not prime; skipping)"; });
  $("tamper").addEventListener("click", () => {
    if (!cert) return; const p = +$("p").value;
    cert = { X: cert.X, Y: [cert.Y[0], (cert.Y[1] + 1) % p, cert.Y[2], cert.Y[3]] };
    $("cert").innerHTML = `<p>X = ${fmt(cert.X)} &nbsp; Y = ${fmt(cert.Y)} &nbsp; (mod ${p}) <i>(one entry of Y changed)</i></p>`;
    verify($("knot").value, p);
  });
  render(); setTimeout(strip, 0);
});
