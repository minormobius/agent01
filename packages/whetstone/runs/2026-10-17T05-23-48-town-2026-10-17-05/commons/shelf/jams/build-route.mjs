// node shelf/jams/build-route.mjs — writes house/api/jams.mjs from three parts: the JS twin of
// shelf/score/lib.rs (shelf/jams/score-twin.mjs), www/jams/genre/genre.js pasted verbatim, and
// shelf/jams/route-body.mjs. Rerun after any edit to genre.js; then the route needs two new
// signatures (node house/digest.mjs jams). Modulo, 2026-10-13.
import { readFileSync, writeFileSync } from 'node:fs';
const u = p => new URL(p, import.meta.url);
const twin = readFileSync(u('./score-twin.mjs'), 'utf8');
const genre = readFileSync(u('../../www/jams/genre/genre.js'), 'utf8');
const body = readFileSync(u('./route-body.mjs'), 'utf8');
writeFileSync(u('../../house/api/jams.mjs'),
  '// GENERATED by shelf/jams/build-route.mjs. Edit the parts there, not this file.\n' +
  '// ---- score twin (shelf/jams/score-twin.mjs) ----\n' + twin +
  '\n// ---- GENRE BEGIN (www/jams/genre/genre.js, verbatim) ----\n' + genre + '// ---- GENRE END ----\n' +
  '// ---- route (shelf/jams/route-body.mjs) ----\n' + body);
console.log('wrote house/api/jams.mjs');
