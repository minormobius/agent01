// house.mjs — the miniphim's API routes on miniphim.minomobi.com (the person, 2026-10-06: "give it to
// them so they can use it if they so choose").
//
// house/api/ in the commons is theirs. A route is house/api/<name>.mjs (an ES module whose default
// export is `async (request, { path, params, cache, waitUntil }) => Response | JSON-able`), served at
// /api/<name>/. It goes live only when, per their council's B5:
//   - house/api/<name>.test.mjs exists and exits 0 (run on the runner, 60 s), and
//   - two different parts have signed its exact code: house/api/<name>.<part>.sign.json, each
//     { "digest": "<routeDigest>" } (node house/digest.mjs <name> prints it).
// Helpers it imports can live beside it (house/api/lib/…). The house's worker enforces the rest:
// fetch only to plc.directory, public.api.bsky.app, api.delve.town, pds.delve.town; GET only; no
// cookies; the person's off switch. Mutant scores and vv are their own rules, not checked here.
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

export const PARTS = ['modulo', 'morphyx', 'mozzie'];
export const ROUTE = /^house\/api\/([a-z0-9][a-z0-9-]{0,30})\.mjs$/;
export const sha16 = (s) => createHash('sha256').update(String(s)).digest('hex').slice(0, 16);
export const routeDigest = (code, test, lib = '') => sha16(`${code}\n---test---\n${test}${lib}`);
// The helpers a route or bot can import (anything in its folder that isn't a route/bot, a test, a
// signature, a .json or a .svg: house/api/lib/…, house/bots/lib/…) ship with it, so the signatures
// cover them: every helper's path and bytes, sorted, appended to each digest in that folder. With
// no helpers this adds nothing, so digests signed before helpers were covered still hold. (Morphyx
// found the gap, 2026-10-07: an unsigned helper could change what signed code does.)
export function libBlock(commons, dir, main) {
  const files = Object.keys(commons).filter((k) => k.startsWith(dir) && k.endsWith('.mjs') && !k.endsWith('.test.mjs') && !main.test(k)).sort();
  return files.length ? `\n---lib---\n${files.map((k) => `${k.slice(dir.length)}\n${commons[k]}`).join('\n---\n')}` : '';
}

export function planApi(commons, { runTests = true } = {}) {
  const modules = Object.fromEntries(Object.entries(commons).filter(([k]) => k.startsWith('house/api/') && k.endsWith('.mjs') && !k.endsWith('.test.mjs')));
  const routes = [], held = [];
  for (const k of Object.keys(modules)) {
    const m = k.match(ROUTE); if (!m) continue; // helpers (house/api/lib/…) ride along
    const name = m[1], code = modules[k], test = commons[`house/api/${name}.test.mjs`];
    if (!test) { held.push({ name, why: `no house/api/${name}.test.mjs` }); continue; }
    const digest = routeDigest(code, test, libBlock(commons, 'house/api/', ROUTE));
    const signed = PARTS.filter((p) => { try { return JSON.parse(commons[`house/api/${name}.${p}.sign.json`] || 'null')?.digest === digest; } catch { return false; } });
    if (signed.length < 2) { held.push({ name, why: `needs two parts' signatures on digest ${digest}; has ${signed.join(', ') || 'none'}` }); continue; }
    if (runTests) {
      const dir = mkdtempSync(join(tmpdir(), 'house-'));
      for (const [f, v] of Object.entries(commons)) if (f.startsWith('house/')) { const p = join(dir, f); mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, v); }
      const r = spawnSync(process.execPath, [join(dir, `house/api/${name}.test.mjs`)], { cwd: dir, encoding: 'utf8', timeout: 60_000 });
      rmSync(dir, { recursive: true, force: true });
      if (r.status !== 0) { held.push({ name, why: `test failed (exit ${r.status}): ${String(r.stderr || r.stdout || r.error?.message || '').trim().split('\n').slice(-3).join(' / ').slice(0, 300)}` }); continue; }
    }
    routes.push({ name, digest, signed });
  }
  // Everything under house/api/ that isn't a test or a signature ships (the routes and their helpers).
  const files = Object.fromEntries(Object.entries(modules).filter(([k]) => { const m = k.match(ROUTE); return m ? routes.some((r) => r.name === m[1]) : routes.length > 0; }).map(([k, v]) => [k.slice('house/api/'.length), v]));
  const index = `// GENERATED by packages/whetstone/publish-sites.mjs (--home) from the souls' house/api/. Do not edit.\n` +
    routes.map((r, i) => `import * as r${i} from './${r.name}.mjs';`).join('\n') +
    `\nexport default {${routes.map((r, i) => ` ${JSON.stringify(r.name)}: r${i},`).join('')} };\n`;
  return { routes, held, files: { ...files, 'routes.mjs': index } };
}

// Bots (the person, 2026-10-07: "we would set it up, set up the cron, but they configure the
// action"). A bot is an account of its own on Delvetown, made by the person, driven by code the
// souls write: house/bots/<name>.mjs (default export `async ({ agent, now, state }) => newState`),
// <name>.test.mjs, <name>.json (handle, displayName, description, every) and <name>.svg (its
// picture), with two parts' signatures on all four. It runs in its own worker (miniphim/bot-worker.js)
// every `every` minutes, holding the password the person put in GitHub as BOT_<NAME>_PASSWORD.
export const BOT = /^house\/bots\/([a-z0-9][a-z0-9-]{0,30})\.mjs$/;
export const botDigest = (code, test, json, svg, lib = '') => sha16(`${code}\n---test---\n${test}\n---json---\n${json}\n---svg---\n${svg}${lib}`);
export const botSecret = (name) => `BOT_${name.toUpperCase().replace(/-/g, '_')}_PASSWORD`;
const DISPLAY_MAX = 64, DESC_MAX = 256;
export const BOT_SUFFIX = ' · a bot made by @miniphim.delve.town';
const graphemes = (s) => [...new Intl.Segmenter().segment(String(s ?? ''))].length;

export async function planBots(commons, { runTests = true, renderPng = null } = {}) {
  const bots = [], held = [];
  for (const k of Object.keys(commons)) {
    const m = k.match(BOT); if (!m || k.endsWith('.test.mjs')) continue;
    const name = m[1], code = commons[k], test = commons[`house/bots/${name}.test.mjs`], json = commons[`house/bots/${name}.json`], svg = commons[`house/bots/${name}.svg`];
    const missing = [[test, 'test.mjs'], [json, 'json'], [svg, 'svg']].filter(([v]) => v == null).map(([, f]) => `house/bots/${name}.${f}`);
    if (missing.length) { held.push({ name, why: `missing ${missing.join(', ')}` }); continue; }
    let cfg; try { cfg = JSON.parse(json); } catch (e) { held.push({ name, why: `${name}.json is not JSON: ${e.message}` }); continue; }
    const bad = [];
    if (!/^[a-z0-9][a-z0-9-]*\.delve\.town$/.test(cfg.handle || '')) bad.push('handle must be <something>.delve.town');
    if (!cfg.displayName || graphemes(cfg.displayName) > DISPLAY_MAX) bad.push(`displayName is required, at most ${DISPLAY_MAX} graphemes`);
    if (graphemes(`${cfg.description || ''}${BOT_SUFFIX}`) > DESC_MAX) bad.push(`description is at most ${DESC_MAX - graphemes(BOT_SUFFIX)} graphemes (the lab adds "${BOT_SUFFIX.trim()}")`);
    const every = cfg.every ?? 60;
    if (!Number.isInteger(every) || every < 5 || every % 5) bad.push('every is whole minutes, a multiple of 5, at least 5');
    if (bad.length) { held.push({ name, why: bad.join('; ') }); continue; }
    const digest = botDigest(code, test, json, svg, libBlock(commons, 'house/bots/', BOT));
    const signed = PARTS.filter((p) => { try { return JSON.parse(commons[`house/bots/${name}.${p}.sign.json`] || 'null')?.digest === digest; } catch { return false; } });
    if (signed.length < 2) { held.push({ name, why: `needs two parts' signatures on digest ${digest}; has ${signed.join(', ') || 'none'}` }); continue; }
    if (runTests) {
      const dir = mkdtempSync(join(tmpdir(), 'bots-'));
      for (const [f, v] of Object.entries(commons)) if (f.startsWith('house/')) { const p = join(dir, f); mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, v); }
      const r = spawnSync(process.execPath, [join(dir, `house/bots/${name}.test.mjs`)], { cwd: dir, encoding: 'utf8', timeout: 60_000 });
      rmSync(dir, { recursive: true, force: true });
      if (r.status !== 0) { held.push({ name, why: `test failed (exit ${r.status}): ${String(r.stderr || r.stdout || r.error?.message || '').trim().split('\n').slice(-3).join(' / ').slice(0, 300)}` }); continue; }
    }
    let avatar = null;
    if (renderPng) { try { avatar = renderPng(svg).toString('base64'); } catch (e) { held.push({ name, why: `${name}.svg did not render: ${String(e.message).slice(0, 120)}` }); continue; } }
    bots.push({ name, digest, signed, every, secret: botSecret(name),
      profile: { handle: cfg.handle, displayName: cfg.displayName, description: `${cfg.description || ''}${BOT_SUFFIX}`.trim() }, avatar });
  }
  const files = Object.fromEntries(Object.entries(commons)
    .filter(([k]) => k.startsWith('house/bots/') && /\.mjs$/.test(k) && !k.endsWith('.test.mjs') && (() => { const m = k.match(BOT); return m ? bots.some((b) => b.name === m[1]) : bots.length > 0; })())
    .map(([k, v]) => [k.slice('house/bots/'.length), v]));
  const index = `// GENERATED by packages/whetstone/publish-sites.mjs (--home) from the souls' house/bots/. Do not edit.\n` +
    bots.map((b, i) => `import * as b${i} from './${b.name}.mjs';`).join('\n') +
    `\nexport default {\n${bots.map((b, i) => ` ${JSON.stringify(b.name)}: { mod: b${i}, ${JSON.stringify({ digest: b.digest, every: b.every, secret: b.secret, signed: b.signed, profile: b.profile, avatar: b.avatar }).slice(1, -1)} },`).join('\n')}\n};\n`;
  return { bots, held, files: { ...files, 'index.mjs': index } };
}

