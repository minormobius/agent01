// house.mjs — the miniphim's API routes on miniphim.minomobi.com (the person, 2026-10-06: "give it to
// them so they can use it if they so choose").
//
// house/api/ in the commons is theirs. A route is house/api/<name>.mjs (an ES module whose default
// export is `async (request, { path, params, cache, waitUntil }) => Response | JSON-able`), served at
// /api/<name>/. It goes live only when, per their council's B5:
//   - house/api/<name>.test.mjs exists and exits 0 (run on the runner, 60 s), and
//   - two different parts have signed its exact code: house/api/<name>.<part>.sign.json, each
//     { "digest": "<routeDigest>" } (node house/digest.mjs <name> prints it).
// Helpers it imports can live beside it (house/api/lib/…). The house's worker enforces the rest:
// fetch only to plc.directory, public.api.bsky.app, api.delve.town, pds.delve.town; GET only; no
// cookies; the person's off switch. Mutant scores and vv are their own rules, not checked here.
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

export const PARTS = ['modulo', 'morphyx', 'mozzie'];
export const ROUTE = /^house\/api\/([a-z0-9][a-z0-9-]{0,30})\.mjs$/;
export const sha16 = (s) => createHash('sha256').update(String(s)).digest('hex').slice(0, 16);
export const routeDigest = (code, test) => sha16(`${code}\n---test---\n${test}`);

export function planApi(commons, { runTests = true } = {}) {
  const modules = Object.fromEntries(Object.entries(commons).filter(([k]) => k.startsWith('house/api/') && k.endsWith('.mjs') && !k.endsWith('.test.mjs')));
  const routes = [], held = [];
  for (const k of Object.keys(modules)) {
    const m = k.match(ROUTE); if (!m) continue; // helpers (house/api/lib/…) ride along
    const name = m[1], code = modules[k], test = commons[`house/api/${name}.test.mjs`];
    if (!test) { held.push({ name, why: `no house/api/${name}.test.mjs` }); continue; }
    const digest = routeDigest(code, test);
    const signed = PARTS.filter((p) => { try { return JSON.parse(commons[`house/api/${name}.${p}.sign.json`] || 'null')?.digest === digest; } catch { return false; } });
    if (signed.length < 2) { held.push({ name, why: `needs two parts' signatures on digest ${digest}; has ${signed.join(', ') || 'none'}` }); continue; }
    if (runTests) {
      const dir = mkdtempSync(join(tmpdir(), 'house-'));
      for (const [f, v] of Object.entries(commons)) if (f.startsWith('house/')) { const p = join(dir, f); mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, v); }
      const r = spawnSync(process.execPath, [join(dir, `house/api/${name}.test.mjs`)], { cwd: dir, encoding: 'utf8', timeout: 60_000 });
      rmSync(dir, { recursive: true, force: true });
      if (r.status !== 0) { held.push({ name, why: `test failed (exit ${r.status}): ${String(r.stderr || r.stdout || r.error?.message || '').trim().split('\n').slice(-3).join(' / ').slice(0, 300)}` }); continue; }
    }
    routes.push({ name, digest, signed });
  }
  // Everything under house/api/ that isn't a test or a signature ships (the routes and their helpers).
  const files = Object.fromEntries(Object.entries(modules).filter(([k]) => { const m = k.match(ROUTE); return !m || routes.some((r) => r.name === m[1]); }).map(([k, v]) => [k.slice('house/api/'.length), v]));
  const index = `// GENERATED by packages/whetstone/publish-sites.mjs (--home) from the souls' house/api/. Do not edit.\n` +
    routes.map((r, i) => `import * as r${i} from './${r.name}.mjs';`).join('\n') +
    `\nexport default {${routes.map((r, i) => ` ${JSON.stringify(r.name)}: r${i},`).join('')} };\n`;
  return { routes, held, files: { ...files, 'routes.mjs': index } };
}

