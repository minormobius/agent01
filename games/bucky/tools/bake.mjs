/* Bake every level's par: the fewest parts the router (js/logic.js B.par)
   can find, from several seeds, and the design that does it. Writes
   js/par.js, which the page shows after a solve and the selftest re-checks.
     node games/bucky/tools/bake.mjs [seeds=8] [tries=20000]   (minutes) */
import { fileURLToPath } from "node:url";
import path from "node:path";
import fs from "node:fs";
const here = path.dirname(fileURLToPath(import.meta.url));
await import(path.join(here, "../js/ball.js"));
await import(path.join(here, "../js/logic.js"));
const B = globalThis.BUCKY;
const seeds = +(process.argv[2] || 8), tries = +(process.argv[3] || 20000), out = {};
for (const lv of B.LEVELS) {
  let best = null;
  for (let s = 1; s <= seeds; s++) {
    const d = B.par(lv, s, tries);
    if (d && (!best || B.parts(d) < B.parts(best))) best = d;
  }
  if (!best) throw new Error("no route for " + lv.id);
  out[lv.id] = { parts: B.parts(best), design: B.encode(best) };
  console.log(lv.id.padEnd(9), out[lv.id].parts);
}
const body = "/* Generated by tools/bake.mjs: each level's par (the fewest parts the\n   router found) and the design that does it. Best known, not proved least. */\n" +
  "(function () {\n  var NS = (typeof window !== \"undefined\") ? window : globalThis;\n  (NS.BUCKY = NS.BUCKY || {}).PAR = " +
  JSON.stringify(out, null, 2).replace(/\n/g, "\n  ") + ";\n})();\n";
fs.writeFileSync(path.join(here, "../js/par.js"), body);
