/* node games/strand/tools/bake.mjs
 *
 * Bakes the level ladder into js/levels.js. Each level is carved (solve.js
 * carve: a random answer, then load-bearing walls until it is the only one)
 * and written as data: the board spec, the colour pairs, the walls and the
 * bridges. The answer itself is not shipped; the selftest re-derives it and
 * re-proves it unique against the current engine, so a change to the mesh
 * or the solver can't quietly break a shipped level.
 *
 * Deterministic: same ladder, same engine → same file. Takes a few minutes.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { loadStrand } from "../test/harness.mjs";

const S = await loadStrand(), O = globalThis.ORB;
const here = path.dirname(fileURLToPath(import.meta.url));

// [title, board spec, pairs, bridges]
const LADDER = [
  ["first bonds", { type: "c60-atoms" }, 9, 0],
  ["buckyball", { type: "c60-atoms" }, 7, 0],
  ["three ways out", { type: "c60-atoms" }, 6, 0],
  ["sparse", { type: "c60-atoms" }, 5, 0],
  ["soccer ball", { type: "c60-panels" }, 5, 2],
  ["crossing", { type: "c60-panels" }, 4, 1],
  ["two bridges", { type: "c60-panels" }, 4, 2],
  ["labyrinth", { type: "c60-panels" }, 3, 0],
  ["minotaur", { type: "c60-panels" }, 2, 0],
  ["foam", { type: "voronoi-atoms", n: 30, seed: "strand-a1" }, 8, 0],
  ["froth", { type: "voronoi-atoms", n: 40, seed: "strand-a2" }, 9, 0],
  ["lattice", { type: "voronoi-atoms", n: 50, seed: "strand-a3" }, 9, 0],
  ["cobweb", { type: "voronoi-atoms", n: 60, seed: "strand-a4" }, 10, 0],
  ["cells", { type: "voronoi-panels", n: 40, seed: "strand-p1" }, 7, 1],
  ["tissue", { type: "voronoi-panels", n: 50, seed: "strand-p2" }, 8, 2],
  ["mosaic", { type: "voronoi-panels", n: 60, seed: "strand-p3" }, 9, 2],
  ["hive", { type: "voronoi-panels", n: 60, seed: "strand-p4" }, 8, 2],
  ["planet", { type: "voronoi-panels", n: 80, seed: "strand-p5" }, 12, 3],
  ["world", { type: "voronoi-panels", n: 100, seed: "strand-p6" }, 16, 3],
];

const levels = [];
for (const [i, [title, spec, K, B]] of LADDER.entries()) {
  const t0 = Date.now();
  let lv = null, tries = 0;
  while (!lv && tries < 12) {
    const b = S.board(spec);
    lv = S.carve(b, { pairs: K, bridges: B, rng: O.rngFor("strand-bake", i, tries), budget: 3e6 });
    tries++;
  }
  if (!lv) throw new Error(`level ${i + 1} "${title}": no unique level in ${tries} tries`);
  const b = S.board(spec);
  levels.push({ title, board: spec, pairs: lv.pairs, walls: lv.walls, bridges: lv.bridges });
  console.log(`${String(i + 1).padStart(2)} ${title.padEnd(15)} ${b.name.padEnd(22)} ${K} colours, ${lv.walls.length} walls, ${lv.bridges.length} bridges · ${tries} tr${tries > 1 ? "ies" : "y"}, ${((Date.now() - t0) / 1000).toFixed(1)} s`);
}

const out = `/* GENERATED by tools/bake.mjs. Do not edit: re-run the baker.
   Each level is proved to have exactly one answer; test/strand.selftest.mjs
   re-proves it against the current engine. */
(function () {
  var NS = (typeof window !== "undefined") ? window : globalThis;
  (NS.STRAND = NS.STRAND || {}).LEVELS = ${JSON.stringify(levels)};
})();
`;
writeFileSync(path.join(here, "../js/levels.js"), out);
console.log(`wrote ${levels.length} levels`);
