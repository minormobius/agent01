#!/usr/bin/env node
// Regenerate docs/SURFACES.md — the where-to-look index — from
// deploy-registry.json (the source of truth).
//
// This is the file root CLAUDE.md points at instead of carrying a site list of
// its own. Every surface gets one row: what it is, where its code lives, where
// it's live, which branch owns its deploy, and where its instruction file is.
// Because it's generated, it cannot drift the way a hand-kept table does.
//
// Usage:
//   node scripts/gen-surface-index.mjs           # dry run — prints a diff summary
//   node scripts/gen-surface-index.mjs --check    # exit 1 if out of date (CI)
//   node scripts/gen-surface-index.mjs --write    # apply

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import {
  loadRegistry, loadLanding, loadCurated, surfaceResolver, describe, scrubEndpoint,
} from './lib/landing.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const write = process.argv.includes('--write');
const check = process.argv.includes('--check');

const reg = loadRegistry(ROOT);
const landing = loadLanding(ROOT);
const resolver = surfaceResolver(reg);
const curated = loadCurated(ROOT);
const OUT = join(ROOT, 'docs', 'SURFACES.md');

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n+/g, ' ').trim();

// One line per surface. Prefers the landing page's curated description (the
// index that actually ships to visitors) over the registry note, and is
// redacted + capped by the shared helper — see scripts/lib/landing.mjs.
const blurb = (s) => esc(describe(s, { landing, resolver, curated }));

// Where a Claude should read for this surface, in priority order.
function docFor(s) {
  const d = s.dir && s.dir !== '.' ? s.dir : '';
  for (const f of ['CLAUDE.md', 'README.md', 'AGENTS.md']) {
    if (d && existsSync(join(ROOT, d, f))) return `[\`${d}/${f}\`](../${d}/${f})`;
  }
  if (!d && existsSync(join(ROOT, 'CLAUDE.md'))) return '[`CLAUDE.md`](../CLAUDE.md)';
  return '—';
}

const endpoint = (s) => {
  const e = (scrubEndpoint(s.endpoint) || '').trim();
  if (!e) return '—';
  // Link the first token if it's a reachable host; keep the rest as text.
  const first = e.split(/[,/]/)[0].replace(/\(.*?\)/g, '').trim();
  return first.includes('.') && !first.includes(' ')
    ? `[${esc(e)}](https://${first})`
    : `\`${esc(e)}\``;
};

const surfaces = [...reg.surfaces].sort((a, b) => a.surface.localeCompare(b.surface));

const rows = surfaces.map((s) =>
  `| \`${esc(s.surface)}\` | ${esc(s.type || '')} | \`${esc(s.dir)}\` | ${endpoint(s)} | \`${esc(s.branch)}\` | ${docFor(s)} | ${blurb(s)} |`,
).join('\n');

// Shared backends, so a Claude can see the blast radius before touching one.
const providers = new Map();
for (const s of surfaces) {
  for (const u of s.uses || []) {
    if (!providers.has(u)) providers.set(u, []);
    providers.get(u).push(s.surface);
  }
}
const shared = [...providers.entries()]
  .sort((a, b) => b[1].length - a[1].length)
  .map(([res, deps]) => `| \`${esc(res)}\` | ${deps.length} | ${deps.map((d) => `\`${d}\``).join(', ')} |`)
  .join('\n');

const u = reg.unmanaged || {};
const codes = (xs) => (xs || []).map((x) => `\`${x}\``).join(', ') || '—';

const body = `<!-- GENERATED by scripts/gen-surface-index.mjs — DO NOT EDIT BY HAND.
     Source of truth: deploy-registry.json. Regenerate with:
       node scripts/gen-surface-index.mjs --write
     CI checks this file is current (scripts/preflight.mjs). -->

# Surface index — where everything lives

Every independently-deployed surface in this repo, generated from
[\`deploy-registry.json\`](../deploy-registry.json). **${surfaces.length} surfaces.**

This is the index to read first. Root [\`CLAUDE.md\`](../CLAUDE.md) carries the
rules that apply everywhere; the per-surface **Docs** column below carries the
instructions for one surface. Don't look for a site list in CLAUDE.md — it
deliberately doesn't have one, because a hand-kept list rots and this doesn't.

## How to navigate to a surface \`X\`

| you want… | look at… |
|---|---|
| what it is and how it works | its **Docs** file below (\`X/CLAUDE.md\`) |
| its code | \`X/\` — the \`dir\` column (don't assume dir == subdomain) |
| its Cloudflare config | \`X/wrangler.jsonc\` (\`name\` = worker, \`routes\` = domain) |
| its deploy | \`.github/workflows/deploy-X.yml\` |
| which branch ships it | the **Owning branch** column |
| its live URL | the **Endpoint** column (e.g. \`answers\` → \`ask.mino.mobi\`) |
| its machine facts | \`deploy-registry.json\` → \`surfaces[]\` where \`surface == "X"\` |

## Surfaces

| Surface | Type | Dir | Endpoint | Owning branch | Docs | What it is |
|---|---|---|---|---|---|---|
${rows}

## Shared backends — check the blast radius before changing these

A change here ripples to every dependent surface listed.

| Resource | Dependents | Surfaces |
|---|---|---|
${shared}

## Unmanaged

Wrangler config present, no deploy surface yet (needs triage): ${codes(u.sites)}.${
  u.in_progress && u.in_progress.length ? `\n\nIn progress: ${codes(u.in_progress)}.` : ''
}
`;

const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
const same = current === body;

if (check) {
  if (same) { console.log(`✓ docs/SURFACES.md in sync (${surfaces.length} surfaces)`); process.exit(0); }
  console.error('✗ docs/SURFACES.md is out of date — run: node scripts/gen-surface-index.mjs --write');
  process.exit(1);
}

if (write) {
  writeFileSync(OUT, body);
  console.log(`${same ? '= unchanged' : '✓ wrote'} docs/SURFACES.md (${surfaces.length} surfaces, ${providers.size} shared backends)`);
} else {
  console.log(`${surfaces.length} surfaces, ${providers.size} shared backends`);
  console.log(same ? '✓ docs/SURFACES.md already in sync' : '~ docs/SURFACES.md would change (pass --write)');
}
