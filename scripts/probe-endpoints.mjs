#!/usr/bin/env node
// Probe every reachable endpoint the rethink knows about and record which are
// dead. Writes rethink/health.json; build-rethink.mjs folds it into data.js so
// the audit, the /next/ landing and the stumble portal can all skip or flag
// dead pages.
//
// "Dead" is one of:
//   http     a 4xx/5xx (a worker that no longer answers, a route that 404s)
//   fallback the apex answered 200 with the landing page instead of the page:
//            the root Pages project serves index.html for any unknown path,
//            so a missing root-served directory never 404s
//   timeout  no answer within the deadline
//   error    a transport failure (DNS, TLS, reset)
//
//   node scripts/probe-endpoints.mjs                # probe, write health.json
//   node scripts/probe-endpoints.mjs --only mino.mobi/foo   # one url
//   node scripts/probe-endpoints.mjs --concurrency 6 --timeout 15000

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const CONC = +arg('--concurrency', 6);
const TIMEOUT = +arg('--timeout', 20000);
const only = arg('--only', '');

const data = readFileSync(join(root, 'rethink/data.js'), 'utf8');
const w = {}; new Function('window', data)(w);
const R = w.RETHINK;

// one probe per distinct URL: every space node plus every proposal member
const urls = new Map();
// space carries every member too (virtual nodes for hash routes and .html pages), with its real URL
for (const s of R.space) if (s.u && !/#/.test(s.u)) urls.set(s.u, { id: s.id, fate: s.fate, top: s.top });
let list = [...urls.keys()];
if (only) list = list.filter((u) => u.includes(only));

// the landing's fingerprint: what the apex returns for a path it does not have
const LANDING_MARK = /name="mino-landing"/;
const isApex = (u) => /^https:\/\/(www\.)?mino\.mobi\//.test(u) || /^https:\/\/minomobi\.com\//.test(u);

async function probe(u) {
  const ctl = new AbortController();
  const t = setTimeout(() => ctl.abort(), TIMEOUT);
  const started = Date.now();
  try {
    const res = await fetch(u, { redirect: 'follow', signal: ctl.signal, headers: { 'user-agent': 'minomobi-probe/1 (+https://mino.mobi/rethink/)' } });
    const ms = Date.now() - started;
    let body = '';
    const ct = res.headers.get('content-type') || '';
    if (/text\/html/.test(ct)) body = (await res.text()).slice(0, 200000);
    else await res.arrayBuffer().catch(() => {});
    const out = { status: res.status, ms, finalUrl: res.url !== u ? res.url : '' };
    if (res.status >= 400) return { ...out, dead: 'http' };
    if (isApex(u) && u !== 'https://mino.mobi/' && u !== 'https://minomobi.com/' && LANDING_MARK.test(body)) return { ...out, dead: 'fallback' };
    return { ...out, dead: '' };
  } catch (e) {
    const ms = Date.now() - started;
    return { status: 0, ms, dead: e.name === 'AbortError' ? 'timeout' : 'error', note: String(e.message || e).slice(0, 120) };
  } finally { clearTimeout(t); }
}

const results = {};
let i = 0, done = 0;
async function worker() {
  while (i < list.length) {
    const u = list[i++];
    results[u] = await probe(u);
    done++;
    if (done % 50 === 0 || done === list.length) process.stderr.write(`  ${done}/${list.length}\n`);
  }
}
await Promise.all(Array.from({ length: CONC }, worker));

const dead = Object.entries(results).filter(([, r]) => r.dead);
const byKind = dead.reduce((o, [, r]) => { o[r.dead] = (o[r.dead] || 0) + 1; return o; }, {});
console.log(`probed ${list.length} urls · dead ${dead.length}` + (dead.length ? ' (' + Object.entries(byKind).map(([k, v]) => `${k} ${v}`).join(' · ') + ')' : ''));
for (const [u, r] of dead.sort()) console.log(`  ${r.dead.padEnd(8)} ${r.status || '-'}  ${u}${r.note ? '  ' + r.note : ''}`);

if (!only) {
  const out = { $comment: 'GENERATED by scripts/probe-endpoints.mjs — every reachable endpoint probed from outside. dead: http (4xx/5xx) · fallback (the apex served the landing instead of the page) · timeout · error. Re-run to refresh; build-rethink folds it into data.js.', checked: new Date().toISOString(), probed: list.length, dead: dead.length, results: Object.fromEntries(Object.keys(results).sort().map((k) => [k, results[k]])) };
  writeFileSync(join(root, 'rethink/health.json'), JSON.stringify(out, null, 1) + '\n');
  console.log('wrote rethink/health.json');
}
