// node proofs/riemann/riemann.selftest.mjs           check everything
// node proofs/riemann/riemann.selftest.mjs --write   also rewrite zeros.js
//
// Holds riemann.js to known values and to itself (functional equation, θ two ways,
// the reality of Z), counts zeros against published counts, and checks that
// zeros.js, which the page loads, is exactly what the engine finds.
import * as R from './riemann.js';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
let pass = 0, fail = 0;
const ok = (cond, msg) => { if (cond) pass++; else { fail++; console.log('FAIL', msg); } };
const near = (a, b, tol, msg) => ok(Math.abs(a - b) <= tol, `${msg}: ${a} vs ${b}`);
const t0 = Date.now();

// ---- ζ at known points ---------------------------------------------------
near(R.zeta([2, 0])[0], Math.PI ** 2 / 6, 1e-13, 'ζ(2)');
near(R.zeta([4, 0])[0], Math.PI ** 4 / 90, 1e-13, 'ζ(4)');
near(R.zeta([3, 0])[0], 1.2020569031595942, 1e-13, 'ζ(3)');
near(R.zeta([0, 0])[0], -0.5, 1e-13, 'ζ(0)');
near(R.zeta([-1, 0])[0], -1 / 12, 1e-13, 'ζ(−1)');
near(R.zeta([-3, 0])[0], 1 / 120, 1e-12, 'ζ(−3)');
near(R.zeta([0.5, 0])[0], -1.4603545088095868, 1e-13, 'ζ(½)');
for (const n of [2, 4, 6, 8]) near(R.cabs(R.zeta([-n, 0])), 0, 1e-12, `trivial zero −${n}`);

// ---- functional equation, at random complex points -------------------------
// ζ(s) = 2^s π^(s−1) sin(πs/2) Γ(1−s) ζ(1−s), with both sides through the Euler–Maclaurin path
{
  let seed = 7; const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
  for (let i = 0; i < 40; i++) {
    const s = [0.05 + 0.9 * rnd(), 1 + 60 * rnd()], t = [1 - s[0], -s[1]];
    const rhs = R.cmul(R.cmul(R.cexp([s[0] * Math.LN2, s[1] * Math.LN2]), R.cexp([(s[0] - 1) * Math.log(Math.PI), s[1] * Math.log(Math.PI)])),
      R.cmul([Math.sin(Math.PI * s[0] / 2) * Math.cosh(Math.PI * s[1] / 2), Math.cos(Math.PI * s[0] / 2) * Math.sinh(Math.PI * s[1] / 2)], R.cmul(R.cgamma(t), R.zeta(t))));
    const lhs = R.zeta(s);
    ok(R.cabs(R.csub(lhs, rhs)) <= 1e-9 * Math.max(1, R.cabs(lhs)), `functional equation at ${s}`);
  }
}

// ---- Γ and θ -----------------------------------------------------------------
near(R.cgamma([5, 0])[0], 24, 1e-10, 'Γ(5)');
near(R.cgamma([0.5, 0])[0], Math.sqrt(Math.PI), 1e-13, 'Γ(½)');
for (let t = 20; t <= 1000; t += 7.3) near(R.theta(t), R.thetaAsymptotic(t), 2e-9, `θ two ways at ${t.toFixed(1)}`);
// θ is continuous (not wrapped): its increments are small and positive past its minimum near t ≈ 6.29
{ let prev = R.theta(7), mono = true; for (let t = 7.1; t < 200; t += 0.1) { const v = R.theta(t); if (!(v > prev && v - prev < 0.5)) mono = false; prev = v; } ok(mono, 'θ increasing and continuous on [7, 200]'); }

// ---- e^{iθ}ζ(½+it) is real -----------------------------------------------
for (let t = 3; t < 1000; t += 3.7) ok(Math.abs(R.Zimag(t)) < 1e-10, `Im e^{iθ}ζ(½+it) = 0 at ${t.toFixed(1)}`);

// ---- zeros ---------------------------------------------------------------------
const zeros = R.findZeros(1000);
// first ten ordinates, Odlyzko's tables
const KNOWN = [14.134725141734693790, 21.022039638771554993, 25.010857580145688763, 30.424876125859513210,
  32.935061587739189691, 37.586178158825671257, 40.918719012147495187, 43.327073280914999519,
  48.005150881167159727, 49.773832477672302181];
KNOWN.forEach((g, i) => near(zeros[i], g, 1e-9, `zero #${i + 1}`));
ok(zeros.filter((g) => g <= 100).length === 29, 'N(100) = 29');
ok(zeros.length === 649, `N(1000) = 649 (got ${zeros.length})`);
for (const g of zeros) ok(Math.abs(R.Z(g)) < 1e-9, `|Z| small at ${g}`);
// Riemann–von Mangoldt: the count never strays more than 2 from θ(T)/π + 1 at midpoints between zeros
for (let i = 1; i < zeros.length; i++) {
  const T = (zeros[i - 1] + zeros[i]) / 2;
  ok(Math.abs(i - R.Nsmooth(T)) < 2, `N(T) ≈ θ(T)/π + 1 at T=${T.toFixed(2)}`);
}

// ---- zeros.js --------------------------------------------------------------
const zfile = join(here, 'zeros.js');
const body = `// generated by riemann.selftest.mjs --write: the ${zeros.length} zeros ½ + iγ of ζ with 0 < γ < 1000, γ to 12 decimals\n` +
  `export const ZEROS = [${zeros.map((g) => g.toFixed(12)).join(',')}];\n`;
if (process.argv.includes('--write')) { writeFileSync(zfile, body); console.log('wrote zeros.js'); }
{
  let have = ''; try { have = readFileSync(zfile, 'utf8'); } catch {}
  ok(have === body, 'zeros.js matches the engine (run with --write)');
}

// ---- primes and the explicit formula ---------------------------------------------
near(R.psi(10), Math.log(2) * 3 + Math.log(3) * 2 + Math.log(5) + Math.log(7), 1e-12, 'ψ(10)');
ok(R.sieve(100).length === 25, 'π(100) = 25');
ok(R.sieve(10000).length === 1229, 'π(10⁴) = 1229');
{
  const err = (K) => { let e = 0, n = 0; for (let x = 10.5; x < 100; x += 1) { e += Math.abs(R.psi0(x) - R.psiExplicit(x, zeros, K)); n++; } return e / n; };
  const e10 = err(10), e100 = err(100), eAll = err(zeros.length);
  ok(e10 > e100 && e100 > eAll, `explicit formula improves with more zeros (${e10.toFixed(3)} > ${e100.toFixed(3)} > ${eAll.toFixed(3)})`);
  ok(eAll < 0.1, `649 zeros rebuild ψ on [10, 100] to mean error < 0.1 (${eAll.toFixed(4)})`);
  // at a prime power the formula must land on the midpoint of the jump
  ok(Math.abs(R.psi0(31) - R.psiExplicit(31, zeros)) < 0.3, 'ψ₀ midpoint convention at x = 31');
}

// ---- zero-free region -----------------------------------------------------------
ok(R.classicalEdge(10) > 0.9 && R.classicalEdge(1e6) < 1 && R.classicalEdge(1e6) > R.classicalEdge(10), 'classical edge shape');

console.log(`${fail ? 'FAILED' : 'ok'}: ${pass} passed, ${fail} failed, ${((Date.now() - t0) / 1000).toFixed(1)} s`);
process.exit(fail ? 1 : 0);
