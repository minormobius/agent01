// node proofs/riemann/learn/build-narration.mjs           rewrite narration.js
// node proofs/riemann/learn/build-narration.mjs --check   exit 1 if narration.js is stale
//
// What autopilot's lecturer needs to speak lecture.js: the pronunciation of every word it says
// (the CMU dictionary via studio's voice-lex, plus EXTRA for the names it lacks) and how long
// each line takes in the formant voice. The voice is a byte-identical copy of studio's
// lib/chipvoice.js in vendor/chipvoice/; riemann.selftest.mjs fails if the copy drifts.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fullLexicon } from '../../../studio/tools/voice-lex.mjs';
import { speak } from './vendor/chipvoice/chipvoice.js';
import { LECTURE } from './lecture.js';

const EXTRA = {
  stepanov: 'S T EH1 P AH0 N AO2 F',
  deligne: 'D AH0 L IY1 N Y',
};
const here = dirname(fileURLToPath(import.meta.url)), full = { ...fullLexicon(), ...EXTRA }, LEX = {};
const lines = LECTURE.flat();
for (const l of lines) for (const w of l.say.toLowerCase().match(/[a-z]+(?:'[a-z]+)?/g) || []) {
  if (!full[w]) throw new Error(`not in the dictionary: "${w}" in "${l.say}" (add it to EXTRA)`);
  LEX[w] = full[w];
}
const DUR = LECTURE.map((slide) => slide.map((l) => { const r = speak(l.say, LEX, { rate: 8000 }); return +(r.audio.length / r.rate).toFixed(3); }));
const js = `// GENERATED by build-narration.mjs from lecture.js: the words the lecturer says, and how long each line takes (s).
// Pronunciations from the CMU Pronouncing Dictionary, Copyright (C) 1993-2015 Carnegie Mellon University. BSD-2-Clause
// (vendor/chipvoice/CMUDICT-LICENSE.txt).
export const DUR = ${JSON.stringify(DUR)};
export const LEXICON = ${JSON.stringify(Object.fromEntries(Object.entries(LEX).sort()), null, 0).replace(/","/g, '",\n  "')};
`;
const file = join(here, 'narration.js');
if (process.argv.includes('--check')) {
  let have = ''; try { have = readFileSync(file, 'utf8'); } catch {}
  if (have !== js) { console.error('narration.js is stale: run node proofs/riemann/learn/build-narration.mjs'); process.exit(1); }
  console.log('narration.js is current');
} else {
  writeFileSync(file, js);
  console.log(`${lines.length} lines, ${Object.keys(LEX).length} words, ${DUR.flat().reduce((a, b) => a + b, 0).toFixed(0)} s spoken`);
}
