// weaver.mjs — the agent.
//
// ─── WHAT THIS AGENT IS ──────────────────────────────────────────────────────
//
// A stigmergic builder with no plan. It never computes the web it is going to
// make. It holds eight numbers about its own body, a stage it is currently in,
// and a handful of registers that never exceed what an animal could plausibly
// hold — the last side it worked, the radius it is standing on, how far out it
// is. Everything else it needs to know it reads off the silk already hanging in
// front of it.
//
// That is the Physarum correspondence, and it is worth being precise about it
// rather than waving at it. Physarum's plasmodium finds shortest paths without
// a map because it deposits a chemoattractant, senses the deposit, and
// reinforces what it senses: the environment holds the state, not the organism.
// A spider does the same trick with a different medium. The difference is the
// whole story of this surface:
//
//     Physarum's trail EVAPORATES.  Silk does NOT.
//
// A decaying trace lets an agent forget a bad early commitment; the network
// re-optimises, and the final structure is largely independent of the order the
// tubes were laid in. An undecaying trace cannot be un-laid. Every thread this
// agent puts down becomes a permanent constraint on where it can stand, what it
// can reach and what it will measure next — so the construction *order* is
// carried all the way into the finished object. That is why the family of webs
// admitted by one set of boundary conditions is generated by path dependence
// rather than by noise, and why perturbing the third radius does more damage
// than perturbing the thirtieth.
//
// ─── THE STAGES ──────────────────────────────────────────────────────────────
//
//   bridge   cast silk on the wind until it snags. Fixes the top of the web
//            forever, from one draw.
//   frame    walk the anchors, laying the convex rim. Anchors it fails to reach
//            are not used — and cannot be used later.
//   hub      drop from the bridge, stop short of the bottom, tie the Y. The
//            stopping point IS the hub eccentricity.
//   radii    repeatedly find the widest rim gap, halve it, walk home. Stops
//            when no gap exceeds leg span. Alternates sides to keep the hub
//            balanced, which is a tension rule, not a symmetry preference.
//   aux      an outward scaffolding spiral at wide pitch. Not a product — a
//            handrail, and it will be eaten.
//   capture  inward, opposite rotation, sticky, gauged against the previous
//            turn and the auxiliary handrail. Consumes the handrail as it goes.
//   finish   hub reinforcement, free zone, done.
//
// Real orb-weavers do exactly this sequence, and — the 2021 Gordus-lab tracking
// work is the citation — do it as stereotyped movement sequences that can run
// in atypical order without becoming a different behaviour. The stage machine
// here is that finding, at low resolution.

import { Fabric, Chain, rayPolygon, convexHull, dist } from './fabric.mjs';
import { Streams, around, tri, uni } from './rng.mjs';
import { segmentBlocked, blocked } from './boundary.mjs';

export const STAGES = ['bridge', 'frame', 'hub', 'radii', 'aux', 'capture', 'finish', 'done'];

export const STAGE_LABEL = {
  bridge: 'bridge line',
  frame: 'frame + anchors',
  hub: 'hub & the Y',
  radii: 'radii',
  aux: 'auxiliary spiral',
  capture: 'capture spiral',
  finish: 'hub reinforcement',
  done: 'done',
};

// ─── THE BODY ────────────────────────────────────────────────────────────────
//
// Eight numbers. Not one of them is a fact about the web; they are all facts
// about the animal, and they are what stays fixed while the boundary changes.
//
// TWO REACHES, NOT ONE, and the distinction is load-bearing. Rim spacing
// between radii is set by the FULL span — the animal straddles the gap between
// two radii while it works, so a gap it cannot straddle is a gap it must split.
// Capture mesh is set by a much shorter reach: the inner foreleg held back on
// the previous turn while the spinnerets lay the next. In a real orb the first
// is ~6× the second, which is exactly why a web has ~30 radii and ~14 spiral
// turns rather than ~30 of each. Both scale with body size, which is why they
// co-vary across a family without being the same number.
export const BODY = {
  legSpan: 95,      // full span — gauges the largest rim gap the agent tolerates
  gauge: 17,        // inner-foreleg reach — gauges capture mesh height
  meshFactor: 1.00, // preferred capture pitch, in gauges
  auxFactor: 2.20,  // auxiliary pitch, in gauges — deliberately coarse
  rimFactor: 1.20,  // stop splitting a rim gap below this many leg spans
  asym: 0.18,       // how much wider it lets the mesh run above the hub than below
  tidiness: 0.16,   // spread on every gauge the animal makes
  maxRadii: 48,
};

const TAU = Math.PI * 2;
const norm = (a) => ((a % TAU) + TAU) % TAU;

export class Weaver {
  constructor(bnd, { seed = 1, body = {}, perturb = null, physEvery = 3, physIters = 3 } = {}) {
    this.bnd = bnd;
    this.body = { ...BODY, ...body };
    this.st = new Streams(seed);
    this.seed = seed;
    this.perturb = perturb;
    this.physEvery = physEvery;
    this.physIters = physIters;

    // TWO DIFFERENT JOBS FOR ONE WORD. `bnd.gravity` is a 0–1 dial on the
    // habitat, and it enters this model twice, in ways worth keeping apart:
    //
    //   · BEHAVIOURALLY, in do_hub and do_capture, where it sets how far the
    //     agent stops short on its drop and how much wider it runs the mesh
    //     above the hub than below. These are things the animal DOES about
    //     gravity, and they are where a finished orb's asymmetry comes from.
    //
    //   · MECHANICALLY, here, where it makes the sheet hang and settle. That
    //     term has to stay small: at full strength every unpinned node reaches
    //     a terminal velocity of g/(1−damping) per substep and the whole web
    //     slides down the frame, taking the hub with it — which silently
    //     cancelled the behavioural rise and made the eccentricity read zero.
    //     Sag is a visual and a source of drift for later measurements, not the
    //     mechanism under the asymmetry.
    this.f = new Fabric({ gravity: bnd.gravity * 0.05 });
    this.stage = 'bridge';
    this.acted = 0;
    this.ranOut = false;
    this.abandoned = 0;      // radii the obstacle forced the agent to give up on
    this.skipped = [];       // anchors it never reached
    this.log = [];           // one line per stage transition, for the UI

    // pinned substrate
    this.anchorNodes = bnd.anchors.map((a) => this.f.node(a.x, a.y, { pinned: true, kind: 'anchor' }));
    this.hull = convexHull(this.anchorNodes);

    this.pos = { x: this.hull[0].x, y: this.hull[0].y };
    this.radii = [];
    this.aux = [];           // {k, d, node, thread, cut}
    this.captureNodes = [];
    this.frameChains = [];
    this.framePoly = [];
    this.deadWindows = [];
    this.counts = { radius: 0, aux: 0, capture: 0 };
  }

  // ─── senses ────────────────────────────────────────────────────────────────
  //
  // Everything the agent knows about the web is one of these three calls, each
  // resolved against the fabric AS IT NOW HANGS.

  get hubPos() { return this.hubNode ? this.hubNode : this.pos; }

  rimAt(angle) {
    const h = this.hubPos;
    return rayPolygon(h.x, h.y, Math.cos(angle), Math.sin(angle), this.framePoly);
  }

  radiusLen(k) { return this.radii[k].chain.length(); }

  get rimMean() {
    if (!this.radii.length) return 200;
    let s = 0;
    for (let k = 0; k < this.radii.length; k++) s += this.radiusLen(k);
    return s / this.radii.length;
  }

  // ─── the loop ──────────────────────────────────────────────────────────────

  step() {
    if (this.stage === 'done') return null;
    const act = this['do_' + this.stage]();
    this.acted++;
    if (this.acted % this.physEvery === 0) this.f.step(1, this.physIters);
    if (act && act.pos) this.pos = { x: act.pos.x, y: act.pos.y };
    return act;
  }

  run(maxSteps = 24000) {
    let n = 0;
    while (this.stage !== 'done' && n++ < maxSteps) this.step();
    // let the finished sheet settle under its own load before anything is measured
    this.f.step(28, 5);
    return this;
  }

  enter(stage, note) {
    this.stage = stage;
    this.log.push({ stage, note, at: this.acted });
    return { kind: 'stage', stage, note, pos: this.pos };
  }

  // ─── 1. bridge ─────────────────────────────────────────────────────────────
  //
  // The single most consequential draw in the run. A spider cannot choose where
  // its bridge line lands — it pays out silk and the air decides. Everything
  // downstream (which corner is "up", where the hub can hang, which anchors are
  // even reachable) follows from this one snag, and nothing later can revise it.
  do_bridge() {
    const cx = this.hull.reduce((s, p) => s + p.x, 0) / this.hull.length;
    const cy = this.hull.reduce((s, p) => s + p.y, 0) / this.hull.length;
    const R = Math.max(1, this.hull.reduce((m, p) => Math.max(m, Math.hypot(p.x - cx, p.y - cy)), 0));

    const scored = this.hull.map((p, i) => {
      const q = this.hull[(i + 1) % this.hull.length];
      const mid = { x: (p.x + q.x) / 2, y: (p.y + q.y) / 2 };
      const up = (cy - mid.y) / R;                     // screen y grows downward
      const L = dist(p, q);
      const gust = 1 + this.bnd.wind * tri(this.st.bridge) * 0.9;
      return { i, w: L * Math.exp(2.2 * up) * Math.max(0.05, gust) };
    }).sort((a, b) => b.w - a.w);

    const pick = (this.perturb && this.perturb.at === 'bridge' && scored.length > 1) ? scored[1] : scored[0];
    this.bridgeEdge = pick.i;
    const a = this.hull[pick.i];
    const b = this.hull[(pick.i + 1) % this.hull.length];
    this.enter('frame', `bridge snagged ${Math.round(dist(a, b))} units of substrate`);
    return { kind: 'bridge', a, b, pos: b };
  }

  // ─── 2. frame ──────────────────────────────────────────────────────────────
  //
  // The rim is convex because tension makes it so, and it is built by WALKING,
  // which is why a missed anchor is lost for good: the agent has no way to come
  // back to a point it has no silk road to.
  do_frame() {
    if (!this.frameOrder) {
      const n = this.hull.length;
      const keep = [];
      for (let s = 0; s < n; s++) {
        const i = (this.bridgeEdge + s) % n;
        const isBridgeEnd = i === this.bridgeEdge || i === (this.bridgeEdge + 1) % n;
        const miss = !isBridgeEnd && this.st.frame() < 0.10 * this.bnd.wind
          && n - keep.length > 3;
        if (miss) this.skipped.push(this.hull[i]);
        else keep.push(this.hull[i]);
      }
      this.frameOrder = keep.length >= 3 ? keep : this.hull.slice();
      this.framePoly = this.frameOrder;
      this.frameIdx = 0;
    }

    const n = this.frameOrder.length;
    if (this.frameIdx < n) {
      const a = this.frameOrder[this.frameIdx];
      const b = this.frameOrder[(this.frameIdx + 1) % n];
      const kind = this.frameIdx === 0 ? 'bridge' : 'frame';
      this.frameChains.push(new Chain(this.f, a, b, kind));
      this.frameIdx++;
      return { kind: 'lay', thread: 'frame', a, b, pos: b };
    }

    // guy lines out to the anchors the rim left behind — the silk is spent
    // whether or not the anchor ends up carrying a radius
    if (this.skipped.length && this.frameIdx === n) {
      for (const s of this.skipped) {
        let best = null;
        for (const c of this.frameChains) {
          const d = dist(s, c.start) + dist(s, c.end);
          if (!best || d < best.d) best = { d, c };
        }
        const node = best.c.attachAtParam(0.5, 6);
        this.f.thread(node, s, 'anchor');
      }
      this.frameIdx++;
      return { kind: 'lay', thread: 'anchor', pos: this.skipped[0] };
    }

    return this.enter('hub', `${n} rim threads, ${this.skipped.length} anchor${this.skipped.length === 1 ? '' : 's'} unreached`);
  }

  // ─── 3. hub ────────────────────────────────────────────────────────────────
  //
  // The spider walks out along the bridge, drops on a line, and STOPS SHORT of
  // the bottom. It stops short because it hunts head-down and falling is
  // cheaper than climbing — so the hub sits above the centre of the frame, and
  // the amount by which it does is a direct readout of gravity. Set gravity to
  // zero (the `weightless` preset) and this term vanishes.
  do_hub() {
    const bridge = this.frameChains[0];
    const fParam = around(this.st.frame, 0.5, 0.16, 0.26, 0.74);
    const top = bridge.attachAtParam(fParam, 4);

    // straight down until the rim stops us
    const down = rayPolygon(top.x, top.y + 1, 0, 1, this.framePoly);
    const drop = down ? down.t + 1 : 200;
    const gNorm = Math.min(1.4, this.bnd.gravity / 0.2);
    const rise = around(this.st.frame, 0.5 - 0.085 * gNorm, 0.035, 0.24, 0.62);

    const hx = top.x;
    const hy = top.y + drop * rise;
    this.hubNode = this.f.node(hx, hy, { kind: 'hub' });

    // arm 1: back up to the bridge
    this.radii.push({ angle: norm(Math.atan2(top.y - hy, top.x - hx)), chain: this._chainTo(top) });

    // arm 2: on down to the rim
    const botHit = this.rimAt(Math.PI / 2);
    if (botHit) this.radii.push(this._radiusAt(Math.PI / 2, botHit));

    // arm 3: the side arm that makes it a Y, on whichever side the animal
    // happens to be facing
    const side = this.st.frame() < 0.5 ? 0 : Math.PI;
    const a3 = norm(side + around(this.st.frame, 0, 0.5, -0.7, 0.7));
    const h3 = this.rimAt(a3);
    if (h3) this.radii.push(this._radiusAt(a3, h3));

    this._sortRadii();
    return this.enter('radii', `hub hung ${Math.round(drop * rise)} below the bridge`);
  }

  _chainTo(node) {
    return new Chain(this.f, this.hubNode, node, 'radius');
  }

  _radiusAt(angle, hit) {
    const chain = this.frameChains[hit.edge];
    const node = chain.attachAtParam(hit.u, 4);
    return { angle: norm(angle), chain: this._chainTo(node) };
  }

  // RE-READ, DON'T REMEMBER. A radius's bearing is recomputed from the hub's
  // CURRENT position every time the list is touched, because the hub is not
  // pinned: every radius laid drags it, so a bearing recorded ten radii ago is
  // no longer where that thread runs. Caching the angle at lay time produced
  // webs whose sorted order disagreed with their geometry, and the agent
  // duly "split" gaps that were already full — a bookkeeping error dressed up
  // as a biological one. The agent has no memory of angles; it looks.
  _sortRadii() {
    const h = this.hubPos;
    for (const r of this.radii) {
      r.angle = norm(Math.atan2(r.chain.end.y - h.y, r.chain.end.x - h.x));
    }
    this.radii.sort((a, b) => a.angle - b.angle);
  }

  // ─── 4. radii ──────────────────────────────────────────────────────────────
  //
  // THE PATH-DEPENDENT STAGE. Each new radius is placed by measuring the gap
  // between two radii that already exist — so an early one that lands 4° off
  // does not average out, it becomes the reference for the two placed after it,
  // and those for the four after them. The stopping rule is local and physical:
  // keep splitting until no gap at the rim is wider than a leg span, because a
  // wider gap is one the animal cannot straddle when it comes to lay the
  // spiral. Radius count is therefore rim perimeter ÷ leg span — an invariant
  // of the family that no single decision sets.
  do_radii() {
    const gap = this._pickGap();
    if (!gap) {
      return this.enter('aux', `${this.radii.length} radii, ${this.abandoned} abandoned`);
    }

    let u = around(this.st.radius, 0.5, 0.13, 0.24, 0.76);
    const i = this.counts.radius;
    if (this.perturb && this.perturb.at === 'radius' && this.perturb.index === i) {
      u = Math.min(0.9, Math.max(0.1, u + (this.perturb.du ?? 0.16)));
    }

    const px = gap.pa.x + (gap.pb.x - gap.pa.x) * u;
    const py = gap.pa.y + (gap.pb.y - gap.pa.y) * u;
    const h = this.hubPos;

    // The agent walks a FRACTION OF THE RIM, so the draw is a fraction of the
    // chord — but the map from rim distance to bearing is badly non-linear near
    // a corner, where one neighbouring radius can be twice the length of the
    // other. Un-clamped, "a quarter of the way along the rim" came out less
    // than a degree off the long radius, the two attachments snapped to one
    // junction, and the pair became a duplicate that the spiral then tried to
    // thread twice — the fan of collapsed cells visible in the lower left of
    // the first build of this page. Bounding the bearing to the middle half of
    // the gap keeps the walk honest and the junctions distinct.
    let angle = norm(Math.atan2(py - h.y, px - h.x));
    let rel = norm(angle - gap.a0);
    const lo = gap.da * 0.25;
    const hi = gap.da * 0.75;
    if (rel < lo || rel > hi || rel > gap.da) {
      rel = Math.min(hi, Math.max(lo, rel > gap.da ? gap.da * 0.5 : rel));
      angle = norm(gap.a0 + rel);
    }

    const hit = this.rimAt(angle);
    this.counts.radius++;
    if (!hit) return { kind: 'noop', pos: this.pos };

    // last-ditch guard: never lay a radius on top of one that is already there
    const dupe = this.radii.some((r) => {
      const d = Math.abs(norm(r.angle - angle));
      return Math.min(d, TAU - d) < 0.006;
    });
    if (dupe) {
      this.deadWindows.push([norm(angle - 0.01), norm(angle + 0.01)]);
      return { kind: 'noop', pos: this.pos };
    }

    if (segmentBlocked(h.x, h.y, hit.x, hit.y, this.bnd.obstacles)) {
      // Silk already paid out, no attachment made. The agent marks the sector
      // by feel — it does not remember an obstacle, it just fails to get a line
      // across and works elsewhere.
      this.abandoned++;
      // A NARROW window, not a generous one. Sized at half the rim gap the
      // agent tolerates, and capped: the first version scaled it by the full
      // leg span over the distance to the rim, which for an obstacle near the
      // hub blanked a 45° sector per failed attempt and left the `leaf` preset
      // with a quarter of the web missing. The agent is not remembering an
      // obstacle — it is failing to get a line across and not immediately
      // trying the same bearing again.
      const w = Math.max(0.04, Math.min(0.13,
        (this.body.legSpan * this.body.rimFactor) / (2 * Math.max(40, hit.t))));
      this.deadWindows.push([norm(angle - w), norm(angle + w)]);
      return { kind: 'abandon', angle, pos: { x: px, y: py } };
    }

    const r = this._radiusAt(angle, hit);
    this.radii.push(r);
    this._sortRadii();
    return { kind: 'lay', thread: 'radius', a: h, b: r.chain.end, pos: r.chain.end };
  }

  _inDead(angle) {
    for (const [a, b] of this.deadWindows) {
      if (a <= b ? (angle >= a && angle <= b) : (angle >= a || angle <= b)) return true;
    }
    return false;
  }

  // Widest rim gap the animal can still usefully split, alternating sides of
  // the hub. Returns null when the rim is everywhere within a leg span.
  _pickGap() {
    if (this.radii.length >= this.body.maxRadii) return null;
    const maxChord = this.body.legSpan * this.body.rimFactor;
    const minAngle = TAU / this.body.maxRadii;
    const n = this.radii.length;
    if (n < 2) return null;

    const cands = [];
    for (let i = 0; i < n; i++) {
      const A = this.radii[i];
      const B = this.radii[(i + 1) % n];
      let da = B.angle - A.angle;
      if (i === n - 1) da = norm(da);
      if (da <= minAngle) continue;
      const mid = norm(A.angle + da / 2);
      if (this._inDead(mid)) continue;
      const pa = A.chain.end;
      const pb = B.chain.end;
      const chord = dist(pa, pb);
      if (chord <= maxChord) continue;
      cands.push({ chord, pa, pb, mid, a0: A.angle, da, side: Math.cos(mid) >= 0 ? 1 : -1 });
    }
    if (!cands.length) return null;
    cands.sort((a, b) => b.chord - a.chord);

    // Alternate sides. Real spiders do this to keep the hub from being dragged
    // off-centre by a run of radii pulling the same way; here it also stops the
    // fill order being a simple sweep, which is what makes the placement noise
    // compound instead of cancel.
    const other = cands.find((c) => c.side !== this.lastSide);
    const chosen = other && other.chord > cands[0].chord * 0.8 ? other : cands[0];
    this.lastSide = chosen.side;
    return chosen;
  }

  // ─── 5. auxiliary spiral ───────────────────────────────────────────────────
  //
  // Coarse, outward, and temporary. Its only job is to be something to hold on
  // to while laying the real spiral — and to be a ruler: the capture spiral's
  // spacing is gauged partly against it. So an auxiliary spiral laid slightly
  // wide is not a harmless scaffolding error, it is a systematic bias printed
  // into the finished mesh. Path dependence again, one stage further on.
  do_aux() {
    const n = this.radii.length;
    if (n < 4) return this.enter('finish', 'too few radii to spiral');

    const Rm = this.rimMean;
    if (this.auxK === undefined) {
      this.auxDir = this.st.aux() < 0.5 ? 1 : -1;
      this.auxK = Math.floor(uni(this.st.aux, 0, n)) % n;
      // FRACTION OF THE RADIUS, not absolute distance from the hub. The
      // scaffolding follows the rim's shape rather than describing a circle
      // inside it — which is what a spider walking a triangular frame actually
      // produces, and what makes the capture spiral that copies it start out
      // rim-shaped too.
      this.auxQ = (this.body.gauge * 3.4) / Rm;
      this.auxPrev = this.radii[this.auxK].chain.attachAt(this.auxQ * this.radiusLen(this.auxK), 5);
      return { kind: 'move', pos: this.auxPrev };
    }

    const k = (this.auxK + this.auxDir + n) % n;
    this.auxK = k;
    const pitch = this.body.gauge * this.body.auxFactor * (1 + 0.85 * this.auxQ);
    this.auxQ += pitch / (n * Rm);

    if (this.auxQ >= 0.90) {
      this.capQ = 0.90;
      this.capK = k;
      return this.enter('capture', `${this.counts.aux} scaffolding attachments`);
    }

    const d = this.auxQ * this.radiusLen(k);
    const node = this.radii[k].chain.attachAt(d, 5);
    this.counts.aux++;
    if (blocked(node.x, node.y, this.bnd.obstacles)) return { kind: 'move', pos: node };
    const th = this.f.thread(this.auxPrev, node, 'aux');
    this.aux.push({ k, d, node, thread: th, cut: false });
    this.auxPrev = node;
    return { kind: 'lay', thread: 'aux', a: th.a, b: th.b, pos: node };
  }

  // ─── 6. capture spiral ─────────────────────────────────────────────────────
  //
  // Inward, sticky, and rotating OPPOSITE to the scaffolding it replaces. The
  // pitch is set by leg span, widened above the hub and narrowed below it —
  // that single term is the entire visible signature of gravity in a finished
  // orb, and it is why the bottom half of a real web has more turns than the
  // top. The auxiliary spiral is cut away turn by turn as it is passed: the
  // agent is standing on the thing it is destroying.
  //
  // THE GAUGE IS PER-RADIUS, AND THAT IS THE WHOLE ASYMMETRY. The agent does
  // not track "how far round the spiral am I". Arriving at a radius, it holds
  // the previous turn ON THAT RADIUS with an inner leg and lays the next one a
  // gauge-length inward of it. So the pitch it chooses for a radius pointing
  // straight up is applied to that radius and nowhere else.
  //
  // The first version of this decremented a single global radius-fraction once
  // per step, which averaged the up/down term over a whole revolution before it
  // reached any thread: the mesh came out symmetric with gravity at full
  // strength, and the only thing left in the measurement was rim shape. A
  // bookkeeping choice had erased the phenomenon the model exists to show.
  do_capture() {
    const n = this.radii.length;
    const mesh = this.body.gauge * this.body.meshFactor;
    const freeZone = this.body.gauge * 3.4;

    if (this.capPrev === undefined) {
      this.capDir = -this.auxDir;                 // real orbs reverse; so does this
      this.capD = this.radii.map((r, k) => this.radiusLen(k) * this.capQ);
      this.capFirst = new Array(n).fill(true);
      this.capDone = new Array(n).fill(false);
      this.capDoneCount = 0;
      this.capBreak = false;
      this.capPrev = this.radii[this.capK].chain.attachAt(this.capD[this.capK], 5);
      this.capFirst[this.capK] = false;
      return { kind: 'move', pos: this.capPrev };
    }

    const k = (this.capK + this.capDir + n) % n;
    this.capK = k;
    if (this.capDone[k]) {
      // BREAK THE SPIRAL RATHER THAN BRIDGE IT. When a radius has reached the
      // free zone the agent simply has nowhere to put the next attachment on
      // it — so it walks on, and the next attachment it does make starts a
      // fresh arc instead of being joined back across the gap. Joining it was
      // the first thing this code did, and it drew a chord straight past the
      // hub every time a run of radii finished together: the two collapsed fans
      // that made the first build of this page look like a folded sheet. The
      // partial inner arcs this leaves are what real orbs have, for the same
      // reason — the spiral runs out of room in the short directions first.
      // Already finished. Break the arc and walk on — do NOT count it again:
      // counting every revisit made the counter reach the radius count within
      // two revolutions of the FIRST radius finishing, which stopped the whole
      // spiral while the long sectors still had two thirds of their run left.
      // That was the empty wedge on the left of the first three builds.
      this.capBreak = true;
      this.capPrevD = undefined;
      return { kind: 'move', pos: this.pos };
    }

    const ang = this.radii[k].angle;
    let d;
    if (this.capFirst[k]) {
      d = this.capD[k];                           // first turn: follow the scaffolding round
      this.capFirst[k] = false;
    } else {
      const up = -Math.sin(ang);                  // +1 straight above the hub
      const gNorm = Math.min(1.4, this.bnd.gravity / 0.2);
      let pitch = mesh * (1 + this.body.asym * up * gNorm)
                * (1 + this.body.tidiness * tri(this.st.capture));
      const i = this.counts.capture;
      if (this.perturb && this.perturb.at === 'capture' && this.perturb.index === i) {
        pitch *= 1 + (this.perturb.dp ?? 0.5);
      }
      d = this.capD[k] - Math.max(0.3 * mesh, pitch);

      // TWO GAUGES, NOT ONE. The inner foreleg holds the previous turn on this
      // radius; the outer legs are still on the attachment just made, one
      // radius back. So the agent is averaging between "a mesh inward of the
      // last turn here" and "level with where I just was" — and that second
      // term is a low-pass filter running around the web.
      //
      // It is why an orb's outer turns follow the frame and its inner turns are
      // nearly circular, and it is not cosmetic: without it every turn kept the
      // rim's exact shape all the way to the hub, and a rectangular frame
      // produced concentric rectangles with hard corners, which no spider has
      // ever built.
      if (!this.capBreak && this.capPrevD !== undefined) {
        d = d * 0.84 + this.capPrevD * 0.16;
      }
    }
    this.counts.capture++;

    if (d < freeZone) {
      this.capDone[k] = true;
      this.capBreak = true;
      this.capDoneCount++;
      if (this.capDoneCount >= n) return this._finishCapture('reached the free zone');
      return { kind: 'move', pos: this.pos };
    }
    if (this.f.silkUsed > this.bnd.silk) {
      this.ranOut = true;
      return this._finishCapture('silk exhausted');
    }

    this.capD[k] = d;
    this.capPrevD = d;
    this._eatAux(k, d);
    const node = this.radii[k].chain.attachAt(d, 4);
    if (blocked(node.x, node.y, this.bnd.obstacles)) {
      this.capBreak = true;             // silk cannot cross the leaf either
      return { kind: 'move', pos: node };
    }
    this.captureNodes.push({ k, d, node, angle: ang });
    if (this.capBreak) {
      // start a new arc here; nothing to join back to
      this.capBreak = false;
      this.capPrev = node;
      return { kind: 'move', pos: node };
    }
    const th = this.f.thread(this.capPrev, node, 'capture');
    this.capPrev = node;
    return { kind: 'lay', thread: 'capture', a: th.a, b: th.b, pos: node };
  }

  _finishCapture(note) {
    this.captureNote = note;
    return this.enter('finish', note);
  }

  // Eat the handrail behind you.
  _eatAux(k, d) {
    for (const a of this.aux) {
      if (a.cut || a.k !== k) continue;
      if (a.d >= d - 1) { this.f.cut(a.thread, { reclaim: 0.85 }); a.cut = true; }
    }
  }

  // ─── 7. finish ─────────────────────────────────────────────────────────────
  do_finish() {
    const n = this.radii.length;
    if (this.hubTurn === undefined) this.hubTurn = 0;
    if (this.hubTurn < 2 * n && n >= 4) {
      const k = this.hubTurn % n;
      const j = (k + 1) % n;
      const ring = this.body.gauge * (1.6 + 0.9 * Math.floor(this.hubTurn / n));
      const a = this.radii[k].chain.attachAt(ring, 3);
      const b = this.radii[j].chain.attachAt(ring, 3);
      this.hubTurn++;
      if (a === b) return { kind: 'move', pos: a };
      const th = this.f.thread(a, b, 'hub');
      return { kind: 'lay', thread: 'hub', a: th.a, b: th.b, pos: b };
    }
    if (!this.ranOut) {
      for (const a of this.aux) {
        if (!a.cut) { this.f.cut(a.thread, { reclaim: 0.85 }); a.cut = true; }
      }
    }
    this.f.compact();
    return this.enter('done', this.ranOut ? 'stopped short — out of silk' : 'web complete');
  }
}

// Convenience: build one web headlessly.
export function weave(bnd, opts = {}) {
  return new Weaver(bnd, opts).run();
}
